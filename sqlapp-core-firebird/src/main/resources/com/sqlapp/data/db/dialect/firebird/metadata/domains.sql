SELECT
f.*, cs.RDB$CHARACTER_SET_NAME AS CHARACTER_SET_NAME,
co.RDB$COLLATION_NAME AS COLLATION_NAME
FROM RDB$FIELDS f
LEFT JOIN RDB$CHARACTER_SETS cs ON cs.RDB$CHARACTER_SET_ID=f.RDB$CHARACTER_SET_ID
LEFT JOIN RDB$COLLATIONS co ON co.RDB$CHARACTER_SET_ID=f.RDB$CHARACTER_SET_ID AND co.RDB$COLLATION_ID=f.RDB$COLLATION_ID
WHERE 1=1
  /*if readerOptions.excludeSystemObjects */
  AND COALESCE(f.RDB$SYSTEM_FLAG,0)=0 AND f.RDB$FIELD_NAME NOT STARTING WITH 'RDB$'
  /*end*/
  /*if isNotEmpty(domainName) */
  AND f.RDB$FIELD_NAME IN /*domainName*/('%')
  /*end*/
ORDER BY RDB$FIELD_NAME
