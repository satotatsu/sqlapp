SELECT RF.RDB$RELATION_NAME AS TABLE_NAME, RF.RDB$FIELD_NAME AS COLUMN_NAME,
       FD.RDB$DIMENSION AS DIMENSION_NUMBER, FD.RDB$LOWER_BOUND AS LOWER_BOUND,
       FD.RDB$UPPER_BOUND AS UPPER_BOUND
FROM RDB$RELATION_FIELDS RF
JOIN RDB$FIELD_DIMENSIONS FD ON RF.RDB$FIELD_SOURCE=FD.RDB$FIELD_NAME
WHERE 1=1
  /*if isNotEmpty(tableName) */
  AND RF.RDB$RELATION_NAME IN /*tableName*/('%')
  /*end*/
  /*if isNotEmpty(columnName) */
  AND RF.RDB$FIELD_NAME IN /*columnName*/('%')
  /*end*/
ORDER BY RF.RDB$RELATION_NAME, RF.RDB$FIELD_NAME, FD.RDB$DIMENSION
