SELECT d.RDB$FIELD_NAME AS DOMAIN_NAME, d.RDB$DIMENSION AS DIMENSION_NUMBER,
       d.RDB$LOWER_BOUND AS LOWER_BOUND, d.RDB$UPPER_BOUND AS UPPER_BOUND
FROM RDB$FIELD_DIMENSIONS d
WHERE 1=1
  /*if isNotEmpty(domainName) */
  AND d.RDB$FIELD_NAME IN /*domainName*/('%')
  /*end*/
ORDER BY d.RDB$FIELD_NAME, d.RDB$DIMENSION
