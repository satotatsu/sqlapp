SELECT
  fa.RDB$FUNCTION_NAME AS ROUTINE_NAME
, fa.RDB$ARGUMENT_NAME
, fa.RDB$ARGUMENT_POSITION
, fa.RDB$MECHANISM
, fa.RDB$FIELD_SOURCE AS TYPE_DOMAIN
, fa.RDB$ARGUMENT_MECHANISM AS TYPE_MECHANISM
, fa.RDB$RELATION_NAME AS TYPE_RELATION
, fa.RDB$FIELD_NAME AS TYPE_COLUMN
, fa.RDB$DEFAULT_SOURCE AS LOCAL_DEFAULT_SOURCE
, fa.RDB$NULL_FLAG AS LOCAL_NULL_FLAG
, local_col.RDB$COLLATION_NAME AS LOCAL_COLLATION_NAME
, fn.RDB$MODULE_NAME AS MODULE_NAME
, fn.RDB$RETURN_ARGUMENT AS RETURN_POSITION
, fa.RDB$DESCRIPTION AS REMARKS
, COALESCE(fa.RDB$DEFAULT_SOURCE,f.RDB$DEFAULT_SOURCE) AS DEFAULT_SOURCE
, COALESCE(fa.RDB$NULL_FLAG, f.RDB$NULL_FLAG) AS NULL_FLAG
, COALESCE(f.RDB$FIELD_TYPE,fa.RDB$FIELD_TYPE) AS FIELD_TYPE
, COALESCE(f.RDB$FIELD_SUB_TYPE,fa.RDB$FIELD_SUB_TYPE) AS FIELD_SUB_TYPE
, COALESCE(f.RDB$FIELD_LENGTH,fa.RDB$FIELD_LENGTH) AS FIELD_LENGTH
, COALESCE(f.RDB$FIELD_PRECISION,fa.RDB$FIELD_PRECISION) AS FIELD_PRECISION
, COALESCE(f.RDB$FIELD_SCALE,fa.RDB$FIELD_SCALE) AS FIELD_SCALE
, COALESCE(f.RDB$CHARACTER_LENGTH,fa.RDB$CHARACTER_LENGTH) AS CHAR_LEN
, c.RDB$CHARACTER_SET_NAME AS CHARACTER_SET_NAME
, col.RDB$COLLATION_NAME AS COLLATION_NAME
FROM RDB$FUNCTION_ARGUMENTS fa
JOIN RDB$FUNCTIONS fn ON fa.RDB$FUNCTION_NAME=fn.RDB$FUNCTION_NAME AND fn.RDB$PACKAGE_NAME IS NULL
LEFT OUTER JOIN RDB$FIELDS f
  ON (fa.RDB$FIELD_SOURCE = f.RDB$FIELD_NAME)
LEFT OUTER JOIN RDB$CHARACTER_SETS c
  ON (COALESCE(f.RDB$CHARACTER_SET_ID,fa.RDB$CHARACTER_SET_ID) = c.RDB$CHARACTER_SET_ID)
LEFT OUTER JOIN RDB$COLLATIONS col
  ON (COALESCE(fa.RDB$COLLATION_ID,f.RDB$COLLATION_ID) = col.RDB$COLLATION_ID
      AND f.RDB$CHARACTER_SET_ID = col.RDB$CHARACTER_SET_ID)
LEFT JOIN RDB$COLLATIONS local_col
  ON fa.RDB$COLLATION_ID=local_col.RDB$COLLATION_ID
  AND f.RDB$CHARACTER_SET_ID=local_col.RDB$CHARACTER_SET_ID
WHERE 1=1
  /*if isNotEmpty(routineName)*/
  AND fa.RDB$FUNCTION_NAME IN /*routineName*/('%')
  /*end*/
  AND fa.RDB$PACKAGE_NAME IS NULL
ORDER BY fa.RDB$FUNCTION_NAME, fa.RDB$ARGUMENT_POSITION
