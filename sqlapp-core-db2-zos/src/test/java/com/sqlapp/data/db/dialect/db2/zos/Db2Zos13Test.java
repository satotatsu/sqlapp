	static DatabaseMetaData metadata(String product, String version) {
		return proxy(DatabaseMetaData.class, (p, m, a) -> switch (m.getName()) {
		case "getDatabaseProductName" -> product;
		case "getDatabaseProductVersion" -> version;
		case "getDatabaseMajorVersion" -> 13;
		case "getDatabaseMinorVersion" -> 0;
		default -> fallback(m.getReturnType());
		});
	}

	private static Connection connection(AtomicInteger calls, boolean unresolved) {
		return proxy(Connection.class, (p, m, a) -> switch (m.getName()) {
		case "getMetaData" -> metadata("DB2", "DSN13015");
		case "prepareStatement" -> statement((String) a[0], calls, unresolved);
		default -> fallback(m.getReturnType());
		});
	}

	private static PreparedStatement statement(String sql, AtomicInteger calls, boolean unresolved) {
		return proxy(PreparedStatement.class, (p, m, a) -> {
			if (m.getName().equals("executeQuery")) {
				calls.incrementAndGet();
				if (sql.contains("host:indexes") || sql.contains("host:checks"))
					return rows(List.of());
				if (sql.contains("REF_COLUMN_NAME")) {
					var arow = row("SCHEMA_NAME", "APP", "TABLE_NAME", "CHILD", "CONSTRAINT_NAME", "FK", "COLUMN_NAME",
							"A", "REF_SCHEMA_NAME", "OTHER", "REF_TABLE_NAME", "PARENT", "REF_COLUMN_NAME",
							unresolved ? null : "X", "ENFORCED", "Y", "DELETE_RULE", "CASCADE", "UPDATE_RULE",
							"NO ACTION");
					var brow = new LinkedHashMap<>(arow);
					brow.put("COLUMN_NAME", "B");
					brow.put("REF_COLUMN_NAME", unresolved ? null : "Y");
					return rows(List.of(arow, brow));
				}
				if (sql.contains("KEY_TYPE")) {
					var arow = row("SCHEMA_NAME", "APP", "TABLE_NAME", "CHILD", "CONSTRAINT_NAME", "PK", "KEY_TYPE",
							"P", "COLUMN_NAME", "A");
					var brow = new LinkedHashMap<>(arow);
					brow.put("COLUMN_NAME", "B");
					return rows(List.of(arow, brow));
				}
				if (sql.contains("TYPE_NAME")) {
					var values = new ArrayList<Map<String, Object>>();
					for (var table : List.of("CHILD", "SECOND"))
						for (var column : List.of("A", "B"))
							values.add(row("SCHEMA_NAME", "APP", "TABLE_NAME", table, "COLUMN_NAME", column,
									"TYPE_NAME", column.equals("B") ? "VARGRAPH" : "INTEGER", "TYPE_LENGTH", 10L,
									"TYPE_SCALE", 0, "NULLABLE", "N", "REMARKS", null, "UNSUPPORTED_GENERATION", "",
									"DEFAULT_SQL", null, "IDENTITY_MODE",
									table.equals("SECOND") && column.equals("A") ? "D" : "", "IDENTITY_START",
									new java.math.BigDecimal("42"), "IDENTITY_INCREMENT", new java.math.BigDecimal("3"),
									"IDENTITY_MINIMUM", java.math.BigDecimal.ONE, "IDENTITY_MAXIMUM",
									new java.math.BigDecimal("1000"), "IDENTITY_CACHE", 0, "IDENTITY_CYCLE", "N",
									"IDENTITY_ORDER", "Y"));
					return rows(values);
				}
				return rows(List.of(row("SCHEMA_NAME", "APP", "TABLE_NAME", "CHILD", "REMARKS", null),
						row("SCHEMA_NAME", "APP", "TABLE_NAME", "SECOND", "REMARKS", null)));
			}
			return fallback(m.getReturnType());
		});
	}

	static CachedRowSet rows(List<Map<String, Object>> values) throws Exception {
		var rs = RowSetProvider.newFactory().createCachedRowSet();
		var md = new RowSetMetaDataImpl();
		var names = new ArrayList<>((values.isEmpty() ? Map.of("EMPTY", "").keySet() : values.get(0).keySet()));
		md.setColumnCount(names.size());
		for (int i = 0; i < names.size(); i++) {
			md.setColumnName(i + 1, names.get(i));
			md.setColumnLabel(i + 1, names.get(i));
			String column = names.get(i);
			md.setColumnType(i + 1,
					values.stream().anyMatch(row -> row.get(column) instanceof java.sql.Timestamp) ? Types.TIMESTAMP
							: Types.JAVA_OBJECT);
		}
		rs.setMetaData(md);
		for (int n = values.size() - 1; n >= 0; n--) {
			rs.moveToInsertRow();
			for (int i = 0; i < names.size(); i++)
				rs.updateObject(i + 1, values.get(n).get(names.get(i)));
			rs.insertRow();
			rs.moveToCurrentRow();
		}
		rs.beforeFirst();
		return rs;
	}

	static Map<String, Object> row(Object... pairs) {
		var row = new LinkedHashMap<String, Object>();
		for (int i = 0; i < pairs.length; i += 2)
			row.put((String) pairs[i], pairs[i + 1]);
		return row;
	}

	static <T> T proxy(Class<T> type, java.lang.reflect.InvocationHandler handler) {
		return type.cast(Proxy.newProxyInstance(type.getClassLoader(), new Class<?>[] { type }, handler));
	}

	static Object fallback(Class<?> type) {
		if (type == boolean.class)
			return false;
		if (type == int.class)
			return 0;
		if (type == long.class)
			return 0L;
		return null;
	}
