	@Test
	void resolvesHostSeparatelyFromLuwAndChecksVersion() {
		var resolver = new Db2Zos13DialectResolver();
		assertInstanceOf(Db2Zos13.class, resolver.getDialect("Db2 for z/OS", 13, 0));
		assertNull(new Db2DialectResolver().getDialect("Db2 for z/OS", 13, 0));
		assertThrows(IllegalArgumentException.class, () -> resolver.getDialect("Db2 for z/OS", 1, 0));
		assertInstanceOf(Db2Zos13.class, DialectResolver.getInstance().getDialect(metadata("DB2", "DSN13015")));
		assertFalse(new Db2SetBasedMigrationSnapshotProvider().supports(new Db2Zos13()));
	}

	@Test
	void createsQuotedTablesCompositeKeysAndIdentity() {
		var dialect = new Db2Zos13();
		var table = new Table("Order");
		table.setSchemaName("App");
		table.getColumns().add(new Column("Id").setDataType(DataType.BIGINT).setNotNull(true).setIdentity(true)
				.setIdentityGenerationType(IdentityGenerationType.ByDefault));
		table.getColumns()
				.add(new Column("Code").setDataType(DataType.VARCHAR).setLength(20).setDefaultValue("'O''Brien'"));
		table.getConstraints().addPrimaryKeyConstraint("PK_Order", "Id", "Code");
		var sql = dialect.createSqlFactoryRegistry().createSql(table, SqlType.CREATE).get(0).getSqlText();
		assertTrue(sql.contains("\"Order\""), sql);
		assertTrue(sql.contains("GENERATED BY DEFAULT AS IDENTITY"), sql);
		assertTrue(sql.contains("PRIMARY KEY"), sql);
		assertTrue(sql.contains("'O''Brien'"), sql);
		assertEquals("\"a\"\"b\"", dialect.quote("a\"b"));
		table.setTableSpaceName("UNSUPPORTED");
		assertThrows(IllegalArgumentException.class,
				() -> dialect.createSqlFactoryRegistry().createSql(table, SqlType.CREATE));
	}

	@Test
	void readsMultipleTablesAndOrderedKeysInSixQueriesAndRecreates() throws Exception {
		var calls = new AtomicInteger();
		var connection = connection(calls, false);
		var reader = new Db2Zos13().getCatalogReader().getSchemaReader().getTableReader();
		reader.setSchemaName("APP");
		var tables = reader.getAllFull(connection);
		assertEquals(6, calls.get(),
				"one query each for tables, columns, indexes, checks, unique keys and foreign keys");
		assertEquals(2, tables.size());
		var second = tables.stream().filter(t -> t.getName().equals("SECOND")).findFirst().orElseThrow();
		assertTrue(second.getColumns().get("A").isIdentity());
		assertEquals(IdentityGenerationType.ByDefault, second.getColumns().get("A").getIdentityGenerationType());
		assertEquals(java.math.BigInteger.valueOf(42), second.getColumns().get("A").getSequence().getStartValue());
		assertEquals(DataType.NVARCHAR, second.getColumns().get("B").getDataType());
		var child = tables.stream().filter(t -> t.getName().equals("CHILD")).findFirst().orElseThrow();
		assertEquals(List.of("A", "B"), child.getColumns().stream().map(Column::getName).toList());
		assertEquals(List.of("A", "B"),
				child.getConstraints().getPrimaryKeyConstraint().getColumns().stream().map(c -> c.getName()).toList());
		var fk = child.getConstraints().getForeignKeyConstraints().get(0);
		assertEquals("OTHER", fk.getRelatedTable().getSchemaName());
		assertEquals(List.of("X", "Y"), fk.getRelatedColumns().stream().map(c -> c.getName()).toList());
		var sql = new Db2Zos13().createSqlFactoryRegistry().createSql(child, SqlType.CREATE).stream()
				.map(op -> op.getSqlText()).reduce("", (a, b) -> a + "\n" + b);
		assertTrue(sql.contains("FOREIGN KEY"), sql);
		assertTrue(sql.contains("ON DELETE CASCADE"), sql);
		assertTrue(sql.contains("REFERENCES \"OTHER\".\"PARENT\""), sql);
		assertFalse(sql.contains("ON UPDATE NONE"), sql);
	}

	@Test
	void preservesProductTypeLimitsAndExactIdentityOptions() {
		var dialect = new Db2Zos13();
		var table = new Table("T");
		table.getColumns().add(new Column("C").setDataType(DataType.CHAR).setLength(255));
		table.getColumns().add(new Column("N").setDataType(DataType.DECIMAL).setLength(31).setScale(2));
		var id = new Column("ID").setDataType(DataType.DECIMAL).setLength(31).setScale(0).setNotNull(true)
				.setIdentity(true);
		var sequence = new Sequence();
		sequence.setStartValue(new java.math.BigInteger("9223372036854775808"));
		sequence.setIncrementBy(java.math.BigInteger.ONE);
		id.setSequence(sequence);
		id.setIdentityCacheSize(0);
		table.getColumns().add(id);
		var sql = dialect.createSqlFactoryRegistry().createSql(table, SqlType.CREATE).get(0).getSqlText();
		assertTrue(sql.contains("CHAR(255)"), sql);
		assertTrue(sql.contains("DECIMAL(31, 2)") || sql.contains("DECIMAL(31,2)"), sql);
		assertTrue(sql.contains("START WITH 9223372036854775808"), sql);
		assertTrue(sql.contains("NO CACHE"), sql);
		table.getColumns().get("N").setLength(32);
		assertThrows(IllegalArgumentException.class,
				() -> dialect.createSqlFactoryRegistry().createSql(table, SqlType.CREATE));
	}

