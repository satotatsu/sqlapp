/* host:variables */
SELECT v.SCHEMA AS SCHEMA_NAME, v.NAME AS VARIABLE_NAME,
 CASE WHEN v.TYPESCHEMA='SYSIBM' THEN NULL ELSE v.TYPESCHEMA END AS UDT_SCHEMA,
 CASE WHEN v.TYPESCHEMA='SYSIBM' THEN NULL ELSE v.TYPENAME END AS UDT_NAME,
 CASE WHEN v.TYPESCHEMA<>'SYSIBM' THEN NULL
  WHEN v.TYPENAME='FLOAT' THEN CASE v.LENGTH WHEN 4 THEN 'REAL' ELSE 'DOUBLE' END
  ELSE RTRIM(v.TYPENAME) END AS TYPE_NAME,
 CASE WHEN v.TYPENAME IN ('TIMESTAMP','TIMESTMP') THEN v.SCALE ELSE v.LENGTH END AS TYPE_LENGTH,
 v.SCALE AS TYPE_SCALE, v.CCSID AS VARIABLE_CCSID,
 CASE RTRIM(v.DEFAULT)
  WHEN '2' THEN v.DEFAULTTEXT WHEN '3' THEN v.DEFAULTTEXT WHEN '4' THEN v.DEFAULTTEXT WHEN '9' THEN v.DEFAULTTEXT
  WHEN 'S' THEN 'CURRENT SQLID' WHEN 'U' THEN 'SESSION_USER'
  WHEN 'AES' THEN 'CURRENT APPLICATION ENCODING SCHEME' WHEN 'ACT' THEN 'CURRENT CLIENT_ACCTNG'
  WHEN 'APN' THEN 'CURRENT CLIENT_APPLNAME' WHEN 'CID' THEN 'CURRENT CLIENT_USERID'
  WHEN 'WSN' THEN 'CURRENT CLIENT_WRKSTNNAME' WHEN 'DAT' THEN 'CURRENT DATE'
  WHEN 'DBG' THEN 'CURRENT DEBUG MODE' WHEN 'DEC' THEN 'CURRENT DECFLOAT ROUNDING MODE'
  WHEN 'DEG' THEN 'CURRENT DEGREE' WHEN 'EXP' THEN 'CURRENT EXPLAIN MODE'
  WHEN 'LCT' THEN 'CURRENT LOCALE LC_CTYPE' WHEN 'MTT' THEN 'CURRENT MAINTAINED TABLE TYPES FOR OPTIMIZATION'
  WHEN 'MEM' THEN 'CURRENT MEMBER' WHEN 'HNT' THEN 'CURRENT OPTIMIZATION HINT'
  WHEN 'CPP' THEN 'CURRENT PACKAGE PATH' WHEN 'CPS' THEN 'CURRENT PACKAGESET'
  WHEN 'PTH' THEN 'CURRENT PATH' WHEN 'PRC' THEN 'CURRENT PRECISION'
  WHEN 'RFA' THEN 'CURRENT REFRESH AGE' WHEN 'RVS' THEN 'CURRENT ROUTINE VERSION'
  WHEN 'RUL' THEN 'CURRENT RULES' WHEN 'SCH' THEN 'CURRENT SCHEMA'
  WHEN 'SVR' THEN 'CURRENT SERVER' WHEN 'TIM' THEN 'CURRENT TIME'
  WHEN 'TST' THEN 'CURRENT TIMESTAMP' WHEN 'STZ' THEN 'SESSION TIME ZONE'
  ELSE NULL END AS DEFAULT_SQL,
 CASE WHEN RTRIM(v.DEFAULT) IN ('1','5','6','7','8') THEN 'STRING CONSTANT DEFAULT'
  WHEN RTRIM(v.DEFAULT) IN ('N','2','3','4','9','S','U','AES','ACT','APN','CID','WSN','DAT','DBG','DEC','DEG',
   'EXP','LCT','MTT','MEM','HNT','CPP','CPS','PTH','PRC','RFA','RVS','RUL','SCH','SVR','TIM','TST','STZ') THEN ''
  ELSE 'DEFAULT ' || RTRIM(v.DEFAULT) END AS UNSUPPORTED_VARIABLE,
 v.REMARKS, v.CREATEDTS AS CREATED_AT
FROM SYSIBM.SYSVARIABLES v WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(v.SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(constantName)*/
 AND RTRIM(v.NAME) IN /*constantName*/('%')
/*end*/
ORDER BY v.SCHEMA, v.NAME
