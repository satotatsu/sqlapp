SELECT t.SCHEMA AS SCHEMA_NAME, t.NAME AS TRIGGER_NAME, t.TBOWNER AS TABLE_SCHEMA, t.TBNAME AS TABLE_NAME,
 t.STATEMENT AS TRIGGER_TEXT, 'D' AS TEXT_KIND,
 CASE t.TRIGTIME WHEN 'B' THEN 'BEFORE' WHEN 'A' THEN 'AFTER' WHEN 'I' THEN 'INSTEAD OF' ELSE t.TRIGTIME END AS ACTION_TIMING,
 CASE t.GRANULARITY WHEN 'R' THEN 'ROW' WHEN 'S' THEN 'STATEMENT' ELSE t.GRANULARITY END AS ACTION_ORIENTATION,
 CASE t.TRIGEVENT WHEN 'I' THEN 'INSERT' WHEN 'U' THEN 'UPDATE' WHEN 'D' THEN 'DELETE' ELSE t.TRIGEVENT END AS EVENT_NAMES,
 CAST(NULL AS VARCHAR(128)) AS OLD_ROW, CAST(NULL AS VARCHAR(128)) AS NEW_ROW,
 CAST(NULL AS VARCHAR(128)) AS OLD_TABLE, CAST(NULL AS VARCHAR(128)) AS NEW_TABLE,
 CAST(NULL AS VARCHAR(2048)) AS SQL_PATH, CAST(NULL AS VARCHAR(2048)) AS WHEN_TEXT,
 CAST(NULL AS VARCHAR(10)) AS TRIGGER_MODE, CAST(NULL AS VARCHAR(10)) AS ACTION_ORDER,
 t.VERSION AS NATIVE_VERSION, 'Y' AS ENABLED_FLAG, t.CREATEDTS AS CREATED_AT, t.REMARKS
FROM SYSIBM.SYSTRIGGERS t WHERE t.ACTIVE IN ('Y',' ')

/*if isNotEmpty(schemaName)*/
 AND RTRIM(t.SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(triggerName)*/
 AND RTRIM(t.NAME) IN /*triggerName*/('%')
/*end*/
ORDER BY t.CREATEDTS,t.SCHEMA,t.NAME
