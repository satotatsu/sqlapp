SELECT c.TBCREATOR AS SCHEMA_NAME, c.TBNAME AS TABLE_NAME, c.CONSTNAME AS CONSTRAINT_NAME,
 c.TYPE AS KEY_TYPE, k.COLNAME AS COLUMN_NAME
FROM SYSIBM.SYSTABCONST c JOIN SYSIBM.SYSKEYCOLUSE k
 ON k.TBCREATOR=c.TBCREATOR AND k.TBNAME=c.TBNAME AND k.CONSTNAME=c.CONSTNAME
WHERE c.TYPE IN ('P','U')
/*if isNotEmpty(schemaName)*/
 AND RTRIM(c.TBCREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(c.TBNAME) IN /*tableName*/('%')
/*end*/
ORDER BY c.TBCREATOR, c.TBNAME, c.CONSTNAME, k.COLSEQ
