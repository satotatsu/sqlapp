SELECT c.SCHEMA AS SCHEMA_NAME, c.NAME AS CONTROL_NAME, c.TBSCHEMA AS TABLE_SCHEMA, c.TBNAME AS TABLE_NAME,
 c.TBCORRELATION AS CORRELATION_NAME, c.COLNAME AS COLUMN_NAME, c.ENABLE AS ENABLE_FLAG,
 CASE WHEN c.STATUS=' ' THEN 'Y' ELSE 'N' END AS VALID_FLAG, c.RULETEXT, c.REMARKS
FROM SYSIBM.SYSCONTROLS c
WHERE c.CONTROL_TYPE='M'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(c.SCHEMA) IN /*schemaName*/('%')
/*end*/
ORDER BY c.SCHEMA, c.NAME
