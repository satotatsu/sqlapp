SELECT i.TBCREATOR AS SCHEMA_NAME, i.TBNAME AS TABLE_NAME, i.CREATOR AS INDEX_SCHEMA, i.NAME AS INDEX_NAME,
 CASE i.UNIQUERULE WHEN 'D' THEN 'N' ELSE 'Y' END AS UNIQUE_FLAG,
 i.COLCOUNT AS KEY_COUNT, k.COLSEQ AS KEY_POSITION, k.COLNAME AS COLUMN_NAME, k.ORDERING AS COLUMN_ORDER, i.REMARKS,
 CASE WHEN i.UNIQUERULE NOT IN ('D','U','R') THEN 'SPECIAL UNIQUENESS'
 WHEN i.KEYTARGET_COUNT<>0 OR i.IX_EXTENSION_TYPE<>' ' THEN 'EXTENDED INDEX'
 WHEN i.INDEXTYPE NOT IN ('2',' ') THEN 'PARTITIONED INDEX' ELSE '' END AS UNSUPPORTED_INDEX
FROM SYSIBM.SYSINDEXES i LEFT JOIN SYSIBM.SYSKEYS k ON k.IXCREATOR=i.CREATOR AND k.IXNAME=i.NAME
WHERE NOT EXISTS (SELECT 1 FROM SYSIBM.SYSTABCONST c WHERE c.TBCREATOR=i.TBCREATOR AND c.TBNAME=i.TBNAME
 AND c.IXOWNER=i.CREATOR AND c.IXNAME=i.NAME AND c.TYPE IN ('P','U'))
 AND i.IMPLICIT<>'Y'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(i.TBCREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(i.TBNAME) IN /*tableName*/('%')
/*end*/
ORDER BY i.TBCREATOR,i.TBNAME,i.CREATOR,i.NAME,k.COLSEQ
