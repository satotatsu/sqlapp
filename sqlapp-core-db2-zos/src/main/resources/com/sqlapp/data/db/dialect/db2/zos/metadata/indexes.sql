SELECT i.TBCREATOR AS SCHEMA_NAME, i.TBNAME AS TABLE_NAME, i.CREATOR AS INDEX_SCHEMA, i.NAME AS INDEX_NAME,
 CASE i.UNIQUERULE WHEN 'D' THEN 'N' ELSE 'Y' END AS UNIQUE_FLAG,
 CASE i.UNIQUERULE WHEN 'N' THEN 'Y' ELSE 'N' END AS UNIQUE_WHERE_NOT_NULL,
 CASE WHEN i.KEYTARGET_COUNT>0 THEN i.KEYTARGET_COUNT ELSE i.COLCOUNT END AS KEY_COUNT,
 k.KEY_POSITION, k.COLUMN_NAME, k.COLUMN_ORDER, k.KEY_EXPRESSION, k.PERIOD AS KEY_PERIOD,
 CASE WHEN i.UNIQUE_COUNT>0 AND k.KEY_POSITION>i.UNIQUE_COUNT THEN 'Y' ELSE 'N' END AS KEY_INCLUDE,
 i.CLUSTERING AS CLUSTER_FLAG,
 CASE WHEN i.INDEXTYPE IN ('D','P') THEN 'Y' ELSE 'N' END AS PARTITIONED_FLAG,
 i.REMARKS,
 CASE WHEN i.UNIQUERULE NOT IN ('D','U','R','N') THEN 'SPECIAL UNIQUENESS'
 WHEN i.IX_EXTENSION_TYPE<>' ' THEN 'EXTENDED INDEX'
 WHEN i.INDEXTYPE='P' AND t.PARTKEYCOLNUM=0 THEN 'INDEX-CONTROLLED PARTITIONING'
 WHEN i.INDEXTYPE NOT IN ('2',' ','D','P') THEN 'INDEX TYPE ' || i.INDEXTYPE ELSE '' END AS UNSUPPORTED_INDEX
FROM SYSIBM.SYSINDEXES i
JOIN SYSIBM.SYSTABLES t ON t.CREATOR=i.TBCREATOR AND t.NAME=i.TBNAME
LEFT JOIN (
 SELECT x.IXCREATOR AS IXSCHEMA, x.IXNAME, x.COLSEQ AS KEY_POSITION, x.COLNAME AS COLUMN_NAME,
  x.ORDERING AS COLUMN_ORDER, CAST(NULL AS VARCHAR(4000)) AS KEY_EXPRESSION, x.PERIOD, 'C' AS KEY_SOURCE
 FROM SYSIBM.SYSKEYS x
 UNION ALL
 SELECT e.IXSCHEMA, e.IXNAME, e.KEYSEQ, CAST(NULL AS VARCHAR(128)), e.ORDERING, e.DERIVED_FROM, ' ', 'T'
 FROM SYSIBM.SYSKEYTARGETS e
) k ON k.IXSCHEMA=i.CREATOR AND k.IXNAME=i.NAME
 AND k.KEY_SOURCE=CASE WHEN i.KEYTARGET_COUNT>0 THEN 'T' ELSE 'C' END
WHERE NOT EXISTS (SELECT 1 FROM SYSIBM.SYSTABCONST c WHERE c.TBCREATOR=i.TBCREATOR AND c.TBNAME=i.TBNAME
 AND c.IXOWNER=i.CREATOR AND c.IXNAME=i.NAME AND c.TYPE IN ('P','U'))
 AND i.IMPLICIT<>'Y'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(i.TBCREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(i.TBNAME) IN /*tableName*/('%')
/*end*/
ORDER BY i.TBCREATOR,i.TBNAME,i.CREATOR,i.NAME,k.KEY_POSITION
