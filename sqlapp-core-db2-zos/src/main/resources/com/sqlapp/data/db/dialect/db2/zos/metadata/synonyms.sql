SELECT * FROM (
 SELECT t.CREATOR AS SCHEMA_NAME, t.NAME AS SYNONYM_NAME, t.TBCREATOR AS TARGET_SCHEMA,
 t.TBNAME AS TARGET_NAME, NULLIF(RTRIM(t.LOCATION),'') AS TARGET_LOCATION,
 'TABLE' AS ALIAS_TYPE, 'ALIAS' AS NAME_KIND,
 CAST(NULL AS VARCHAR(10)) AS MEMBER_NAME, CAST(NULL AS VARCHAR(128)) AS BASE_CATALOG,
 t.CREATEDTS AS CREATED_AT, t.ALTEREDTS AS ALTERED_AT, t.REMARKS
 FROM SYSIBM.SYSTABLES t WHERE t.TYPE='A'
 UNION ALL
 SELECT s.SCHEMA, s.NAME, s.SEQSCHEMA, s.SEQNAME, CAST(NULL AS VARCHAR(128)),
 'SEQUENCE', 'ALIAS', CAST(NULL AS VARCHAR(10)), CAST(NULL AS VARCHAR(128)),
 s.CREATEDTS, s.ALTEREDTS, s.REMARKS
 FROM SYSIBM.SYSSEQUENCES s WHERE s.SEQTYPE='A'
 UNION ALL
 SELECT s.CREATOR, s.NAME, s.TBCREATOR, s.TBNAME, CAST(NULL AS VARCHAR(128)),
 'TABLE', 'SYNONYM', CAST(NULL AS VARCHAR(10)), CAST(NULL AS VARCHAR(128)),
 s.CREATEDTS, CAST(NULL AS TIMESTAMP), CAST(NULL AS VARCHAR(762))
 FROM SYSIBM.SYSSYNONYMS s
) a WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(a.SCHEMA_NAME) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(synonymName)*/
 AND RTRIM(a.SYNONYM_NAME) IN /*synonymName*/('%')
/*end*/
ORDER BY a.SCHEMA_NAME,a.SYNONYM_NAME
