WITH names AS (
 SELECT r.SCHEMA, r.SPECIFICNAME, r.ROUTINETYPE, MIN(r.NAME) AS ROUTINE_NAME,
 COUNT(DISTINCT r.NAME) AS NAME_COUNT
 FROM SYSIBM.SYSROUTINES r GROUP BY r.SCHEMA,r.SPECIFICNAME,r.ROUTINETYPE
)
SELECT a.SCHEMA AS SCHEMA_NAME, COALESCE(n.ROUTINE_NAME,a.SPECIFICNAME) AS OBJECT_NAME,
 a.SPECIFICNAME AS SPECIFIC_NAME, a.ROUTINETYPE AS ROUTINE_KIND,
 a.GRANTOR AS GRANTOR_NAME, a.GRANTEE AS GRANTEE_NAME, 'EXECUTE' AS PRIVILEGE_NAME,
 CASE a.EXECUTEAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE, CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST,
 CASE WHEN a.SPECIFICNAME='*' OR n.NAME_COUNT=1 THEN 'Y' ELSE 'N' END AS RESOLVED_FLAG,
 a.COLLID AS PACKAGE_COLLECTION, HEX(a.CONTOKEN) AS PACKAGE_TOKEN, a.AUTHHOWGOT
FROM SYSIBM.SYSROUTINEAUTH a LEFT JOIN names n ON n.SCHEMA=a.SCHEMA
 AND n.SPECIFICNAME=a.SPECIFICNAME AND n.ROUTINETYPE=a.ROUTINETYPE
WHERE 1=1
/*if isNotEmpty(schemaName)*/ AND RTRIM(a.SCHEMA) IN /*schemaName*/('%') /*end*/
/*if isNotEmpty(objectName)*/ AND RTRIM(COALESCE(n.ROUTINE_NAME,a.SPECIFICNAME)) IN /*objectName*/('%') /*end*/
ORDER BY a.SCHEMA,a.ROUTINETYPE,a.SPECIFICNAME,a.GRANTEE,a.GRANTOR
