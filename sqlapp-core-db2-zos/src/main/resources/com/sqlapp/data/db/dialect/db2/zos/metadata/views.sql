SELECT v.CREATOR AS SCHEMA_NAME, v.NAME AS TABLE_NAME, v.STATEMENT AS VIEW_TEXT,
 'D' AS TEXT_KIND, v.CHECK AS CHECK_OPTION, v.PATHSCHEMAS AS SQL_PATH, t.REMARKS
FROM SYSIBM.SYSVIEWS v JOIN SYSIBM.SYSTABLES t ON t.CREATOR=v.CREATOR AND t.NAME=v.NAME
WHERE v.TYPE='V'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(v.CREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(v.NAME) IN /*tableName*/('%')
/*end*/
ORDER BY v.CREATOR,v.NAME
