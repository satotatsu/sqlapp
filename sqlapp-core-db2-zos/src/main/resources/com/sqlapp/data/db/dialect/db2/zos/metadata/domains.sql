SELECT t.SCHEMA AS SCHEMA_NAME, t.NAME AS DOMAIN_NAME, t.METATYPE,
 t.SOURCESCHEMA AS SOURCE_SCHEMA, t.SOURCETYPE AS SOURCE_TYPE,
 CAST(NULL AS CHAR(1)) AS TYPE_RULES, t.LENGTH AS NATIVE_LENGTH, t.LENGTH AS TYPE_LENGTH,
 CASE WHEN t.SOURCETYPE='TIMESTAMP' AND t.LENGTH=10 AND t.SCALE=0 THEN 6 ELSE t.SCALE END AS TYPE_SCALE,
 CAST(NULL AS INTEGER) AS CCSID, CAST(NULL AS VARCHAR(3)) AS NORMALIZE_DATA,
 t.ARRAYLENGTH AS ARRAY_CARDINALITY, t.SUBTYPE, t.ENCODING_SCHEME,
 t.ARRAYINDEXTYPEID AS ARRAY_INDEX_TYPE, t.ARRAYINDEXTYPELEN AS ARRAY_INDEX_LENGTH,
 t.ARRAYINDEXSUBTYPE AS ARRAY_INDEX_SUBTYPE, t.INLINE_LENGTH,
 t.CREATEDTS AS CREATED_AT, t.REMARKS
FROM SYSIBM.SYSDATATYPES t WHERE 1=1
/*if isNotEmpty(schemaName)*/ AND RTRIM(t.SCHEMA) IN /*schemaName*/('%') /*end*/
/*if isNotEmpty(domainName)*/ AND RTRIM(t.NAME) IN /*domainName*/('%') /*end*/
ORDER BY t.SCHEMA,t.NAME
