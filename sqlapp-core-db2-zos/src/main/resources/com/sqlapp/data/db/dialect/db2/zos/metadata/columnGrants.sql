SELECT a.CREATOR AS SCHEMA_NAME, a.TNAME AS OBJECT_NAME, a.COLNAME AS COLUMN_NAME,
 a.GRANTOR AS GRANTOR_NAME, a.GRANTEE AS GRANTEE_NAME,
 CASE a.PRIVILEGE WHEN 'R' THEN 'REFERENCES' WHEN ' ' THEN 'UPDATE' ELSE a.PRIVILEGE END AS PRIVILEGE_NAME,
 '?' AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE, CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM SYSIBM.SYSCOLAUTH a WHERE 1=1
/*if isNotEmpty(columnName)*/ AND RTRIM(a.COLNAME) IN /*columnName*/('%') /*end*/
/*if isNotEmpty(schemaName)*/
 AND RTRIM(a.CREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(a.TNAME) IN /*tableName*/('%')
/*end*/
ORDER BY a.CREATOR,a.TNAME,a.COLNAME,a.GRANTEE,a.PRIVILEGE
