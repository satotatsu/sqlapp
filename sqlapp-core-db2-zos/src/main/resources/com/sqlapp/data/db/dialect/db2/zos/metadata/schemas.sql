SELECT DISTINCT s.OBJECT_SCHEMA AS SCHEMA_NAME
FROM (SELECT CREATOR AS OBJECT_SCHEMA FROM SYSIBM.SYSTABLES WHERE TYPE IN ('T','H','V','A')
 UNION SELECT SCHEMA AS OBJECT_SCHEMA FROM SYSIBM.SYSSEQUENCES WHERE SEQTYPE IN ('S','A')
 UNION SELECT CREATOR AS OBJECT_SCHEMA FROM SYSIBM.SYSSYNONYMS
 UNION SELECT SCHEMA AS OBJECT_SCHEMA FROM SYSIBM.SYSDATATYPES
 UNION SELECT SCHEMA AS OBJECT_SCHEMA FROM SYSIBM.SYSROUTINES WHERE SYSTEM_DEFINED=' ' AND ACTIVE IN ('Y',' ')
 UNION SELECT SCHEMA AS OBJECT_SCHEMA FROM SYSIBM.SYSTRIGGERS WHERE ACTIVE IN ('Y',' ')) s
WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(s.OBJECT_SCHEMA) IN /*schemaName*/('%')
/*end*/
ORDER BY s.OBJECT_SCHEMA
