/* host:sequences */
SELECT s.SCHEMA AS SCHEMA_NAME, s.NAME AS SEQUENCE_NAME, CAST(NULL AS VARCHAR(128)) AS SEQUENCE_TYPE,
 s.PRECISION AS TYPE_PRECISION, VARCHAR(s.DATATYPEID) AS NATIVE_TYPE_ID,
 s.START AS START_VALUE, s.INCREMENT AS INCREMENT_VALUE, s.MINVALUE AS MINIMUM_VALUE, s.MAXVALUE AS MAXIMUM_VALUE,
 s.CYCLE AS CYCLE_FLAG, s.ORDER AS ORDER_FLAG, s.CACHE AS CACHE_SIZE, s.REMARKS
FROM SYSIBM.SYSSEQUENCES s WHERE s.SEQTYPE='S'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(s.SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(sequenceName)*/
 AND RTRIM(s.NAME) IN /*sequenceName*/('%')
/*end*/
ORDER BY s.SCHEMA,s.NAME
