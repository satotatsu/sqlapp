SELECT c.TBCREATOR AS SCHEMA_NAME, c.TBNAME AS TABLE_NAME, c.NAME AS COLUMN_NAME,
 CASE WHEN c.COLTYPE='TIMESTMP' THEN 'TIMESTAMP' WHEN c.COLTYPE='FLOAT' THEN CASE c.LENGTH WHEN 4 THEN 'REAL' ELSE 'DOUBLE' END ELSE RTRIM(c.COLTYPE) END AS TYPE_NAME, c.LENGTH AS TYPE_LENGTH, c.SCALE AS TYPE_SCALE,
 CASE WHEN c.COLTYPE='DISTINCT' THEN c.TYPESCHEMA ELSE NULL END AS UDT_SCHEMA,
 CASE WHEN c.COLTYPE='DISTINCT' THEN c.TYPENAME ELSE NULL END AS UDT_NAME,
 CASE WHEN c.COLTYPE='DISTINCT' AND c.DEFAULT IN ('1','2','3','4','5','6','7','8','9','S','U') THEN 'Y' ELSE 'N' END AS UDT_DEFAULT_CAST,
 c.NULLS AS NULLABLE, c.REMARKS,
 CASE c.DEFAULT
  WHEN '1' THEN CASE WHEN c.COLTYPE IN ('GRAPHIC','VARGRAPH','DBCLOB') OR (c.COLTYPE='DISTINCT' AND dt.SOURCETYPE IN ('GRAPHIC','VARGRAPHIC','DBCLOB')) THEN 'G' ELSE '' END || '''' || REPLACE(c.DEFAULTVALUE, '''', '''''') || ''''
  WHEN '2' THEN c.DEFAULTVALUE WHEN '3' THEN c.DEFAULTVALUE WHEN '4' THEN c.DEFAULTVALUE
  WHEN '5' THEN 'X''' || c.DEFAULTVALUE || '''' WHEN '6' THEN 'UX''' || c.DEFAULTVALUE || ''''
  WHEN '7' THEN 'G''' || REPLACE(c.DEFAULTVALUE, '''', '''''') || ''''
  WHEN '8' THEN 'G''' || REPLACE(c.DEFAULTVALUE, '''', '''''') || ''''
  WHEN '9' THEN c.DEFAULTVALUE WHEN 'S' THEN 'CURRENT SQLID' WHEN 'U' THEN 'SESSION_USER'
  WHEN 'Y' THEN CASE WHEN c.NULLS='Y' THEN 'NULL'
    WHEN c.COLTYPE IN ('SMALLINT','INTEGER','BIGINT','DECIMAL','FLOAT','DECFLOAT') THEN '0'
    WHEN c.COLTYPE='DATE' THEN 'CURRENT DATE' WHEN c.COLTYPE='TIME' THEN 'CURRENT TIME'
    WHEN c.COLTYPE='TIMESTMP' THEN 'CURRENT TIMESTAMP'
    WHEN c.COLTYPE='BINARY' THEN 'X''00''' WHEN c.COLTYPE='VARBIN' THEN 'X'''''
    WHEN c.COLTYPE IN ('VARCHAR','VARGRAPH','CLOB','DBCLOB') THEN ''''''
    ELSE ''' ''' END ELSE CAST(NULL AS VARCHAR(1536)) END AS DEFAULT_SQL,
 CASE c.DEFAULT WHEN 'I' THEN 'A' WHEN 'J' THEN 'D' ELSE '' END AS IDENTITY_MODE,
 CASE WHEN c.COLTYPE='DISTINCT' AND c.DEFAULT='Y' AND c.NULLS='N' THEN 'DISTINCT IMPLICIT DEFAULT'
 WHEN c.DEFAULT IN ('N','I','J','1','2','3','4','5','6','7','8','9','S','U','Y') THEN '' ELSE c.DEFAULT END AS UNSUPPORTED_GENERATION,
 s.START AS IDENTITY_START, s.INCREMENT AS IDENTITY_INCREMENT,
 s.MINVALUE AS IDENTITY_MINIMUM, s.MAXVALUE AS IDENTITY_MAXIMUM,
 s.CYCLE AS IDENTITY_CYCLE, s.CACHE AS IDENTITY_CACHE, s.ORDER AS IDENTITY_ORDER
FROM SYSIBM.SYSCOLUMNS c
LEFT JOIN SYSIBM.SYSDATATYPES dt ON c.COLTYPE='DISTINCT' AND dt.SCHEMA=c.TYPESCHEMA AND dt.NAME=c.TYPENAME
LEFT JOIN SYSIBM.SYSSEQUENCESDEP d ON d.DSCHEMA=c.TBCREATOR AND d.DNAME=c.TBNAME AND d.DCOLNAME=c.NAME AND d.DTYPE IN ('I',' ')
LEFT JOIN SYSIBM.SYSSEQUENCES s ON s.SEQUENCEID=d.BSEQUENCEID
WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(c.TBCREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(c.TBNAME) IN /*tableName*/('%')
/*end*/
ORDER BY c.TBCREATOR, c.TBNAME, c.COLNO
