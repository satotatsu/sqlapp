SELECT t.CREATOR AS SCHEMA_NAME, t.NAME AS TABLE_NAME, t.REMARKS, t.TYPE AS TABLE_KIND,
 t.DBNAME AS TS_DATABASE, t.TSNAME AS TS_NAME,
 COALESCE(s.IMPLICIT, 'N') AS TS_IMPLICIT, COALESCE(d.IMPLICIT, 'N') AS DB_IMPLICIT,
 t.ENCODING_SCHEME, t.PARTKEYCOLNUM AS PARTITION_KEY_COUNT,
 CASE WHEN t.TYPE='T' THEN t.VERSIONING_SCHEMA ELSE '' END AS HISTORY_SCHEMA,
 CASE WHEN t.TYPE='T' THEN t.VERSIONING_TABLE ELSE '' END AS HISTORY_TABLE,
 CASE WHEN t.CLUSTERRID=1 THEN 'Y' ELSE 'N' END AS VERSIONING_EXTRA_ROW,
 t.CONTROL AS ACCESS_CONTROL,
 CASE WHEN p.LOGICAL_PART>0 THEN p.LOGICAL_PART ELSE p.PARTITION END AS PARTITION_NUMBER,
 p.LIMITKEY AS PARTITION_HIGH_VALUE,
 CASE WHEN t.ENCODING_SCHEME NOT IN ('E','A','U') THEN 'ENCODING SCHEME ' || t.ENCODING_SCHEME
 ELSE '' END AS UNSUPPORTED_TABLE
FROM SYSIBM.SYSTABLES t
LEFT JOIN SYSIBM.SYSTABLESPACE s ON s.DBNAME=t.DBNAME AND s.NAME=t.TSNAME
LEFT JOIN SYSIBM.SYSDATABASE d ON d.NAME=t.DBNAME
LEFT JOIN SYSIBM.SYSTABLEPART p ON t.PARTKEYCOLNUM>0 AND p.DBNAME=t.DBNAME AND p.TSNAME=t.TSNAME
WHERE t.TYPE IN ('T','H')
/*if isNotEmpty(schemaName)*/
 AND RTRIM(t.CREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(t.NAME) IN /*tableName*/('%')
/*end*/
ORDER BY t.CREATOR, t.NAME, PARTITION_NUMBER
