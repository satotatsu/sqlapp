/* host:checks */
SELECT c.TBOWNER AS SCHEMA_NAME, c.TBNAME AS TABLE_NAME, c.CHECKNAME AS CONSTRAINT_NAME,
 c.CHECKCONDITION AS CHECK_TEXT, 'Y' AS ENFORCED,
 CASE WHEN c.PERIOD<>' ' THEN 'TEMPORAL PERIOD' ELSE '' END AS UNSUPPORTED_CHECK
FROM SYSIBM.SYSCHECKS c WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(c.TBOWNER) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(c.TBNAME) IN /*tableName*/('%')
/*end*/
ORDER BY c.TBOWNER,c.TBNAME,c.CHECKNAME
