/* host:routines */
SELECT r.SCHEMA AS SCHEMA_NAME, r.NAME AS ROUTINE_NAME, r.SPECIFICNAME AS SPECIFIC_NAME,
 r.LANGUAGE AS LANGUAGE_NAME, r.TEXT AS ROUTINE_TEXT,
 CASE WHEN r.ORIGIN='N' OR (r.ORIGIN='Q' AND LENGTH(r.TEXT)>0) THEN 'D' ELSE 'E' END AS TEXT_KIND,
 r.REMARKS, CAST(NULL AS VARCHAR(2048)) AS SQL_PATH,
 r.EXTERNAL_NAME, r.PARAMETER_STYLE, r.SQL_DATA_ACCESS,
 r.DETERMINISTIC, r.VERSION AS NATIVE_VERSION,
 r.FUNCTION_TYPE AS FUNCTION_FORM,
 CAST(NULL AS INTEGER) AS PARAM_POSITION, CAST(NULL AS VARCHAR(128)) AS PARAM_NAME,
 CAST(NULL AS CHAR(1)) AS PARAM_ROW_TYPE, CAST(NULL AS VARCHAR(5)) AS PARAM_MODE,
 CAST(NULL AS VARCHAR(128)) AS PARAM_TYPE, CAST(NULL AS BIGINT) AS PARAM_LENGTH,
 CAST(NULL AS INTEGER) AS PARAM_SCALE,
 CAST(NULL AS VARCHAR(128)) AS PARAM_TYPE_SCHEMA, CAST(NULL AS VARCHAR(128)) AS PARAM_TYPE_NAME
FROM SYSIBM.SYSROUTINES r WHERE r.ROUTINETYPE=/*routineKind*/'P'
 AND r.ACTIVE IN ('Y',' ') AND r.SYSTEM_DEFINED=' '

/*if isNotEmpty(schemaName)*/
 AND RTRIM(r.SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(procedureName)*/
 AND RTRIM(r.NAME) IN /*procedureName*/('%')
/*end*/
/*if isNotEmpty(functionName)*/
 AND RTRIM(r.NAME) IN /*functionName*/('%')
/*end*/
ORDER BY r.SCHEMA,r.SPECIFICNAME
