WITH source AS (
 SELECT a.* FROM SYSIBM.SYSTABAUTH a WHERE 1=1
 /*if isNotEmpty(schemaName)*/ AND RTRIM(a.TCREATOR) IN /*schemaName*/('%') /*end*/
 /*if isNotEmpty(objectName)*/ AND RTRIM(a.TTNAME) IN /*objectName*/('%') /*end*/
), sequences AS (
 SELECT a.* FROM SYSIBM.SYSSEQUENCEAUTH a WHERE 1=1
 /*if isNotEmpty(schemaName)*/ AND RTRIM(a.SCHEMA) IN /*schemaName*/('%') /*end*/
 /*if isNotEmpty(objectName)*/ AND RTRIM(a.NAME) IN /*objectName*/('%') /*end*/
), grants AS (
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'ALTER' AS PRIVILEGE_NAME,CASE a.ALTERAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.ALTERAUTH<>' '
UNION ALL
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'DELETE' AS PRIVILEGE_NAME,CASE a.DELETEAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.DELETEAUTH<>' '
UNION ALL
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'INDEX' AS PRIVILEGE_NAME,CASE a.INDEXAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.INDEXAUTH<>' '
UNION ALL
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'INSERT' AS PRIVILEGE_NAME,CASE a.INSERTAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.INSERTAUTH<>' '
UNION ALL
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'SELECT' AS PRIVILEGE_NAME,CASE a.SELECTAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.SELECTAUTH<>' '
UNION ALL
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'UPDATE' AS PRIVILEGE_NAME,CASE a.UPDATEAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.UPDATEAUTH<>' ' AND a.UPDATECOLS<>'*'
UNION ALL
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'REFERENCES' AS PRIVILEGE_NAME,CASE a.REFERENCESAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.REFERENCESAUTH<>' ' AND a.REFCOLS<>'*'
UNION ALL
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'TRIGGER' AS PRIVILEGE_NAME,CASE a.TRIGGERAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.TRIGGERAUTH<>' '
UNION ALL
SELECT a.TCREATOR AS SCHEMA_NAME,a.TTNAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'UNLOAD' AS PRIVILEGE_NAME,CASE a.UNLOADAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST
FROM source a WHERE a.UNLOADAUTH<>' '
), sequence_grants AS (
 SELECT a.SCHEMA AS SCHEMA_NAME,a.NAME AS OBJECT_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'ALTER' AS PRIVILEGE_NAME,CASE a.ALTERAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST,
 'SEQUENCE' AS OBJECT_KIND,a.COLLID AS PACKAGE_COLLECTION,
 CASE WHEN a.GRANTEETYPE='P' AND a.COLLID<>'' THEN HEX(a.CONTOKEN) ELSE NULL END AS PACKAGE_TOKEN,a.AUTHHOWGOT
 FROM sequences a WHERE a.ALTERAUTH<>' '
 UNION ALL
 SELECT a.SCHEMA,a.NAME,a.GRANTOR,a.GRANTEE,'USAGE',
 CASE a.USEAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END,
 a.GRANTORTYPE,CAST(NULL AS VARCHAR(10)), 'SEQUENCE',a.COLLID,
 CASE WHEN a.GRANTEETYPE='P' AND a.COLLID<>'' THEN HEX(a.CONTOKEN) ELSE NULL END,a.AUTHHOWGOT
 FROM sequences a WHERE a.USEAUTH<>' '
), all_grants AS (
 SELECT g.*,'TABLE' AS OBJECT_KIND,CAST(NULL AS VARCHAR(128)) AS PACKAGE_COLLECTION,
 CAST(NULL AS VARCHAR(16)) AS PACKAGE_TOKEN,CAST(NULL AS CHAR(1)) AS AUTHHOWGOT FROM grants g
 UNION ALL SELECT * FROM sequence_grants
 UNION ALL
 SELECT a.QUALIFIER,a.NAME,a.GRANTOR,a.GRANTEE,'USAGE',
 CASE a.USEAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END,
 a.GRANTORTYPE,CAST(NULL AS VARCHAR(10)),'TYPE',CAST(NULL AS VARCHAR(128)),
 CAST(NULL AS VARCHAR(16)),a.AUTHHOWGOT
 FROM SYSIBM.SYSRESAUTH a WHERE a.OBTYPE='D' AND a.USEAUTH<>' '
 /*if isNotEmpty(schemaName)*/ AND RTRIM(a.QUALIFIER) IN /*schemaName*/('%') /*end*/
 /*if isNotEmpty(objectName)*/ AND RTRIM(a.NAME) IN /*objectName*/('%') /*end*/
)
SELECT * FROM all_grants ORDER BY SCHEMA_NAME,OBJECT_NAME,OBJECT_KIND,GRANTEE_NAME,PRIVILEGE_NAME
