/* host:schemaGrants */
WITH source AS (
 SELECT a.* FROM SYSIBM.SYSSCHEMAAUTH a WHERE 1=1
 /*if isNotEmpty(schemaName)*/ AND RTRIM(a.SCHEMANAME) IN /*schemaName*/('%') /*end*/
), grants AS (
 SELECT a.SCHEMANAME AS SCHEMA_NAME,a.GRANTOR AS GRANTOR_NAME,a.GRANTEE AS GRANTEE_NAME,
 'CREATEIN' AS PRIVILEGE_NAME,
 CASE a.CREATEINAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END AS GRANTEE_TYPE,
 a.GRANTORTYPE AS GRANTOR_TYPE,CAST(NULL AS VARCHAR(10)) AS AUTHORIZATION_LIST,a.AUTHHOWGOT
 FROM source a WHERE a.CREATEINAUTH<>' '
 UNION ALL
 SELECT a.SCHEMANAME,a.GRANTOR,a.GRANTEE,'ALTERIN',
 CASE a.ALTERINAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END,
 a.GRANTORTYPE,CAST(NULL AS VARCHAR(10)),a.AUTHHOWGOT
 FROM source a WHERE a.ALTERINAUTH<>' '
 UNION ALL
 SELECT a.SCHEMANAME,a.GRANTOR,a.GRANTEE,'DROPIN',
 CASE a.DROPINAUTH WHEN 'G' THEN 'Y' WHEN 'Y' THEN 'N' ELSE '?' END,
 CASE a.GRANTEETYPE WHEN ' ' THEN 'U' WHEN 'L' THEN 'R' WHEN 'R' THEN 'I' ELSE a.GRANTEETYPE END,
 a.GRANTORTYPE,CAST(NULL AS VARCHAR(10)),a.AUTHHOWGOT
 FROM source a WHERE a.DROPINAUTH<>' '
)
SELECT * FROM grants ORDER BY SCHEMA_NAME,GRANTEE_NAME,GRANTOR_NAME,PRIVILEGE_NAME
