SELECT r.CREATOR AS SCHEMA_NAME, r.TBNAME AS TABLE_NAME, r.RELNAME AS CONSTRAINT_NAME,
 f.COLNAME AS COLUMN_NAME, r.REFTBCREATOR AS REF_SCHEMA_NAME, r.REFTBNAME AS REF_TABLE_NAME,
 p.COLNAME AS REF_COLUMN_NAME, r.ENFORCED,
 CASE r.DELETERULE WHEN 'A' THEN 'NO ACTION' WHEN 'C' THEN 'CASCADE' WHEN 'N' THEN 'SET NULL' WHEN 'R' THEN 'RESTRICT' ELSE r.DELETERULE END AS DELETE_RULE,
 'NO ACTION' AS UPDATE_RULE
FROM SYSIBM.SYSRELS r JOIN SYSIBM.SYSFOREIGNKEYS f
 ON f.CREATOR=r.CREATOR AND f.TBNAME=r.TBNAME AND f.RELNAME=r.RELNAME
LEFT JOIN SYSIBM.SYSTABCONST u ON u.TBCREATOR=r.REFTBCREATOR AND u.TBNAME=r.REFTBNAME
 AND ((RTRIM(r.IXNAME)='' AND u.TYPE='P') OR (RTRIM(r.IXNAME)<>'' AND u.IXOWNER=r.IXOWNER AND u.IXNAME=r.IXNAME AND u.TYPE='U'))
LEFT JOIN SYSIBM.SYSKEYCOLUSE p ON p.TBCREATOR=u.TBCREATOR AND p.TBNAME=u.TBNAME AND p.CONSTNAME=u.CONSTNAME AND p.COLSEQ=f.COLSEQ
WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(r.CREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(r.TBNAME) IN /*tableName*/('%')
/*end*/
ORDER BY r.CREATOR, r.TBNAME, r.RELNAME, f.COLSEQ
