SELECT t.CREATOR AS SCHEMA_NAME, t.NAME AS TABLE_NAME, t.REMARKS,
 v.STATEMENT AS MQT_TEXT, 'D' AS TEXT_KIND, v.PATHSCHEMAS AS SQL_PATH,
 v.REFRESH, v.ENABLE AS ENABLE_FLAG, v.MAINTENANCE, v.ISOLATION
FROM SYSIBM.SYSTABLES t
JOIN SYSIBM.SYSVIEWS v ON v.CREATOR=t.CREATOR AND v.NAME=t.NAME AND v.TYPE='M'
WHERE t.TYPE='M'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(t.CREATOR) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(t.NAME) IN /*tableName*/('%')
/*end*/
ORDER BY t.CREATOR, t.NAME
