SELECT
  fk.CONSTRAINT_CATALOG AS `constraint_catalog`
, fk.CONSTRAINT_SCHEMA AS `constraint_schema`
, fk.CONSTRAINT_NAME AS `constraint_name`
, fk.TABLE_NAME AS `table_name`
, fk.COLUMN_NAME AS `column_name`
, pk.TABLE_CATALOG AS `referenced_table_catalog`
, pk.TABLE_SCHEMA AS `referenced_table_schema`
, pk.TABLE_NAME AS `referenced_table_name`
, pk.COLUMN_NAME AS `referenced_column_name`
, rc.MATCH_OPTION AS `match_option`
, rc.UPDATE_RULE AS `update_rule`
, rc.DELETE_RULE AS `delete_rule`
FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS rc
INNER JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE fk
  ON rc.CONSTRAINT_CATALOG=fk.CONSTRAINT_CATALOG
 AND rc.CONSTRAINT_SCHEMA=fk.CONSTRAINT_SCHEMA
 AND rc.CONSTRAINT_NAME=fk.CONSTRAINT_NAME
INNER JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE pk
  ON rc.UNIQUE_CONSTRAINT_CATALOG=pk.CONSTRAINT_CATALOG
 AND rc.UNIQUE_CONSTRAINT_SCHEMA=pk.CONSTRAINT_SCHEMA
 AND rc.UNIQUE_CONSTRAINT_NAME=pk.CONSTRAINT_NAME
 AND fk.POSITION_IN_UNIQUE_CONSTRAINT=pk.ORDINAL_POSITION
WHERE TRUE
  /*if isNotEmpty(schemaName)*/
  AND fk.TABLE_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND fk.TABLE_NAME IN /*tableName*/('%')
  /*end*/
  /*if isNotEmpty(constraintName)*/
  AND fk.CONSTRAINT_NAME IN /*constraintName*/('%')
  /*end*/
ORDER BY fk.TABLE_SCHEMA, fk.TABLE_NAME, fk.CONSTRAINT_NAME,
  fk.ORDINAL_POSITION
