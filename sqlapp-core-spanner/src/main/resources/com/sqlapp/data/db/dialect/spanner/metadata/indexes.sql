SELECT
  i.*
, cc.COLUMN_NAME
, cc.ORDINAL_POSITION
, cc.COLUMN_ORDERING
, cc.IS_NULLABLE
, cc.SPANNER_TYPE
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.INDEX_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=i.TABLE_SCHEMA
      AND opt.TABLE_NAME=i.TABLE_NAME
      AND opt.INDEX_NAME=i.INDEX_NAME
      AND opt.OPTION_NAME='distance_type'
  ) AS DISTANCE_TYPE
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.INDEX_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=i.TABLE_SCHEMA
      AND opt.TABLE_NAME=i.TABLE_NAME
      AND opt.INDEX_NAME=i.INDEX_NAME
      AND opt.OPTION_NAME='tree_depth'
  ) AS TREE_DEPTH
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.INDEX_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=i.TABLE_SCHEMA
      AND opt.TABLE_NAME=i.TABLE_NAME
      AND opt.INDEX_NAME=i.INDEX_NAME
      AND opt.OPTION_NAME='num_leaves'
  ) AS NUM_LEAVES
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.INDEX_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=i.TABLE_SCHEMA
      AND opt.TABLE_NAME=i.TABLE_NAME
      AND opt.INDEX_NAME=i.INDEX_NAME
      AND opt.OPTION_NAME='num_branches'
  ) AS NUM_BRANCHES
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.INDEX_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=i.TABLE_SCHEMA
      AND opt.TABLE_NAME=i.TABLE_NAME
      AND opt.INDEX_NAME=i.INDEX_NAME
      AND opt.OPTION_NAME='disable_search'
  ) AS DISABLE_SEARCH
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.INDEX_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=i.TABLE_SCHEMA
      AND opt.TABLE_NAME=i.TABLE_NAME
      AND opt.INDEX_NAME=i.INDEX_NAME
      AND opt.OPTION_NAME='sort_order_sharding'
  ) AS SORT_ORDER_SHARDING
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.INDEX_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=i.TABLE_SCHEMA
      AND opt.TABLE_NAME=i.TABLE_NAME
      AND opt.INDEX_NAME=i.INDEX_NAME
      AND opt.OPTION_NAME='locality_group'
  ) AS LOCALITY_GROUP
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.INDEX_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=i.TABLE_SCHEMA
      AND opt.TABLE_NAME=i.TABLE_NAME
      AND opt.INDEX_NAME=i.INDEX_NAME
      AND opt.OPTION_NAME='columnar_policy'
  ) AS COLUMNAR_POLICY
FROM INFORMATION_SCHEMA.INDEXES i
INNER JOIN INFORMATION_SCHEMA.INDEX_COLUMNS cc
  ON (i.TABLE_SCHEMA=cc.TABLE_SCHEMA
  AND
  i.TABLE_NAME=cc.TABLE_NAME
  AND
  i.INDEX_NAME=cc.INDEX_NAME
  )
WHERE 1=1
  AND i.INDEX_TYPE IN ('INDEX', 'SEARCH', 'VECTOR')
  /*if isNotEmpty(schemaName)*/
  AND i.TABLE_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND i.TABLE_NAME IN /*tableName*/('%')
  /*end*/
  /*if isNotEmpty(indexName)*/
  AND i.INDEX_NAME IN /*indexName*/('%')
  /*end*/
ORDER BY i.TABLE_SCHEMA, i.TABLE_NAME, i.INDEX_NAME,
  cc.ORDINAL_POSITION
