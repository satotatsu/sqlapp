SELECT
  t.*
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.TABLE_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=t.TABLE_SCHEMA
      AND opt.TABLE_NAME=t.TABLE_NAME
      AND opt.OPTION_NAME='locality_group'
  ) AS LOCALITY_GROUP
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.TABLE_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=t.TABLE_SCHEMA
      AND opt.TABLE_NAME=t.TABLE_NAME
      AND opt.OPTION_NAME='columnar_policy'
  ) AS COLUMNAR_POLICY
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.TABLE_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=t.TABLE_SCHEMA
      AND opt.TABLE_NAME=t.TABLE_NAME
      AND opt.OPTION_NAME='fulltext_dictionary_table'
  ) AS FULLTEXT_DICTIONARY_TABLE
, (
    SELECT opt.OPTION_VALUE
    FROM INFORMATION_SCHEMA.TABLE_OPTIONS opt
    WHERE opt.TABLE_SCHEMA=t.TABLE_SCHEMA
      AND opt.TABLE_NAME=t.TABLE_NAME
      AND opt.OPTION_NAME='fulltext_dictionary_staleness'
  ) AS FULLTEXT_DICTIONARY_STALENESS
FROM INFORMATION_SCHEMA.TABLES t
WHERE 1=1
  AND t.TABLE_TYPE='BASE TABLE'
  /*if isNotEmpty(schemaName)*/
  AND t.TABLE_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND t.TABLE_NAME IN /*tableName*/('%')
  /*end*/
ORDER BY t.TABLE_SCHEMA, t.TABLE_NAME
