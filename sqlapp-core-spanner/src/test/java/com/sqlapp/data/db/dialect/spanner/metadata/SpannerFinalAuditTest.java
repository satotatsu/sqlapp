package com.sqlapp.data.db.dialect.spanner.metadata;

import static org.junit.jupiter.api.Assertions.*;
import java.lang.reflect.Proxy;
import java.sql.*;
import java.util.*;
import org.junit.jupiter.api.Test;
import com.sqlapp.data.db.dialect.spanner.DialectHolder;
import com.sqlapp.data.db.sql.SqlType;
import com.sqlapp.data.parameter.ParametersContext;
import com.sqlapp.data.schemas.*;
import com.sqlapp.jdbc.ExResultSet;
import com.sqlapp.jdbc.sql.SqlParameterCollection;

class SpannerFinalAuditTest {
	@SuppressWarnings("unchecked")
	private <T> T proxy(Class<T> type, java.lang.reflect.InvocationHandler handler) {
		return (T) Proxy.newProxyInstance(type.getClassLoader(), new Class<?>[] { type }, handler);
	}

	private ExResultSet result(Map<String, String> values) {
		final var labels = new ArrayList<>(values.keySet());
		final var metadata = proxy(ResultSetMetaData.class, (p, method, args) -> switch (method.getName()) {
		case "getColumnCount" -> labels.size();
		case "getColumnLabel", "getColumnName" -> labels.get((Integer) args[0] - 1);
		case "getTableName", "getSchemaName" -> "";
		case "isNullable" -> ResultSetMetaData.columnNullable;
		default -> throw new UnsupportedOperationException(method.getName());
		});
		final boolean[] wasNull = { false };
		return new ExResultSet(proxy(ResultSet.class, (p, method, args) -> {
			if (method.getName().equals("getMetaData"))
				return metadata;
			if (method.getName().equals("wasNull"))
				return wasNull[0];
			final String label = args[0].toString();
			if (!values.containsKey(label))
				throw new SQLException("Unknown exact JDBC label: " + label);
			final String value = values.get(label);
			wasNull[0] = value == null;
			return switch (method.getName()) {
			case "getString", "getObject" -> value;
			case "getLong" -> value == null ? 0L : Long.parseLong(value);
			default -> throw new UnsupportedOperationException(method.getName());
			};
		}));
	}

	@Test
	void legacyAndModernJdbcColumnLabelsSurviveSchemaXmlAndDdl() throws Exception {
		for (boolean modern : List.of(false, true)) {
			final var values = new HashMap<>(Map.of("table_catalog", "", "table_schema", "Sales", "table_name",
					"Orders", "column_name", "id", "spanner_type", "INT64", "is_nullable", "NO"));
			if (modern) {
				values.put("IS_IDENTITY", "YES");
				values.put("IDENTITY_GENERATION", "BY DEFAULT");
				values.put("IDENTITY_KIND", "BIT_REVERSED_POSITIVE_SEQUENCE");
			}
			final var column = new SpannerColumnReader(DialectHolder.defaultDialect).createColumn(result(values));
			assertEquals(modern, column.isIdentity());
			assertNull(column.getIdentityStartValue());
			final var schema = new Schema("Sales");
			schema.setDialect(DialectHolder.defaultDialect);
			final var table = new Table("Orders");
			schema.getTables().add(table);
			table.getColumns().add(column);
			table.getConstraints().addPrimaryKeyConstraint("PRIMARY_KEY", column);
			table.getConstraints().add(new CheckConstraint("positive", "id > 0"));
			final Schema restored = SchemaUtils.readXml(new java.io.StringReader(schema.asXml()));
			final var registry = DialectHolder.defaultDialect.createSqlFactoryRegistry();
			registry.getOptions().setDecorateSchemaName(true);
			final String sql = registry.createSql(restored.getTables().get(0), SqlType.CREATE).get(0).getSqlText();
			assertTrue(sql.contains("`Sales`.`Orders`"), sql);
			assertTrue(sql.contains("PRIMARY KEY") && sql.contains("CHECK (id > 0"), sql);
			assertEquals(modern, sql.contains("GENERATED BY DEFAULT AS IDENTITY"));
		}
	}

	@Test
	void columnQueryDoesNotReferenceNewerPhysicalColumnsExplicitly() {
		final var reader = new SpannerColumnReader(DialectHolder.defaultDialect);
		final var parameters = new SqlParameterCollection();
		reader.getSqlNode(null).eval(new ParametersContext(), parameters);
		assertTrue(parameters.getSql().contains("col.*"));
		for (String name : List.of("IS_IDENTITY", "IDENTITY_KIND", "ON_UPDATE_EXPRESSION", "IS_GENERATED", "IS_HIDDEN"))
			assertFalse(parameters.getSql().contains("col." + name), parameters.getSql());
	}

	@Test
	void rejectsUnknownGeneratedStorageAndHiddenFlags() {
		for (String field : List.of("IS_GENERATED", "IS_STORED", "IS_HIDDEN")) {
			final var values = new HashMap<>(Map.of("table_catalog", "", "table_schema", "Sales", "table_name",
					"Orders", "column_name", "computed", "spanner_type", "INT64", "is_nullable", "YES"));
			if (field.equals("IS_STORED")) {
				values.put("IS_GENERATED", "ALWAYS");
				values.put("GENERATION_EXPRESSION", "1 + 2");
			}
			values.put(field, "unknown");
			assertThrows(IllegalArgumentException.class,
					() -> new SpannerColumnReader(DialectHolder.defaultDialect).createColumn(result(values)));
		}
	}
}
