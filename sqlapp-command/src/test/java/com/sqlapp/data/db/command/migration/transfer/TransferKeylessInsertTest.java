package com.sqlapp.data.db.command.migration.transfer;

import static org.junit.jupiter.api.Assertions.*;
import java.nio.file.*;
import java.util.*;
import org.hsqldb.jdbc.JDBCDataSource;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;

class TransferKeylessInsertTest {
	@TempDir
	Path directory;

	@ParameterizedTest
	@ValueSource(strings = { "REQUIRE_EXISTING", "CREATE_MISSING", "CREATE_MISSING_WITH_IDENTITY" })
	void keylessChildrenCopyDuplicatesAndNullsInParentOrderAndVerify(String schemaMode) throws Exception {
		boolean createMissing = !schemaMode.equals("REQUIRE_EXISTING");
		var source = database();
		var target = database();
		sql(source, "CREATE TABLE PARENTS(ID INTEGER NOT NULL PRIMARY KEY)",
				"CREATE TABLE EVENTS(PARENT_ID INTEGER, NOTE VARCHAR(40), FOREIGN KEY(PARENT_ID) REFERENCES PARENTS(ID))",
				"INSERT INTO PARENTS VALUES(1)", "INSERT INTO EVENTS VALUES(1,'同じ行'),(1,'同じ行'),(NULL,NULL)");
		if (!createMissing)
			sql(target, "CREATE TABLE PARENTS(ID INTEGER NOT NULL PRIMARY KEY)",
					"CREATE TABLE EVENTS(PARENT_ID INTEGER, NOTE VARCHAR(40), EXISTING_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, FOREIGN KEY(PARENT_ID) REFERENCES PARENTS(ID))");
		Path job = Files.writeString(directory.resolve("job.yaml"),
				"formatVersion: 1\nsource: from\ntarget: to\ntables: [EVENTS,PARENTS]\nschemaMode: " + schemaMode
						+ "\nchunkSize: 1\n");
		boolean mapped = schemaMode.equals("CREATE_MISSING_WITH_IDENTITY");
		String eventTable = mapped ? "EVENT_LOG" : "EVENTS";
		String noteColumn = mapped ? "MESSAGE" : "NOTE";
		if (mapped) {
			Files.writeString(directory.resolve("names.yaml"),
					"formatVersion: 1\ntables:\n  PARENTS: {targetTable: PEOPLE, columns: {ID: OWNER_ID}}\n  EVENTS: {targetTable: EVENT_LOG, columns: {PARENT_ID: OWNER_ID, NOTE: MESSAGE}}\n");
			Files.writeString(job, Files.readString(job) + "mappingFile: names.yaml\n");
		}
		var service = new TransferJobExecutionService();
		var connections = Map.of("from", source, "to", target);
		var review = service.review(job, connections, directory);
		assertTrue(review.prepared().warnings().stream()
				.anyMatch(message -> message.startsWith(TransferKeylessChecks.CODE)));
		assertTrue(Files.readString(review.prepared().dataJob().file()).contains("fullScan: true"));
		var outcome = service.execute(review, connections);
		assertEquals(TransferJobExecutionService.Phase.COMPLETE, outcome.phase());
		assertEquals(4, outcome.copyResult().getProcessedRows());
		assertTrue(outcome.verificationResult().isMatch());
		if (schemaMode.equals("CREATE_MISSING_WITH_IDENTITY")) {
			assertTrue(review.prepared().warnings().stream()
					.anyMatch(message -> message.startsWith(TransferKeylessChecks.GENERATED_TARGET_KEY)));
			try (var c = target.getConnection();
					var keys = c.getMetaData().getPrimaryKeys(null, "PUBLIC", eventTable)) {
				assertTrue(keys.next());
				assertEquals(TransferKeylessChecks.GENERATED_COLUMN, keys.getString("COLUMN_NAME"));
			}
			try (var c = target.getConnection();
					var s = c.createStatement();
					var rows = s.executeQuery("SELECT COUNT(DISTINCT SQLAPP_ROW_ID) FROM " + eventTable)) {
				rows.next();
				assertEquals(3, rows.getInt(1));
			}
			try (var c = source.getConnection(); var keys = c.getMetaData().getPrimaryKeys(null, "PUBLIC", "EVENTS")) {
				assertFalse(keys.next());
			}
		}
		try (var c = target.getConnection();
				var s = c.createStatement();
				var rows = s.executeQuery("SELECT COUNT(*) FROM " + eventTable + " WHERE " + noteColumn + "='同じ行'")) {
			rows.next();
			assertEquals(2, rows.getInt(1));
		}
		assertThrows(TransferJobExecutionService.ExecutionException.class, () -> service.execute(review, connections));
	}

	@org.junit.jupiter.api.Test
	void generatedColumnCollisionAndStrictWarningsRejectBeforeTargetChanges() throws Exception {
		var source = database();
		var target = database();
		sql(source, "CREATE TABLE ITEMS(SQLAPP_ROW_ID INTEGER)");
		Path file = Files.writeString(directory.resolve("collision.yaml"),
				"formatVersion: 1\nsource: from\ntarget: to\ntables: [ITEMS]\nschemaMode: CREATE_MISSING_WITH_IDENTITY\n");
		var service = new TransferJobExecutionService();
		var bindings = Map.of("from", source, "to", target);
		assertTrue(assertThrows(TransferSchemaPreparation.ValidationException.class,
				() -> service.review(file, bindings, directory)).getMessage().contains("collides"));
		Files.writeString(file, Files.readString(file).replace("CREATE_MISSING_WITH_IDENTITY", "CREATE_MISSING")
				+ "compatibilityPolicy: ERROR\n");
		assertTrue(assertThrows(TransferSchemaPreparation.ValidationException.class,
				() -> service.review(file, bindings, directory)).getMessage().startsWith(TransferKeylessChecks.CODE));
		try (var c = target.getConnection(); var tables = c.getMetaData().getTables(null, "PUBLIC", "ITEMS", null)) {
			assertFalse(tables.next());
		}
	}

	private static void sql(JDBCDataSource database, String... statements) throws Exception {
		try (var c = database.getConnection(); var s = c.createStatement()) {
			for (String text : statements)
				s.execute(text);
		}
	}

	private static JDBCDataSource database() {
		var ds = new JDBCDataSource();
		ds.setUrl("jdbc:hsqldb:mem:keyless_" + UUID.randomUUID());
		ds.setUser("SA");
		ds.setPassword("");
		return ds;
	}
}
