package com.sqlapp.data.db.command.migration.transfer;

import static org.junit.jupiter.api.Assertions.*;
import java.nio.file.*;
import java.sql.*;
import java.util.*;
import org.hsqldb.jdbc.JDBCDataSource;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

class TransferIdentityPreservationTest {
	@TempDir
	Path directory;

	@ParameterizedTest
	@CsvSource({ "false,false", "false,true", "true,false", "true,true" })
	void preservesZeroSparseIdentityKeysForeignKeysAndNulls(boolean csv, boolean createMissing) throws Exception {
		final var source = database();
		final var target = database();
		sql(source,
				"CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 0) PRIMARY KEY, NAME VARCHAR(30) DEFAULT 'source-default')",
				"CREATE TABLE INVOICES(ID INTEGER NOT NULL PRIMARY KEY, CUSTOMER_ID BIGINT NOT NULL REFERENCES CUSTOMERS(ID))",
				"INSERT INTO CUSTOMERS(ID,NAME) VALUES(0,NULL),(42,'forty-two')",
				"INSERT INTO INVOICES VALUES(1,0),(2,42)");
		if (!createMissing)
			sql(target,
					"CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 1000) PRIMARY KEY, NAME VARCHAR(30) DEFAULT 'target-default')",
					"CREATE TABLE INVOICES(ID INTEGER NOT NULL PRIMARY KEY, CUSTOMER_ID BIGINT NOT NULL REFERENCES CUSTOMERS(ID))");
		final var job = Files.writeString(directory.resolve("transfer.yaml"),
				"formatVersion: 1\nsource: from\ntarget: to\ntables: [INVOICES, CUSTOMERS]\nchunkSize: 1\nschemaMode: "
						+ (createMissing ? "CREATE_MISSING" : "REQUIRE_EXISTING") + "\n"
						+ (csv ? "dataMode: FILE\nfiles: {directory: packages, nullValue: __NULL__}\n" : ""));
		if (csv) {
			final var exported = new TransferFileExportService().export(job, Map.of("from", source));
			final var service = new TransferFileImportService();
			final var bindings = Map.of("to", target);
			final var review = service.review(exported.file(), exported.fingerprint(), bindings);
			assertCounterCheck(review.schemaPreparation().warnings());
			final var result = service.execute(review, bindings, directory);
			assertEquals(TransferJobExecutionService.Phase.COMPLETE, result.phase());
			assertTrue(result.verification().values().stream().allMatch(value -> value.isMatch()));
			assertEquals(4, result.copyResult().getProcessedRows());
			assertEquals(review.schemaPreparation().warnings(), result.schemaPreparation().warnings());
			assertTrue(Files.readString(result.auditFile()).contains(TransferGeneratedKeyChecks.CODE));
		} else {
			final var service = new TransferJobExecutionService();
			final var bindings = Map.of("from", source, "to", target);
			final var review = service.review(job, bindings, directory);
			assertCounterCheck(review.prepared().warnings());
			final var generated = new com.sqlapp.data.db.command.migration.bulk.BulkMigrationJobConfigurationEditorIO()
					.validate(review.prepared().dataJob().text());
			assertTrue(generated.getTasks().stream()
					.allMatch(task -> task.getBulk().isKeepIdentity() && task.getBulk().isKeepNulls()));
			final var result = service.execute(review, bindings);
			assertEquals(TransferJobExecutionService.Phase.COMPLETE, result.phase());
			assertTrue(result.verificationResult().isMatch());
			assertEquals(4, result.copyResult().getProcessedRows());
			assertCounterCheck(result.prepared().warnings());
			assertTrue(Files.readString(new TransferJobReportIO().writeOutcome(review, result))
					.contains(TransferGeneratedKeyChecks.CODE));
		}
		try (var connection = target.getConnection();
				var rows = connection.createStatement().executeQuery("SELECT ID,NAME FROM CUSTOMERS ORDER BY ID")) {
			assertTrue(rows.next());
			assertEquals(0, rows.getLong(1));
			assertNull(rows.getString(2));
			assertTrue(rows.next());
			assertEquals(42, rows.getLong(1));
			assertEquals("forty-two", rows.getString(2));
			assertFalse(rows.next());
		}
		try (var connection = target.getConnection();
				var rows = connection.createStatement().executeQuery("SELECT CUSTOMER_ID FROM INVOICES ORDER BY ID")) {
			assertTrue(rows.next());
			assertEquals(0, rows.getLong(1));
			assertTrue(rows.next());
			assertEquals(42, rows.getLong(1));
			assertFalse(rows.next());
		}
	}

	private static void assertCounterCheck(List<String> warnings) {
		final var checks = TransferGeneratedKeyChecks.messages(warnings);
		assertEquals(1, checks.size());
		assertTrue(checks.getFirst().contains("CUSTOMERS"));
		assertTrue(checks.getFirst().contains("column 'ID'"));
		assertTrue(checks.getFirst().contains("not checked or synchronized"));
	}

	@ParameterizedTest
	@org.junit.jupiter.params.provider.ValueSource(booleans = { false, true })
	void strictExistingTargetPolicyRejectsUnverifiedGeneratedCounterBeforeCopy(boolean csv) throws Exception {
		final var source = database();
		final var target = database();
		for (var data : List.of(source, target))
			sql(data, "CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY(START WITH 0) PRIMARY KEY)");
		sql(source, "INSERT INTO CUSTOMERS(ID) VALUES(0),(42)");
		final var job = Files.writeString(directory.resolve("strict.yaml"),
				"formatVersion: 1\nsource: from\ntarget: to\ntables: [CUSTOMERS]\nschemaMode: REQUIRE_EXISTING\ncompatibilityPolicy: ERROR\n"
						+ (csv ? "dataMode: FILE\nfiles: {directory: packages, nullValue: __NULL__}\n" : ""));
		final Exception failure;
		if (csv) {
			final var exported = new TransferFileExportService().export(job, Map.of("from", source));
			failure = assertThrows(TransferSchemaPreparation.ValidationException.class,
					() -> new TransferFileImportService().review(exported.file(), exported.fingerprint(),
							Map.of("to", target)));
		} else
			failure = assertThrows(TransferSchemaPreparation.ValidationException.class,
					() -> new TransferJobExecutionService().review(job, Map.of("from", source, "to", target),
							directory));
		assertTrue(failure.getMessage().contains(TransferGeneratedKeyChecks.CODE));
		try (var connection = target.getConnection();
				var rows = connection.createStatement().executeQuery("SELECT COUNT(*) FROM CUSTOMERS")) {
			assertTrue(rows.next());
			assertEquals(0, rows.getInt(1));
		}
	}

	private static JDBCDataSource database() {
		final var value = new JDBCDataSource();
		value.setUrl("jdbc:hsqldb:mem:identity_transfer_" + UUID.randomUUID());
		value.setUser("SA");
		value.setPassword("");
		return value;
	}

	private static void sql(JDBCDataSource value, String... statements) throws Exception {
		try (var connection = value.getConnection(); var command = connection.createStatement()) {
			for (var text : statements)
				command.execute(text);
		}
	}
}
