package com.sqlapp.data.db.command.migration.transfer;

import static org.junit.jupiter.api.Assertions.*;

import java.math.BigInteger;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Map;
import java.util.UUID;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import com.sqlapp.jdbc.bulk.GeneratedKeyCounters.Action;

class TransferGeneratedKeySynchronizationTest {
	@TempDir
	Path directory;

	@Test
	void directCopyRaisesTheTargetIdentityPastImportedKeys() throws Exception {
		var source = database();
		var target = database();
		sql(source, "CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(30))",
				"INSERT INTO CUSTOMERS(ID, NAME) VALUES (5, 'a'), (42, 'b')");
		sql(target, "CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(30))");
		var result = transfer(source, target, "");
		assertEquals(TransferJobExecutionService.Phase.COMPLETE, result.phase());
		assertTrue(TransferGeneratedKeyChecks.messages(result.prepared().warnings()).isEmpty());
		var counter = result.generatedKeyCounters().getFirst();
		assertEquals(Action.RESTARTED, counter.action(), counter.toString());
		assertEquals(BigInteger.valueOf(43), counter.next());
		sql(target, "INSERT INTO CUSTOMERS(NAME) VALUES ('new')");
		assertEquals(43, single(target, "SELECT ID FROM CUSTOMERS WHERE NAME = 'new'"));
	}

	@Test
	void warnModeLeavesTheCounterAndKeepsTheWarning() throws Exception {
		var source = database();
		var target = database();
		sql(source, "CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(30))",
				"INSERT INTO CUSTOMERS(ID, NAME) VALUES (42, 'b')");
		sql(target, "CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, NAME VARCHAR(30))");
		var result = transfer(source, target, "generatedKeyCounters: WARN\n");
		assertEquals(1, TransferGeneratedKeyChecks.messages(result.prepared().warnings()).size());
		assertTrue(result.generatedKeyCounters().isEmpty());
		sql(target, "INSERT INTO CUSTOMERS(NAME) VALUES ('new')");
		assertEquals(1, single(target, "SELECT ID FROM CUSTOMERS WHERE NAME = 'new'"));
	}

	@Test
	void strictPolicyAcceptsSynchronizedCounters() throws Exception {
		var source = database();
		var target = database();
		sql(source, "CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)",
				"INSERT INTO CUSTOMERS(ID) VALUES (7)");
		sql(target, "CREATE TABLE CUSTOMERS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)");
		var result = transfer(source, target, "compatibilityPolicy: ERROR\n");
		assertEquals(Action.RESTARTED, result.generatedKeyCounters().getFirst().action());
	}

	private TransferJobExecutionService.Outcome transfer(JdbcDataSource source, JdbcDataSource target, String extra)
			throws Exception {
		var job = Files.writeString(directory.resolve("transfer-" + UUID.randomUUID() + ".yaml"),
				"formatVersion: 1\nsource: from\ntarget: to\ntables: [CUSTOMERS]\nschemaMode: REQUIRE_EXISTING\n"
						+ extra);
		var service = new TransferJobExecutionService();
		var bindings = Map.of("from", source, "to", target);
		var review = service.review(job, bindings, directory);
		return service.execute(review, bindings);
	}

	private static JdbcDataSource database() {
		var value = new JdbcDataSource();
		value.setURL("jdbc:h2:mem:counter_" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1");
		value.setUser("sa");
		value.setPassword("");
		return value;
	}

	private static void sql(JdbcDataSource value, String... statements) throws Exception {
		try (var connection = value.getConnection(); var command = connection.createStatement()) {
			for (var text : statements)
				command.execute(text);
		}
	}

	private static long single(JdbcDataSource value, String sql) throws Exception {
		try (var connection = value.getConnection();
				var command = connection.createStatement();
				var rows = command.executeQuery(sql)) {
			rows.next();
			return rows.getLong(1);
		}
	}
}
