	private JdbcTreeDataSession createDate(Connection connection, List<Table> tables, int rowSize1, int rowSize2,
			int rowSize3) throws SQLException {
		int cnt = 0;
		final Table tab = tables.get(cnt++);
		final Table tab1 = tables.get(cnt++);
		final Table tab1_1 = tables.get(cnt++);
		JdbcTreeDataSession session = new JdbcTreeDataSession(connection, tables);
		session.setNewRowInitializer(row -> {
			row.put("CREATED_AT", LocalDateTime.now());
		});
		session.setBeforeRootBatchHandler((batchCounter, table, rows) -> {
			System.out.println("BeforeRootBatch batchCount=" + batchCounter);
			rows.forEach(row -> System.out.println(row));
			assertTrue(session.getRootBatchSize() >= table.getRows().size());
		});
		session.setPreparedStatementBeforeExecuteHandler(statement -> {
			System.out.println(statement);
		});
		System.out.println("---------------------------INSERT------------------------------------");
		session.setTableOperationMode(TableOperationMode.INSERT);
		try (session) {
			for (int i = 0; i < rowSize1; i++) {
				Table current = tab;
				Row row = session.newRow(current);
				row.put("PK_COL1", current.getName() + "_PK_COL1_" + i);
				row.put("PK_COL2", current.getName() + "_PK_COL2_" + i);
				row.put("TXT", current.getName() + "_TXT_" + i);
				for (int j = 0; j < rowSize2; j++) {
					current = tab1;
					row = session.newRow(current);
					row.put("PK_COL3", current.getName() + "_PK_COL3_" + j);
					row.put("TXT", current.getName() + "_TXT_" + j);
					for (int k = 0; k < rowSize3; k++) {
						current = tab1_1;
						row = session.newRow(current);
						row.put("PK_COL4A", current.getName() + "_PK_COL4A_" + k);
						row.put("TXT1", current.getName() + "_TXT1_" + k);
						row.put("TXT2", current.getName() + "_TXT2_" + k);
						row.put("TXT3", current.getName() + "_TXT3_" + k);
					}
				}
			}
		}
		session.close();
		session.setTableOperationMode(TableOperationMode.NONE);
		session.select(tab);
		session.select(tab1);
		session.select(tab1_1);
		return session;
	}

