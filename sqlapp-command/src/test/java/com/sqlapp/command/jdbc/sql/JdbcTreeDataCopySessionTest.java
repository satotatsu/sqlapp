	void testCopyAndNormalizeHierarchicalData(int rowSize1, int rowSize2, int rowSize3,
			Consumer<JdbcTreeDataCopySession> initializer) throws SQLException {
		test(connection -> {
			executeSql(connection, CREATE_TABLE);
			executeSql(connection, CREATE_TABLE_1);
			executeSql(connection, CREATE_TABLE_1_1);
			executeSql(connection, CREATE_TABLE_TO);
			executeSql(connection, CREATE_TABLE_1_TO);
			executeSql(connection, CREATE_TABLE_1_1_TO);
			executeSql(connection, CREATE_TABLE_1_1_1_TO);
			Optional<Schema> schemaOption = SchemaUtils.getSchema(connection, "PUBLIC");
			assertTrue(schemaOption.isPresent());
			Schema schema = schemaOption.get();
			List<Table> tables = CommonUtils.list();
			final Table tab = schema.getTables().get("TAB");
			final Table tab1 = schema.getTables().get("TAB_1");
			final Table tab1_1 = schema.getTables().get("TAB_1_1");
			tables.add(tab);
			tables.add(tab1);
			tables.add(tab1_1);
			JdbcTreeDataSession source = createDate(connection, tables, rowSize1, rowSize2, rowSize3);
			tables.clear();
			final Table tabTo = schema.getTables().get("TAB_TO");
			final Table tab1To = schema.getTables().get("TAB_1_TO");
			final Table tab1_1To = schema.getTables().get("TAB_1_1_TO");
			final Table tab1_1_1To = schema.getTables().get("TAB_1_1_1_TO");
			tables.add(tabTo);
			tables.add(tab1To);
			tables.add(tab1_1To);
			tables.add(tab1_1_1To);
			JdbcTreeDataSession session = new JdbcTreeDataSession(connection, tables);
			session.setNewRowInitializer(row -> {
				row.put("CREATED_AT", LocalDateTime.now());
			});
			session.setPreparedStatementBeforeExecuteHandler(statement -> {
				System.out.println(statement);
			});
			System.out.println("---------------------------COPY------------------------------------");
			JdbcTreeDataCopySession copySession = new JdbcTreeDataCopySession(source, session);
			initializer.accept(copySession);
			try (copySession) {
				while (copySession.next(tab)) {
					Row sourceRow = copySession.getRow(tab);
					Row row = copySession.newCopy(sourceRow, tabTo);
					while (copySession.next(tab1)) {
						sourceRow = copySession.getRow(tab1);
						row = copySession.newCopy(sourceRow, tab1To);
						while (copySession.next(tab1_1)) {
							sourceRow = copySession.getRow(tab1_1);
							row = copySession.newCopy(sourceRow, tab1_1To);
							//
							row = copySession.newRow(tab1_1_1To);
							row.put("ROW_NO", 1);
							row.put("TXT", sourceRow.get("TXT1"));
							row = copySession.newRow(tab1_1_1To);
							row.put("ROW_NO", 2);
							row.put("TXT", sourceRow.get("TXT2"));
							row = copySession.newRow(tab1_1_1To);
							row.put("ROW_NO", 3);
							row.put("TXT", sourceRow.get("TXT3"));
						}
					}
				}
			}
			tab.read(connection);
			tab1.read(connection);
			tab1_1.read(connection);
			tabTo.read(connection);
			tab1To.read(connection);
			tab1_1To.read(connection);
			tab1_1_1To.read(connection);
			assertEquals(0, tab.getRows().size());
			assertEquals(rowSize1, tabTo.getRows().size());
			assertEquals(0, tab1.getRows().size());
			assertEquals(rowSize1 * rowSize2, tab1To.getRows().size());
			assertEquals(0, tab1_1.getRows().size());
			assertEquals(rowSize1 * rowSize2 * rowSize3, tab1_1To.getRows().size());
			assertEquals(rowSize1 * rowSize2 * rowSize3 * 3, tab1_1_1To.getRows().size());
		}, (connection) -> {
			this.dropTables(connection, "TAB_1_1");
			this.dropTables(connection, "TAB_1");
			this.dropTables(connection, "TAB");
			this.dropTables(connection, "TAB_1_1_1_TO");
			this.dropTables(connection, "TAB_1_1_TO");
			this.dropTables(connection, "TAB_1_TO");
			this.dropTables(connection, "TAB_TO");
		});
	}

