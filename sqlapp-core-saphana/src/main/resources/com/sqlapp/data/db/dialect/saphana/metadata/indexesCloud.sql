SELECT I.*, IC.*
FROM INDEXES I
LEFT JOIN INDEX_COLUMNS IC ON I.SCHEMA_NAME = IC.SCHEMA_NAME
  AND I.TABLE_NAME = IC.TABLE_NAME AND I.INDEX_NAME = IC.INDEX_NAME
WHERE I.CONSTRAINT IS NULL
  AND I.INDEX_TYPE <> 'FUZZY SEARCH'
  AND NOT EXISTS (SELECT 1 FROM VECTOR_INDEXES V WHERE V.SCHEMA_NAME = I.SCHEMA_NAME
    AND V.TABLE_NAME = I.TABLE_NAME AND V.INDEX_NAME = I.INDEX_NAME)
  /*if isNotEmpty(schemaName)*/
  AND I.SCHEMA_NAME IN /*schemaName;type=NVARCHAR*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND I.TABLE_NAME IN /*tableName;type=NVARCHAR*/('%')
  /*end*/
  /*if isNotEmpty(indexName)*/
  AND I.INDEX_NAME IN /*indexName;type=NVARCHAR*/('%')
  /*end*/
ORDER BY I.SCHEMA_NAME, I.TABLE_NAME, I.INDEX_NAME, IC.POSITION
