SELECT
f.*
, pc.COLUMN_NAME AS TABLE_COLUMN_NAME
, pc.DATA_TYPE_NAME AS TABLE_COLUMN_DATA_TYPE_NAME
, pc.LENGTH AS TABLE_COLUMN_LENGTH
, pc.SCALE AS TABLE_COLUMN_SCALE
, pc.IS_NULLABLE AS TABLE_COLUMN_IS_NULLABLE
FROM FUNCTIONS f
LEFT JOIN FUNCTION_PARAMETERS p
  ON p.SCHEMA_NAME = f.SCHEMA_NAME AND p.FUNCTION_NAME = f.FUNCTION_NAME
 AND p.PARAMETER_TYPE IN ('RETURN', 'OUT') AND p.DATA_TYPE_NAME = 'TABLE_TYPE'
LEFT JOIN FUNCTION_PARAMETER_COLUMNS pc
  ON pc.SCHEMA_NAME = p.SCHEMA_NAME AND pc.FUNCTION_NAME = p.FUNCTION_NAME
 AND pc.PARAMETER_POSITION = p.POSITION
WHERE 1=1
  /*if isNotEmpty(schemaName) */
  AND f.SCHEMA_NAME IN /*schemaName;type=NVARCHAR*/('%')
  /*end*/
  /*if isNotEmpty(functionName) */
  AND f.FUNCTION_NAME IN /*functionName;type=NVARCHAR*/('%')
  /*end*/
ORDER BY f.SCHEMA_NAME, f.FUNCTION_NAME, pc.POSITION
