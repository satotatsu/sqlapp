SELECT t.SCHEMA_NAME, t.TABLE_NAME AS TYPE_NAME
     , c.COLUMN_NAME AS TABLE_COLUMN_NAME
     , c.DATA_TYPE_NAME AS TABLE_COLUMN_DATA_TYPE_NAME
     , c.LENGTH AS TABLE_COLUMN_LENGTH
     , c.SCALE AS TABLE_COLUMN_SCALE
     , c.IS_NULLABLE AS TABLE_COLUMN_IS_NULLABLE
FROM TABLES t
LEFT JOIN TABLE_COLUMNS c ON c.SCHEMA_NAME = t.SCHEMA_NAME AND c.TABLE_NAME = t.TABLE_NAME
WHERE t.IS_USER_DEFINED_TYPE = 'TRUE'
  /*if isNotEmpty(schemaName)*/
  AND t.SCHEMA_NAME IN /*schemaName;type=NVARCHAR*/('%')
  /*end*/
  /*if isNotEmpty(typeName)*/
  AND t.TABLE_NAME IN /*typeName;type=NVARCHAR*/('%')
  /*end*/
ORDER BY t.SCHEMA_NAME, t.TABLE_NAME, c.POSITION
