SELECT
  c.FILE_NAME
, c.SECTION
, c.KEY
, c.FILE_NAME || '/' || c.SECTION || '/' || c.KEY AS SETTING_NAME
, c.LAYER_NAME
, c.VALUE
, c.VALUE AS RAW_VALUE
, c.DEFAULT_VALUE
FROM (
  SELECT
    i.*
  , MAX(CASE WHEN i.LAYER_NAME = 'DEFAULT' THEN i.VALUE END)
      OVER (PARTITION BY i.FILE_NAME, i.SECTION, i.KEY) AS DEFAULT_VALUE
  , ROW_NUMBER() OVER (PARTITION BY i.FILE_NAME, i.SECTION, i.KEY ORDER BY
      CASE i.LAYER_NAME WHEN 'DATABASE' THEN 1 WHEN 'HOST' THEN 2 WHEN 'SYSTEM' THEN 3 ELSE 4 END, i.HOST) AS LAYER_RANK
  FROM M_INIFILE_CONTENTS i
  WHERE 1=1
    /*if isNotEmpty(settingName) */
    AND i.FILE_NAME || '/' || i.SECTION || '/' || i.KEY IN /*settingName;type=NVARCHAR*/('%')
    /*end*/
) c
WHERE c.LAYER_RANK = 1
ORDER BY c.FILE_NAME, c.SECTION, c.KEY
