SELECT
  v.HOST
, v.PORT
, v.FILE_NAME
, v.SECTION
, v.KEY
, v.FILE_NAME || '/' || v.SECTION || '/' || v.KEY AS SETTING_NAME
, v.LAYER_NAME
, v.VALUE
, v.RAW_VALUE
, v.RESTART_REQUIRED
, p.DESCRIPTION
, p.DATA_TYPE_NAME
, p.DEFAULT_VALUE
, p.UNIT
FROM M_CONFIGURATION_PARAMETER_VALUES v
LEFT OUTER JOIN CONFIGURATION_PARAMETER_PROPERTIES p
  ON (p.SECTION = v.SECTION
  AND p.KEY = v.KEY)
WHERE 1=1
  /*if isNotEmpty(settingName) */
  AND v.FILE_NAME || '/' || v.SECTION || '/' || v.KEY IN /*settingName;type=NVARCHAR*/('%')
  /*end*/
ORDER BY v.FILE_NAME, v.SECTION, v.KEY, v.HOST, v.PORT
