SELECT a.SPECIFIC_SCHEMA AS SCHEMA_NAME, a.ROUTINE_NAME AS OBJECT_NAME, a.SPECIFIC_NAME,
 CASE r.ROUTINE_TYPE WHEN 'FUNCTION' THEN 'F' WHEN 'PROCEDURE' THEN 'P' ELSE '?' END AS ROUTINE_KIND,
 a.GRANTOR AS GRANTOR_NAME, CASE a.GRANTEE WHEN '*PUBLIC' THEN 'PUBLIC' ELSE a.GRANTEE END AS GRANTEE_NAME,
 a.PRIVILEGE_TYPE AS PRIVILEGE_NAME,
 CASE a.IS_GRANTABLE WHEN 'YES' THEN 'Y' WHEN 'NO' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 'U' AS GRANTEE_TYPE, CAST(NULL AS CHAR(1)) AS GRANTOR_TYPE, a.AUTHORIZATION_LIST,
 CASE WHEN r.SPECIFIC_NAME IS NULL THEN 'N' ELSE 'Y' END AS RESOLVED_FLAG,
 CAST(NULL AS VARCHAR(128)) AS PACKAGE_COLLECTION, CAST(NULL AS VARCHAR(16)) AS PACKAGE_TOKEN,
 CAST(NULL AS CHAR(1)) AS AUTHHOWGOT
FROM QSYS2.SYSROUTINEAUTH a LEFT JOIN QSYS2.SYSROUTINES r
 ON r.SPECIFIC_SCHEMA=a.SPECIFIC_SCHEMA AND r.SPECIFIC_NAME=a.SPECIFIC_NAME
WHERE 1=1
/*if isNotEmpty(schemaName)*/ AND RTRIM(a.SPECIFIC_SCHEMA) IN /*schemaName*/('%') /*end*/
/*if isNotEmpty(objectName)*/ AND RTRIM(a.ROUTINE_NAME) IN /*objectName*/('%') /*end*/
ORDER BY a.SPECIFIC_SCHEMA,a.SPECIFIC_NAME,a.GRANTEE,a.PRIVILEGE_TYPE
