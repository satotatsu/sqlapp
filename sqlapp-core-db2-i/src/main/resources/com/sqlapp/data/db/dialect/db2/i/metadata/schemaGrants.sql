SELECT a.SCHEMA_NAME,a.GRANTOR AS GRANTOR_NAME,
 CASE a.GRANTEE WHEN '*PUBLIC' THEN 'PUBLIC' ELSE a.GRANTEE END AS GRANTEE_NAME,
 a.PRIVILEGE_TYPE AS PRIVILEGE_NAME,
 CASE a.IS_GRANTABLE WHEN 'YES' THEN 'Y' WHEN 'NO' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 'U' AS GRANTEE_TYPE,CAST(NULL AS CHAR(1)) AS GRANTOR_TYPE,a.AUTHORIZATION_LIST,
 CAST(NULL AS CHAR(1)) AS AUTHHOWGOT
FROM QSYS2.SYSSCHEMAAUTH a WHERE 1=1
/*if isNotEmpty(schemaName)*/ AND RTRIM(a.SCHEMA_NAME) IN /*schemaName*/('%') /*end*/
ORDER BY a.SCHEMA_NAME,a.GRANTEE,a.PRIVILEGE_TYPE
