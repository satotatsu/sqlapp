/* host:routines */
SELECT r.ROUTINE_SCHEMA AS SCHEMA_NAME, r.ROUTINE_NAME, r.SPECIFIC_NAME,
 CASE r.ROUTINE_BODY WHEN 'SQL' THEN 'SQL' ELSE r.EXTERNAL_LANGUAGE END AS LANGUAGE_NAME,
 r.ROUTINE_DEFINITION AS ROUTINE_TEXT,
 CASE r.ROUTINE_BODY WHEN 'SQL' THEN 'S' ELSE 'E' END AS TEXT_KIND,
 r.LONG_COMMENT AS REMARKS, CAST(NULL AS VARCHAR(2048)) AS SQL_PATH,
 r.EXTERNAL_NAME, r.PARAMETER_STYLE, r.SQL_DATA_ACCESS,
 r.IS_DETERMINISTIC AS DETERMINISTIC, CAST(NULL AS VARCHAR(128)) AS NATIVE_VERSION,
 r.FUNCTION_TYPE AS FUNCTION_FORM,
 p.ORDINAL_POSITION AS PARAM_POSITION, p.PARAMETER_NAME AS PARAM_NAME,
 p.ROW_TYPE AS PARAM_ROW_TYPE, p.PARAMETER_MODE AS PARAM_MODE, p.DATA_TYPE AS PARAM_TYPE,
 BIGINT(COALESCE(p.CHARACTER_MAXIMUM_LENGTH,p.NUMERIC_PRECISION)) AS PARAM_LENGTH,
 p.NUMERIC_SCALE AS PARAM_SCALE, p.DATA_TYPE_SCHEMA AS PARAM_TYPE_SCHEMA, p.DATA_TYPE_NAME AS PARAM_TYPE_NAME
FROM QSYS2.SYSROUTINES r LEFT JOIN QSYS2.SYSPARMS p ON p.SPECIFIC_SCHEMA=r.SPECIFIC_SCHEMA AND p.SPECIFIC_NAME=r.SPECIFIC_NAME
WHERE ((/*routineKind*/'P'='P' AND r.ROUTINE_TYPE='PROCEDURE')
 OR (/*routineKind*/'P'='F' AND r.ROUTINE_TYPE='FUNCTION'))

/*if isNotEmpty(schemaName)*/
 AND RTRIM(r.ROUTINE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(procedureName)*/
 AND RTRIM(r.ROUTINE_NAME) IN /*procedureName*/('%')
/*end*/
/*if isNotEmpty(functionName)*/
 AND RTRIM(r.ROUTINE_NAME) IN /*functionName*/('%')
/*end*/
ORDER BY r.ROUTINE_SCHEMA,r.SPECIFIC_NAME,p.ORDINAL_POSITION,p.ROW_TYPE
