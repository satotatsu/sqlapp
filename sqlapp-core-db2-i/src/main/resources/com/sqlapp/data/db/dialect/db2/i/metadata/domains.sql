/* host:domains */
SELECT t.USER_DEFINED_TYPE_SCHEMA AS SCHEMA_NAME, t.USER_DEFINED_TYPE_NAME AS DOMAIN_NAME,
 t.METATYPE, t.SOURCE_SCHEMA, t.SOURCE_TYPE, t.TYPERULES AS TYPE_RULES,
 t.LENGTH AS NATIVE_LENGTH,
 COALESCE(t.CHARACTER_MAXIMUM_LENGTH, CASE WHEN t.SOURCE_TYPE IN ('DECIMAL','NUMERIC') THEN t.NUMERIC_PRECISION ELSE t.LENGTH END) AS TYPE_LENGTH,
 CASE WHEN t.SOURCE_TYPE='TIMESTAMP' THEN t.DATETIME_PRECISION ELSE t.NUMERIC_SCALE END AS TYPE_SCALE,
 t.CCSID, t.NORMALIZE_DATA, t.MAXIMUM_CARDINALITY AS ARRAY_CARDINALITY,
 CAST(NULL AS CHAR(1)) AS SUBTYPE, CAST(NULL AS CHAR(1)) AS ENCODING_SCHEME,
 CAST(NULL AS INTEGER) AS ARRAY_INDEX_TYPE, CAST(NULL AS BIGINT) AS ARRAY_INDEX_LENGTH,
 CAST(NULL AS CHAR(1)) AS ARRAY_INDEX_SUBTYPE, CAST(NULL AS INTEGER) AS INLINE_LENGTH,
 t.CREATE_TIME AS CREATED_AT, t.LONG_COMMENT AS REMARKS
FROM QSYS2.SYSTYPES t WHERE t.METATYPE IN ('T','A')
/*if isNotEmpty(schemaName)*/ AND RTRIM(t.USER_DEFINED_TYPE_SCHEMA) IN /*schemaName*/('%') /*end*/
/*if isNotEmpty(domainName)*/ AND RTRIM(t.USER_DEFINED_TYPE_NAME) IN /*domainName*/('%') /*end*/
ORDER BY t.USER_DEFINED_TYPE_SCHEMA,t.USER_DEFINED_TYPE_NAME
