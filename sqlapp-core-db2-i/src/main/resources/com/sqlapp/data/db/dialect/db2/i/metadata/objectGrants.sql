/* host:objectGrants */
SELECT * FROM (
SELECT a.TABLE_SCHEMA AS SCHEMA_NAME, a.TABLE_NAME AS OBJECT_NAME,
 a.GRANTOR AS GRANTOR_NAME, CASE a.GRANTEE WHEN '*PUBLIC' THEN 'PUBLIC' ELSE a.GRANTEE END AS GRANTEE_NAME,
 a.PRIVILEGE_TYPE AS PRIVILEGE_NAME, CASE a.IS_GRANTABLE WHEN 'YES' THEN 'Y' WHEN 'NO' THEN 'N' ELSE '?' END AS GRANTABLE_FLAG,
 'U' AS GRANTEE_TYPE, CAST(NULL AS CHAR(1)) AS GRANTOR_TYPE, a.AUTHORIZATION_LIST,
 'TABLE' AS OBJECT_KIND,CAST(NULL AS VARCHAR(128)) AS PACKAGE_COLLECTION,
 CAST(NULL AS VARCHAR(16)) AS PACKAGE_TOKEN,CAST(NULL AS CHAR(1)) AS AUTHHOWGOT
FROM QSYS2.SYSTABAUTH a WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(a.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(objectName)*/
 AND RTRIM(a.TABLE_NAME) IN /*objectName*/('%')
/*end*/
UNION ALL
SELECT a.SEQUENCE_SCHEMA,a.SEQUENCE_NAME,a.GRANTOR,
 CASE a.GRANTEE WHEN '*PUBLIC' THEN 'PUBLIC' ELSE a.GRANTEE END,
 a.PRIVILEGE_TYPE,CASE a.IS_GRANTABLE WHEN 'YES' THEN 'Y' WHEN 'NO' THEN 'N' ELSE '?' END,
 'U',CAST(NULL AS CHAR(1)),a.AUTHORIZATION_LIST,'SEQUENCE',CAST(NULL AS VARCHAR(128)),
 CAST(NULL AS VARCHAR(16)),CAST(NULL AS CHAR(1))
FROM QSYS2.SYSSEQUENCEAUTH a WHERE 1=1
/*if isNotEmpty(schemaName)*/ AND RTRIM(a.SEQUENCE_SCHEMA) IN /*schemaName*/('%') /*end*/
/*if isNotEmpty(objectName)*/ AND RTRIM(a.SEQUENCE_NAME) IN /*objectName*/('%') /*end*/
UNION ALL
SELECT a.USER_DEFINED_TYPE_SCHEMA,a.USER_DEFINED_TYPE_NAME,a.GRANTOR,
 CASE a.GRANTEE WHEN '*PUBLIC' THEN 'PUBLIC' ELSE a.GRANTEE END,
 a.PRIVILEGE_TYPE,CASE a.IS_GRANTABLE WHEN 'YES' THEN 'Y' WHEN 'NO' THEN 'N' ELSE '?' END,
 'U',CAST(NULL AS CHAR(1)),a.AUTHORIZATION_LIST,'TYPE',CAST(NULL AS VARCHAR(128)),
 CAST(NULL AS VARCHAR(16)),CAST(NULL AS CHAR(1))
FROM QSYS2.SYSUDTAUTH a WHERE 1=1
/*if isNotEmpty(schemaName)*/ AND RTRIM(a.USER_DEFINED_TYPE_SCHEMA) IN /*schemaName*/('%') /*end*/
/*if isNotEmpty(objectName)*/ AND RTRIM(a.USER_DEFINED_TYPE_NAME) IN /*objectName*/('%') /*end*/
) all_grants
ORDER BY SCHEMA_NAME,OBJECT_NAME,OBJECT_KIND,GRANTEE_NAME,PRIVILEGE_NAME
