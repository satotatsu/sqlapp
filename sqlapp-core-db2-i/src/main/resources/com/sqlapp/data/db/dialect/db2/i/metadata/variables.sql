/* host:variables */
SELECT v.VARIABLE_SCHEMA AS SCHEMA_NAME, v.VARIABLE_NAME,
 v.USER_DEFINED_TYPE_SCHEMA AS UDT_SCHEMA, v.USER_DEFINED_TYPE_NAME AS UDT_NAME,
 v.DATA_TYPE AS TYPE_NAME,
 CASE WHEN v.DATA_TYPE IN ('TIMESTMP','TIMESTAMP') THEN v.DATETIME_PRECISION ELSE v.LENGTH END AS TYPE_LENGTH,
 v.NUMERIC_SCALE AS TYPE_SCALE, v.CCSID AS VARIABLE_CCSID,
 v."DEFAULT" AS DEFAULT_SQL,
 CASE WHEN v.READONLY IS NULL OR v.READONLY='N' THEN '' ELSE 'READONLY ' || v.READONLY END AS UNSUPPORTED_VARIABLE,
 v.LONG_COMMENT AS REMARKS
FROM QSYS2.SYSVARIABLES v WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(v.VARIABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(constantName)*/
 AND RTRIM(v.VARIABLE_NAME) IN /*constantName*/('%')
/*end*/
ORDER BY v.VARIABLE_SCHEMA, v.VARIABLE_NAME
