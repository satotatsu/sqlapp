/* host:triggers */
SELECT t.TRIGGER_SCHEMA AS SCHEMA_NAME, t.TRIGGER_NAME, t.EVENT_OBJECT_SCHEMA AS TABLE_SCHEMA,
 t.EVENT_OBJECT_TABLE AS TABLE_NAME, t.ACTION_STATEMENT AS TRIGGER_TEXT, 'S' AS TEXT_KIND,
 CASE t.ACTION_TIMING WHEN 'INSTEAD' THEN 'INSTEAD OF' ELSE t.ACTION_TIMING END AS ACTION_TIMING,
 t.ACTION_ORIENTATION,
 CASE WHEN t.EVENT_MANIPULATION<>'MULTI' THEN t.EVENT_MANIPULATION ELSE
 TRIM(TRAILING ',' FROM
 (CASE WHEN t.EVENTINSERT IN ('Y','YES') THEN 'INSERT,' ELSE '' END ||
 CASE WHEN t.EVENTUPDATE IN ('Y','YES') THEN 'UPDATE,' ELSE '' END ||
 CASE WHEN t.EVENTDELETE IN ('Y','YES') THEN 'DELETE,' ELSE '' END)) END AS EVENT_NAMES,
 t.ACTION_REFERENCE_OLD_ROW AS OLD_ROW, t.ACTION_REFERENCE_NEW_ROW AS NEW_ROW,
 t.ACTION_REFERENCE_OLD_TABLE AS OLD_TABLE, t.ACTION_REFERENCE_NEW_TABLE AS NEW_TABLE,
 t.SQL_PATH, t.ACTION_CONDITION AS WHEN_TEXT, t.TRIGGER_MODE, VARCHAR(t.ACTION_ORDER) AS ACTION_ORDER,
 CAST(NULL AS VARCHAR(128)) AS NATIVE_VERSION, t.ENABLED AS ENABLED_FLAG, t.CREATED AS CREATED_AT,
 CAST(NULL AS VARCHAR(2000)) AS REMARKS
FROM QSYS2.SYSTRIGGERS t WHERE 1=1

/*if isNotEmpty(schemaName)*/
 AND RTRIM(t.TRIGGER_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(triggerName)*/
 AND RTRIM(t.TRIGGER_NAME) IN /*triggerName*/('%')
/*end*/
ORDER BY t.EVENT_OBJECT_SCHEMA,t.EVENT_OBJECT_TABLE,t.ACTION_ORDER,t.TRIGGER_NAME
