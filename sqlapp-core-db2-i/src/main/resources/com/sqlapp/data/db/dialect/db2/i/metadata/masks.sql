SELECT c.RCAC_SCHEMA AS SCHEMA_NAME, c.RCAC_NAME AS CONTROL_NAME, c.TABLE_SCHEMA, c.TABLE_NAME,
 c.TBCORRELATION AS CORRELATION_NAME, c.COLUMN_NAME, c.ENABLE AS ENABLE_FLAG, 'Y' AS VALID_FLAG,
 c.RULETEXT, c.LONG_COMMENT AS REMARKS
FROM QSYS2.SYSCONTROLS c
WHERE c.CONTROL_TYPE='M'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(c.RCAC_SCHEMA) IN /*schemaName*/('%')
/*end*/
ORDER BY c.RCAC_SCHEMA, c.RCAC_NAME
