SELECT c.TABLE_SCHEMA AS SCHEMA_NAME, c.TABLE_NAME, c.CONSTRAINT_NAME, k.CHECK_CLAUSE AS CHECK_TEXT,
 CASE c.ENABLED WHEN 'NO' THEN 'N' ELSE 'Y' END AS ENFORCED,
 CASE WHEN k.INSERT_ACTION IS NOT NULL OR k.UPDATE_ACTION IS NOT NULL THEN 'VIOLATION ACTION'
 WHEN c.CHECK_PENDING='YES' THEN 'CHECK PENDING' ELSE '' END AS UNSUPPORTED_CHECK
FROM QSYS2.SYSCST c JOIN QSYS2.SYSCHKCST k ON k.CONSTRAINT_SCHEMA=c.CONSTRAINT_SCHEMA AND k.CONSTRAINT_NAME=c.CONSTRAINT_NAME
WHERE c.CONSTRAINT_TYPE='CHECK'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(c.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(c.TABLE_NAME) IN /*tableName*/('%')
/*end*/
ORDER BY c.TABLE_SCHEMA,c.TABLE_NAME,c.CONSTRAINT_NAME
