SELECT i.TABLE_SCHEMA AS SCHEMA_NAME, i.TABLE_NAME, i.INDEX_SCHEMA, i.INDEX_NAME,
 CASE i.IS_UNIQUE WHEN 'D' THEN 'N' ELSE 'Y' END AS UNIQUE_FLAG,
 CASE i.IS_UNIQUE WHEN 'V' THEN 'Y' ELSE 'N' END AS UNIQUE_WHERE_NOT_NULL,
 i.COLUMN_COUNT AS KEY_COUNT, k.ORDINAL_POSITION AS KEY_POSITION, k.COLUMN_NAME, k.ORDERING AS COLUMN_ORDER,
 CASE WHEN k.COLUMN_POSITION IS NULL THEN k.KEY_EXPRESSION END AS KEY_EXPRESSION,
 'N' AS KEY_INCLUDE,
 CASE WHEN i.INDEX_HAS_SEARCH_CONDITION='Y' THEN i.SEARCH_CONDITION END AS WHERE_TEXT,
 CASE WHEN i.IS_SPANNING_INDEX IS NULL THEN CAST(NULL AS CHAR(1))
  WHEN i.IS_SPANNING_INDEX='YES' THEN 'N' WHEN i.IS_SPANNING_INDEX='NO' THEN 'Y' ELSE 'X' END AS PARTITIONED_FLAG,
 i.LONG_COMMENT AS REMARKS,
 CASE WHEN i.IS_UNIQUE NOT IN ('D','U','V') THEN 'ENCODED VECTOR OR SPECIAL UNIQUENESS'
 WHEN i.INDEX_HAS_INCLUDE_EXPRESSION='Y' THEN 'INCLUDE AGGREGATE'
 WHEN i.INDEX_HAS_SEARCH_CONDITION='Y' AND i.SEARCH_CONDITION IS NULL THEN 'MISSING SEARCH CONDITION'
 WHEN k.COLUMN_POSITION IS NULL AND k.KEY_EXPRESSION IS NULL THEN 'MISSING KEY EXPRESSION' ELSE '' END AS UNSUPPORTED_INDEX
FROM QSYS2.SYSINDEXES i LEFT JOIN QSYS2.SYSKEYS k ON k.INDEX_SCHEMA=i.INDEX_SCHEMA AND k.INDEX_NAME=i.INDEX_NAME
WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(i.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(i.TABLE_NAME) IN /*tableName*/('%')
/*end*/
ORDER BY i.TABLE_SCHEMA,i.TABLE_NAME,i.INDEX_SCHEMA,i.INDEX_NAME,k.ORDINAL_POSITION
