SELECT t.TABLE_SCHEMA AS SCHEMA_NAME, t.TABLE_NAME, t.TABLE_TEXT AS REMARKS,
 t.SYSTEM_TABLE_NAME AS SYSTEM_NAME, t.CONTROL AS ACCESS_CONTROL,
 p.PERIOD_NAME, p.BEGIN_COLUMN_NAME AS PERIOD_BEGIN, p.END_COLUMN_NAME AS PERIOD_END,
 CASE WHEN p.HISTORY_TABLE_NAME IS NOT NULL THEN t.TABLE_SCHEMA END AS HISTORY_SCHEMA,
 p.HISTORY_TABLE_NAME AS HISTORY_TABLE, p.VERSIONING_STATUS,
 CASE p.ON_DELETE_ADD_EXTRA_ROW WHEN 'YES' THEN 'Y' ELSE 'N' END AS VERSIONING_EXTRA_ROW,
 s.PARTITION_TYPE, st.PARTITIONING_KEYS AS PARTITION_KEYS, s.TABLE_PARTITION AS PARTITION_NAME,
 s.PARTITION_NUMBER, s.LOWINCLUSIVE AS PARTITION_LOW_INCLUSIVE, s.LOWVALUE AS PARTITION_LOW_VALUE,
 s.HIGHINCLUSIVE AS PARTITION_HIGH_INCLUSIVE, s.HIGHVALUE AS PARTITION_HIGH_VALUE,
 CASE WHEN t.PARTITION_TABLE='DISTRIBUTED' THEN 'DISTRIBUTED TABLE'
 WHEN p.PERIOD_TYPE IS NOT NULL AND p.PERIOD_TYPE<>'S' THEN 'APPLICATION PERIOD'
 WHEN t.PARTITION_TABLE<>'NO' AND s.PARTITION_TYPE NOT IN ('R','H') THEN 'PARTITIONING ' || s.PARTITION_TYPE
 ELSE '' END AS UNSUPPORTED_TABLE
FROM QSYS2.SYSTABLES t
LEFT JOIN QSYS2.SYSPERIODS p ON p.TABLE_SCHEMA=t.TABLE_SCHEMA AND p.TABLE_NAME=t.TABLE_NAME
LEFT JOIN QSYS2.SYSTABLESTAT st ON t.PARTITION_TABLE<>'NO'
 AND st.TABLE_SCHEMA=t.TABLE_SCHEMA AND st.TABLE_NAME=t.TABLE_NAME
LEFT JOIN QSYS2.SYSPARTITIONSTAT s ON t.PARTITION_TABLE<>'NO'
 AND s.TABLE_SCHEMA=t.TABLE_SCHEMA AND s.TABLE_NAME=t.TABLE_NAME
WHERE t.TABLE_TYPE='T'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(t.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(t.TABLE_NAME) IN /*tableName*/('%')
/*end*/
ORDER BY t.TABLE_SCHEMA, t.TABLE_NAME, s.PARTITION_NUMBER
