SELECT c.TABLE_SCHEMA AS SCHEMA_NAME, c.TABLE_NAME, c.COLUMN_NAME,
 c.DATA_TYPE AS TYPE_NAME,
 CASE WHEN c.DATA_TYPE='TIMESTMP' THEN c.DATETIME_PRECISION ELSE c.LENGTH END AS TYPE_LENGTH,
 c.NUMERIC_SCALE AS TYPE_SCALE,
 c.USER_DEFINED_TYPE_SCHEMA AS UDT_SCHEMA, c.USER_DEFINED_TYPE_NAME AS UDT_NAME,
 CASE c.IS_NULLABLE WHEN 'YES' THEN 'Y' ELSE 'N' END AS NULLABLE,
 c.COLUMN_TEXT AS REMARKS, c.COLUMN_DEFAULT AS DEFAULT_SQL,
 CASE WHEN c.IS_IDENTITY='YES' THEN CASE c.IDENTITY_GENERATION WHEN 'ALWAYS' THEN 'A' ELSE 'D' END ELSE '' END AS IDENTITY_MODE,
 CASE c.HAS_DEFAULT WHEN 'Q' THEN 'ROW_BEGIN' WHEN 'R' THEN 'ROW_END' WHEN 'X' THEN 'TRANSACTION_START_ID'
  WHEN 'E' THEN 'ROW_CHANGE_ALWAYS' WHEN 'F' THEN 'ROW_CHANGE_DEFAULT' ELSE '' END AS GENERATION_KIND,
 CASE c.HIDDEN WHEN 'N' THEN 'N' WHEN 'P' THEN 'Y' ELSE 'X' END AS HIDDEN_FLAG,
 c.CCSID AS COLUMN_CCSID,
 CASE WHEN c.HAS_DEFAULT IN ('Q','R','X','E','F') THEN ''
      WHEN c.IS_IDENTITY='NO' AND c.IDENTITY_GENERATION IS NOT NULL THEN c.IDENTITY_GENERATION
      WHEN c.COLUMN_EXPRESSION IS NOT NULL THEN 'EXPRESSION' ELSE '' END AS UNSUPPORTED_GENERATION,
 c.IDENTITY_START, c.IDENTITY_INCREMENT, c.IDENTITY_MINIMUM, c.IDENTITY_MAXIMUM,
 CASE c.IDENTITY_CYCLE WHEN 'YES' THEN 'Y' ELSE 'N' END AS IDENTITY_CYCLE,
 c.IDENTITY_CACHE, CASE c.IDENTITY_ORDER WHEN 'YES' THEN 'Y' ELSE 'N' END AS IDENTITY_ORDER
FROM QSYS2.SYSCOLUMNS c WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(c.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(c.TABLE_NAME) IN /*tableName*/('%')
/*end*/
ORDER BY c.TABLE_SCHEMA, c.TABLE_NAME, c.ORDINAL_POSITION
