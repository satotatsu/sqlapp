/* host:sequences */
SELECT s.SEQUENCE_SCHEMA AS SCHEMA_NAME, s.SEQUENCE_NAME, s.DATA_TYPE AS SEQUENCE_TYPE,
 s.NUMERIC_PRECISION AS TYPE_PRECISION, CAST(NULL AS VARCHAR(20)) AS NATIVE_TYPE_ID,
 s.START AS START_VALUE, s.INCREMENT AS INCREMENT_VALUE, s.MINIMUM_VALUE, s.MAXIMUM_VALUE,
 CASE s.CYCLE_OPTION WHEN 'YES' THEN 'Y' ELSE 'N' END AS CYCLE_FLAG,
 CASE s.ORDER WHEN 'YES' THEN 'Y' ELSE 'N' END AS ORDER_FLAG, s.CACHE AS CACHE_SIZE, s.LONG_COMMENT AS REMARKS
FROM QSYS2.SYSSEQUENCES s WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(s.SEQUENCE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(sequenceName)*/
 AND RTRIM(s.SEQUENCE_NAME) IN /*sequenceName*/('%')
/*end*/
ORDER BY s.SEQUENCE_SCHEMA,s.SEQUENCE_NAME
