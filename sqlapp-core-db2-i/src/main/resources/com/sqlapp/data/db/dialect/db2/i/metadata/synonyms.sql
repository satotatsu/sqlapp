/* host:synonyms */
SELECT t.TABLE_SCHEMA AS SCHEMA_NAME, t.TABLE_NAME AS SYNONYM_NAME,
 t.BASE_TABLE_SCHEMA AS TARGET_SCHEMA, t.BASE_TABLE_NAME AS TARGET_NAME,
 CASE WHEN RTRIM(t.BASE_TABLE_CATALOG) IN (CURRENT SERVER,'*LOCAL') THEN NULL
 ELSE NULLIF(RTRIM(t.BASE_TABLE_CATALOG),'') END AS TARGET_LOCATION,
 'TABLE' AS ALIAS_TYPE, 'ALIAS' AS NAME_KIND, t.BASE_TABLE_MEMBER AS MEMBER_NAME,
 t.BASE_TABLE_CATALOG AS BASE_CATALOG, CAST(NULL AS TIMESTAMP) AS CREATED_AT,
 t.LAST_ALTERED_TIMESTAMP AS ALTERED_AT, t.LONG_COMMENT AS REMARKS
FROM QSYS2.SYSTABLES t WHERE t.TABLE_TYPE='A'
/*if isNotEmpty(schemaName)*/
 AND RTRIM(t.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(synonymName)*/
 AND RTRIM(t.TABLE_NAME) IN /*synonymName*/('%')
/*end*/
ORDER BY t.TABLE_SCHEMA,t.TABLE_NAME
