SELECT k.TABLE_SCHEMA AS SCHEMA_NAME, k.TABLE_NAME, k.CONSTRAINT_NAME, k.COLUMN_NAME,
 p.TABLE_SCHEMA AS REF_SCHEMA_NAME, p.TABLE_NAME AS REF_TABLE_NAME, p.COLUMN_NAME AS REF_COLUMN_NAME,
 r.DELETE_RULE, r.UPDATE_RULE, CASE c.ENABLED WHEN 'YES' THEN 'Y' ELSE 'N' END AS ENFORCED
FROM QSYS2.SYSREFCST r JOIN QSYS2.SYSKEYCST k
 ON k.CONSTRAINT_SCHEMA=r.CONSTRAINT_SCHEMA AND k.CONSTRAINT_NAME=r.CONSTRAINT_NAME
JOIN QSYS2.SYSCST c ON c.CONSTRAINT_SCHEMA=r.CONSTRAINT_SCHEMA AND c.CONSTRAINT_NAME=r.CONSTRAINT_NAME
 AND c.TABLE_SCHEMA=k.TABLE_SCHEMA AND c.TABLE_NAME=k.TABLE_NAME
LEFT JOIN QSYS2.SYSKEYCST p ON p.CONSTRAINT_SCHEMA=r.UNIQUE_CONSTRAINT_SCHEMA
 AND p.CONSTRAINT_NAME=r.UNIQUE_CONSTRAINT_NAME AND p.ORDINAL_POSITION=k.ORDINAL_POSITION
WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(k.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(k.TABLE_NAME) IN /*tableName*/('%')
/*end*/
ORDER BY k.TABLE_SCHEMA, k.TABLE_NAME, k.CONSTRAINT_NAME, k.ORDINAL_POSITION
