SELECT v.TABLE_SCHEMA AS SCHEMA_NAME, v.TABLE_NAME, v.VIEW_DEFINITION AS VIEW_TEXT,
 'S' AS TEXT_KIND, v.CHECK_OPTION, CAST(NULL AS VARCHAR(2048)) AS SQL_PATH, t.LONG_COMMENT AS REMARKS
FROM QSYS2.SYSVIEWS v JOIN QSYS2.SYSTABLES t ON t.TABLE_SCHEMA=v.TABLE_SCHEMA AND t.TABLE_NAME=v.TABLE_NAME WHERE 1=1
/*if isNotEmpty(schemaName)*/
 AND RTRIM(v.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(v.TABLE_NAME) IN /*tableName*/('%')
/*end*/
ORDER BY v.TABLE_SCHEMA,v.TABLE_NAME
