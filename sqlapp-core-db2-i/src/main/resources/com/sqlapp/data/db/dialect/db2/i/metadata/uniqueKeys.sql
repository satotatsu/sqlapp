SELECT c.TABLE_SCHEMA AS SCHEMA_NAME, c.TABLE_NAME, c.CONSTRAINT_NAME,
 CASE c.CONSTRAINT_TYPE WHEN 'PRIMARY KEY' THEN 'P' ELSE 'U' END AS KEY_TYPE, k.COLUMN_NAME
FROM QSYS2.SYSCST c JOIN QSYS2.SYSKEYCST k
 ON k.CONSTRAINT_SCHEMA=c.CONSTRAINT_SCHEMA AND k.CONSTRAINT_NAME=c.CONSTRAINT_NAME
 AND k.TABLE_SCHEMA=c.TABLE_SCHEMA AND k.TABLE_NAME=c.TABLE_NAME
WHERE c.CONSTRAINT_TYPE IN ('PRIMARY KEY','UNIQUE')
/*if isNotEmpty(schemaName)*/
 AND RTRIM(c.TABLE_SCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(tableName)*/
 AND RTRIM(c.TABLE_NAME) IN /*tableName*/('%')
/*end*/
ORDER BY c.TABLE_SCHEMA, c.TABLE_NAME, c.CONSTRAINT_NAME, k.ORDINAL_POSITION
