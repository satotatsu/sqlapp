	@FunctionalInterface
	private interface MetadataCall {
		Object invoke(String method, Object[] args) throws Exception;
	}

	private Connection fixture(String methodName, List<Map<String, Object>> data) {
		return connection(metadata((method, args) -> {
			assertEquals(methodName, method);
			return rows(data);
		}));
	}

	private DatabaseMetaData metadata(MetadataCall call) {
		return (DatabaseMetaData) Proxy.newProxyInstance(getClass().getClassLoader(),
				new Class<?>[] { DatabaseMetaData.class }, (proxy, method, args) -> switch (method.getName()) {
				case "getDatabaseProductName" -> "JDBC test";
				case "getDatabaseProductVersion" -> "1.0";
				case "getDatabaseMajorVersion" -> 1;
				case "getDatabaseMinorVersion" -> 0;
				case "storesUpperCaseIdentifiers", "storesLowerCaseIdentifiers" -> false;
				default -> call.invoke(method.getName(), args);
				});
	}

	private Connection connection(DatabaseMetaData metadata) {
		return (Connection) Proxy.newProxyInstance(getClass().getClassLoader(), new Class<?>[] { Connection.class },
				(proxy, method, args) -> {
					if (method.getName().equals("getMetaData"))
						return metadata;
					throw new UnsupportedOperationException(method.getName());
				});
	}

	private static Map<String, Object> row(Object... values) {
		Map<String, Object> row = new LinkedHashMap<>();
		for (int i = 0; i < values.length; i += 2)
			row.put((String) values[i], values[i + 1]);
		return row;
	}

	private ResultSet rows(List<Map<String, Object>> data) throws Exception {
		Set<String> names = new LinkedHashSet<>();
		for (var row : data)
			names.addAll(row.keySet());
		if (names.isEmpty())
			names.add("EMPTY");
		List<String> columns = new ArrayList<>(names);
		var metadata = new RowSetMetaDataImpl();
		metadata.setColumnCount(columns.size());
		for (int i = 0; i < columns.size(); i++) {
			String name = columns.get(i);
			Object sample = data.stream().map(row -> row.get(name)).filter(Objects::nonNull).findFirst().orElse(null);
			metadata.setColumnName(i + 1, name);
			metadata.setColumnLabel(i + 1, name);
			metadata.setColumnType(i + 1, sample instanceof Number ? Types.INTEGER
					: sample instanceof Boolean ? Types.BOOLEAN : Types.VARCHAR);
		}
		var result = RowSetProvider.newFactory().createCachedRowSet();
		result.setMetaData(metadata);
		for (int r = data.size() - 1; r >= 0; r--) {
			result.moveToInsertRow();
			for (int i = 0; i < columns.size(); i++)
				result.updateObject(i + 1, data.get(r).get(columns.get(i)));
			result.insertRow();
			result.moveToCurrentRow();
		}
		result.beforeFirst();
		return result;
	}
