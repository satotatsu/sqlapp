	@Test
	void preservesAnonymousForeignKeysAndCompositeOrder() throws Exception {
		var keys = new JdbcForeignKeyConstraintReader(dialect).doGetAll(
				fixture("getImportedKeys",
						List.of(foreignKey(null, "P1", "B", 1), foreignKey(null, "P2", "C", 1),
								foreignKey("COMPOSITE", "P1", "B", 2), foreignKey("COMPOSITE", "P1", "A", 1))),
				tableContext("T"), null);
		assertEquals(3, keys.size());
		assertNull(keys.get(0).getName());
		assertEquals("P1", keys.get(0).getRelatedTable().getName());
		assertEquals("P2", keys.get(1).getRelatedTable().getName());
		assertEquals(List.of("A", "B"), keys.get(2).getColumns().stream().map(c -> c.getName()).toList());
		Table child = new Table("T").setCatalogName("CAT").setSchemaName("S");
		child.getColumns().add("A");
		child.getColumns().add("B");
		child.getColumns().add("C");
		child.getConstraints().addAll(keys);
		assertEquals(3, child.getConstraints().getForeignKeyConstraints().size());
		Table restored = SchemaUtils.readXml(new java.io.StringReader(child.asXml()));
		assertEquals(3, restored.getConstraints().getForeignKeyConstraints().size());
	}

