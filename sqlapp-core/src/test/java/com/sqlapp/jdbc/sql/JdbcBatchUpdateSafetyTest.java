package com.sqlapp.jdbc.sql;

import static org.junit.jupiter.api.Assertions.*;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.atomic.AtomicInteger;

import org.junit.jupiter.api.Test;

import com.sqlapp.data.parameter.ParametersContext;
import com.sqlapp.jdbc.sql.node.SqlNode;

class JdbcBatchUpdateSafetyTest {

	private SqlNode parse(String sql) {
		return SqlParser.getInstance().parse(null, sql);
	}

	private Connection database() throws SQLException {
		Connection connection = DriverManager.getConnection("jdbc:hsqldb:mem:" + UUID.randomUUID(), "sa", "");
		try (var statement = connection.createStatement()) {
			statement.execute("CREATE TABLE t (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v INTEGER, tenant INTEGER)");
		}
		return connection;
	}

	@Test
	void rejectsDynamicTemplatesBeforeAccessingTheConnection() {
		for (String sql : List.of("UPDATE t SET v=1 /*if flag*/ WHERE id=1 /*end*/",
				"DELETE FROM t WHERE id IN /*ids*/(0)", "/*for x:items*/ /*x*/0 /*end*/",
				"SELECT /*# value */", "SELECT /*include 'part'*/")) {
			JdbcBatchUpdateHandler handler = new JdbcBatchUpdateHandler(parse(sql));
			IllegalArgumentException error = assertThrows(IllegalArgumentException.class,
					() -> handler.execute(null, List.of(Map.of())));
			assertTrue(error.getMessage().contains("setEvaluateSqlPerRow(true)"));
		}
	}

	@Test
	void fixedTemplatesRefreshBindingsAcrossBatchBoundaries() throws Exception {
		SqlNode template = parse("INSERT INTO t(v) VALUES (/*v*/0)");
		JdbcBatchUpdateHandler handler = new JdbcBatchUpdateHandler(template);
		try (Connection connection = database()) {
			handler.setBatchSize(2);
			handler.execute(connection, List.of(Map.of("v", 11), Map.of("v", 22), Map.of("v", 33)));
			assertEquals(3, handler.getUpdateCount());
			try (var statement = connection.createStatement(); ResultSet rows = statement.executeQuery("SELECT SUM(v) FROM t")) {
				assertTrue(rows.next());
				assertEquals(66, rows.getInt(1));
			}
		}
	}

	@Test
	void dynamicModeFlushesOnSqlChangesAndKeepsTheCorrectWhereClause() throws Exception {
		SqlNode node = parse("UPDATE t SET v=/*v*/0 WHERE id=/*id*/0 /*if scoped*/ AND tenant=/*tenant*/0 /*end*/");
		JdbcBatchUpdateHandler handler = new JdbcBatchUpdateHandler(node);
		handler.setEvaluateSqlPerRow(true);
		handler.setBatchSize(2);
		try (Connection connection = database()) {
			try (var statement = connection.createStatement()) {
				statement.executeUpdate("INSERT INTO t(id,v,tenant) VALUES (1,0,1),(2,0,2),(3,0,1),(4,0,1)");
			}
			handler.execute(connection, List.of(
					Map.of("id", 1, "v", 11, "scoped", false),
					Map.of("id", 2, "v", 22, "scoped", true, "tenant", 1),
					Map.of("id", 3, "v", 33, "scoped", true, "tenant", 1),
					Map.of("id", 4, "v", 44, "scoped", false)));
			assertEquals(3, handler.getUpdateCount());
			try (var statement = connection.createStatement(); ResultSet rows = statement.executeQuery("SELECT v FROM t ORDER BY id")) {
				for (int expected : new int[] { 11, 0, 33, 44 }) {
					assertTrue(rows.next());
					assertEquals(expected, rows.getInt(1));
				}
				assertFalse(rows.next());
			}
		}
	}

	@Test
	void configuredGeneratedKeyHandlersSurviveContextAndBatchExecution() throws Exception {
		AtomicInteger calls = new AtomicInteger();
		SqlNode node = parse("INSERT INTO t(v) VALUES (/*v*/0)");
		GeneratedKeyHandler keys = (row, info) -> calls.incrementAndGet();
		try (Connection connection = database()) {
			JdbcHandler single = new JdbcHandler(node, keys);
			single.execute(connection, Map.of("v", 1));
			ParametersContext context = new ParametersContext();
			context.put("v", 2);
			single.execute(connection, context);
			assertEquals(2, calls.get());
			JdbcBatchUpdateHandler batch = new JdbcBatchUpdateHandler(node, keys);
			batch.setBatchSize(2);
			batch.execute(connection, List.of(Map.of("v", 3), Map.of("v", 4), Map.of("v", 5)));
			assertEquals(5, calls.get());
		}
	}

	@Test
	void dynamicParameterOperatorsRequireExplicitEvaluation() {
		ParametersContext context = new ParametersContext();
		context.putOperatorValue("id", SqlComparisonOperator.GT, 1);
		JdbcBatchUpdateHandler handler = new JdbcBatchUpdateHandler(parse("DELETE FROM t WHERE id=/*id*/0"));
		assertThrows(IllegalArgumentException.class, () -> handler.execute(null, List.of(context)));
	}

	@Test
	void dynamicListsCanChangeTheirNumberOfBindVariables() throws Exception {
		JdbcBatchUpdateHandler handler = new JdbcBatchUpdateHandler(parse("DELETE FROM t WHERE id IN /*ids*/(0)"));
		handler.setEvaluateSqlPerRow(true);
		try (Connection connection = database()) {
			try (var statement = connection.createStatement()) {
				statement.executeUpdate("INSERT INTO t(id,v) VALUES (1,11),(2,22),(3,33),(4,44)");
			}
			handler.execute(connection, List.of(Map.of("ids", List.of(1)), Map.of("ids", List.of(2, 3))));
			assertEquals(3, handler.getUpdateCount());
			try (var statement = connection.createStatement(); ResultSet rows = statement.executeQuery("SELECT id FROM t")) {
				assertTrue(rows.next());
				assertEquals(4, rows.getInt(1));
				assertFalse(rows.next());
			}
		}
	}

	@Test
	void dynamicBatchFailurePropagatesAndRemainsRollbackable() throws Exception {
		JdbcBatchUpdateHandler handler = new JdbcBatchUpdateHandler(parse("INSERT INTO t(id,v) VALUES (/*id*/0, /*v*/0)"));
		handler.setEvaluateSqlPerRow(true);
		handler.setBatchSize(2);
		try (Connection connection = database()) {
			connection.setAutoCommit(false);
			assertThrows(SQLException.class, () -> handler.execute(connection,
					List.of(Map.of("id", 1, "v", 11), Map.of("id", 2, "v", 22), Map.of("id", 1, "v", 33))));
			connection.rollback();
			try (var statement = connection.createStatement(); ResultSet rows = statement.executeQuery("SELECT COUNT(*) FROM t")) {
				assertTrue(rows.next());
				assertEquals(0, rows.getInt(1));
			}
		}
	}

	@Test
	void batchSizeOneEvaluatesDynamicSqlWithoutOptIn() throws Exception {
		JdbcBatchUpdateHandler handler = new JdbcBatchUpdateHandler(parse(
				"INSERT INTO t(v) VALUES (/*if flag*/ /*v*/0\n-- else 99\n/*end*/)"));
		handler.setBatchSize(1);
		try (Connection connection = database()) {
			handler.execute(connection, List.of(Map.of("flag", true, "v", 11), Map.of("flag", false)));
			assertEquals(2, handler.getUpdateCount());
			try (var statement = connection.createStatement(); ResultSet rows = statement.executeQuery("SELECT SUM(v) FROM t")) {
				assertTrue(rows.next());
				assertEquals(110, rows.getInt(1));
			}
		}
	}
}
