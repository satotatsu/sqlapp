package com.sqlapp.data.db.dialect.hsql.metadata;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.sql.DriverManager;
import java.util.HashMap;
import java.util.Map;

import org.junit.jupiter.api.Test;

class HsqlIdentityRestartsTest {

	@Test
	void parsesPlainAndQuotedIdentifiersOnly() {
		Map<String, Long> result = new HashMap<>();
		HsqlIdentityRestarts.parse("ALTER TABLE PUBLIC.T ALTER COLUMN ID RESTART WITH 12", result);
		HsqlIdentityRestarts.parse("ALTER TABLE PUBLIC.\"My \"\"T\"\"\" ALTER COLUMN \"Id x\" RESTART WITH -3", result);
		HsqlIdentityRestarts.parse("ALTER SEQUENCE PUBLIC.SQ RESTART WITH 100", result);
		HsqlIdentityRestarts.parse(null, result);
		assertEquals(Map.of(HsqlIdentityRestarts.key("PUBLIC", "T", "ID"), 12L,
				HsqlIdentityRestarts.key("PUBLIC", "My \"T\"", "Id x"), -3L), result);
	}

	@Test
	void nonAdministratorsGetNoValues() throws Exception {
		String url = "jdbc:hsqldb:mem:identity-restarts-" + java.util.UUID.randomUUID();
		try (var admin = DriverManager.getConnection(url, "SA", ""); var statement = admin.createStatement()) {
			statement.execute("CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY, V INT)");
			statement.execute("INSERT INTO T(V) VALUES(1)");
			statement.execute("CREATE USER READER PASSWORD 'r'");
			statement.execute("GRANT SELECT ON T TO READER");
			assertEquals(1L, HsqlIdentityRestarts.read(admin).get(HsqlIdentityRestarts.key("PUBLIC", "T", "ID")));
			try (var reader = DriverManager.getConnection(url, "READER", "r")) {
				assertEquals(Map.of(), HsqlIdentityRestarts.read(reader));
			}
		}
	}
}
