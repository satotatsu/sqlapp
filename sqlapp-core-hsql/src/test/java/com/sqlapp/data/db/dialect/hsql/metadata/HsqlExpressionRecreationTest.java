package com.sqlapp.data.db.dialect.hsql.metadata;

import static org.junit.jupiter.api.Assertions.*;
import java.sql.DriverManager;
import org.junit.jupiter.api.Test;
import com.sqlapp.data.db.dialect.DialectResolver;
import com.sqlapp.data.db.sql.SqlType;
import com.sqlapp.data.schemas.Schema;
import com.sqlapp.data.schemas.SchemaUtils;

class HsqlExpressionRecreationTest {
	@Test
	void generatedAndDefaultExpressionsOrderFunctionsAndSequencesBeforeTables() throws Exception {
		try (var connection = DriverManager.getConnection("jdbc:hsqldb:mem:expression-order", "SA", "");
				var statement = connection.createStatement()) {
			statement.execute("CREATE SCHEMA APP AUTHORIZATION DBA");
			statement.execute("CREATE SEQUENCE APP.S START WITH 5");
			statement.execute(
					"CREATE FUNCTION APP.\"Adjust.Value\"(V INTEGER) RETURNS INTEGER DETERMINISTIC RETURN V * 2");
			statement.execute(
					"CREATE TABLE APP.T (ID INTEGER GENERATED BY DEFAULT AS SEQUENCE APP.S, SEED INTEGER DEFAULT 42, G INTEGER GENERATED ALWAYS AS (APP.\"Adjust.Value\"(ID)))");
			var dialect = DialectResolver.getInstance().getDialect(connection);
			var reader = dialect.getCatalogReader().getSchemaReader();
			reader.setSchemaName("APP");
			var schema = reader.getAllFull(connection).get(0);
			Schema restored = SchemaUtils.readXml(new java.io.StringReader(schema.asXml()));
			var operations = dialect.createSqlFactoryRegistry().createSql(restored, SqlType.CREATE);
			try (var target = DriverManager.getConnection("jdbc:hsqldb:mem:expression-order-target", "SA", "");
					var targetStatement = target.createStatement()) {
				for (var operation : operations)
					targetStatement.execute(operation.getSqlText());
				targetStatement.execute("INSERT INTO APP.T DEFAULT VALUES");
				try (var rs = targetStatement.executeQuery("SELECT ID, SEED, G FROM APP.T")) {
					assertTrue(rs.next());
					assertEquals(5, rs.getInt(1));
					assertEquals(42, rs.getInt(2));
					assertEquals(10, rs.getInt(3));
				}
				try (var rs = targetStatement.executeQuery("VALUES NEXT VALUE FOR APP.S")) {
					assertTrue(rs.next());
					assertEquals(6, rs.getInt(1));
				}
			}
		}
	}
}
