package com.sqlapp.data.db.dialect.hsql;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import org.junit.jupiter.api.Test;

import com.sqlapp.data.db.datatype.DataType;
import com.sqlapp.data.db.dialect.Dialect;
import com.sqlapp.data.db.dialect.DialectResolver;
import com.sqlapp.data.db.sql.SqlFactory;
import com.sqlapp.data.db.sql.SqlType;
import com.sqlapp.data.parameter.ParametersContext;
import com.sqlapp.data.schemas.Table;
import com.sqlapp.data.schemas.SchemaUtils;

/**
 * Regression tests for the HSQL dialect review: column definitions and identity
 * state must survive a metadata read followed by DDL regeneration, and
 * application selects must honour paging.
 */
class HsqlReviewRegressionTest {

	@Test
	void intervalPrecisionAndFractionalSecondsSurviveRecreation() throws Exception {
		Map<String, String> recreated = recreate(
				"CREATE TABLE T(A INTERVAL SECOND(4,9), B INTERVAL DAY(3) TO SECOND(2),"
						+ " C INTERVAL HOUR(5) TO MINUTE, D INTERVAL MINUTE TO SECOND(3), E INTERVAL YEAR(4) TO MONTH)");
		assertEquals("INTERVAL SECOND(4,9)", recreated.get("A"));
		assertEquals("INTERVAL DAY(3) TO SECOND(2)", recreated.get("B"));
		assertEquals("INTERVAL HOUR(5) TO MINUTE", recreated.get("C"));
		assertEquals("INTERVAL MINUTE TO SECOND(3)", recreated.get("D"));
		assertEquals("INTERVAL YEAR(4) TO MONTH", recreated.get("E"));
	}

	@Test
	void intervalSecondValueFitsRecreatedColumn() throws Exception {
		try (Connection source = open(); Connection target = open()) {
			execute(source, "CREATE TABLE T(A INTERVAL SECOND(4,9))");
			Table table = read(source);
			assertEquals(DataType.INTERVAL_SECOND, table.getColumns().get("A").getDataType());
			assertEquals(9, table.getColumns().get("A").getScale());
			createIn(target, table);
			execute(target, "INSERT INTO T VALUES(INTERVAL '1234.123456789' SECOND(4,9))");
		}
	}

	@Test
	void fixedLengthBinaryIsDistinguishedFromVarbinary() throws Exception {
		Map<String, String> recreated = recreate("CREATE TABLE T(A BINARY(4), B VARBINARY(4))");
		assertEquals("BINARY(4)", recreated.get("A"));
		assertEquals("VARBINARY(4)", recreated.get("B"));
		try (Connection source = open()) {
			execute(source, "CREATE TABLE T(A BINARY(4))");
			assertEquals(DataType.BINARY, read(source).getColumns().get("A").getDataType());
		}
	}

	@Test
	void identityNextValueIsNotReusedAfterRecreation() throws Exception {
		try (Connection source = open(); Connection target = open()) {
			execute(source,
					"CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY(START WITH 10) PRIMARY KEY, V INT)");
			execute(source, "INSERT INTO T(V) VALUES(1)");
			execute(source, "INSERT INTO T(V) VALUES(2)");
			execute(source, "DELETE FROM T WHERE ID=11");
			Table table = read(source);
			assertEquals(12L, table.getColumns().get("ID").getIdentityLastValue());
			assertEquals(10L, table.getColumns().get("ID").getIdentityStartValue());
			createIn(target, table);
			execute(target, "INSERT INTO T(ID,V) VALUES(10,1)");
			execute(target, "INSERT INTO T(V) VALUES(3)");
			assertEquals(List.of(10, 12), ids(target, "SELECT ID FROM T ORDER BY ID"));
		}
	}

	@Test
	void unusedIdentityKeepsItsStartValue() throws Exception {
		try (Connection source = open()) {
			execute(source, "CREATE TABLE T(ID INT GENERATED ALWAYS AS IDENTITY(START WITH 5) PRIMARY KEY)");
			var column = read(source).getColumns().get("ID");
			assertEquals(5L, column.getIdentityStartValue());
			assertNull(column.getIdentityLastValue());
		}
	}

	@Test
	void selectForAppAppliesOffsetAndFetch() throws Exception {
		try (Connection connection = open()) {
			execute(connection, "CREATE TABLE T(ID INT PRIMARY KEY, LABEL VARCHAR(10))");
			execute(connection, "INSERT INTO T VALUES(1,'a'),(2,'b'),(3,'c'),(4,'d'),(5,'e')");
			Table table = read(connection);
			var node = dialect(connection).createSqlFactoryRegistry().createSqlNodes(table, SqlType.SELECT_FOR_APP)
					.get(0);
			assertEquals(List.of(2, 3), select(connection, node, table, 2, 1));
			assertEquals(List.of(1, 2), select(connection, node, table, 2, null));
			assertEquals(List.of(3, 4, 5), select(connection, node, table, null, 2));
			assertEquals(List.of(1, 2, 3, 4, 5), select(connection, node, table, null, null));
		}
	}

	private static List<Integer> select(Connection connection, com.sqlapp.jdbc.sql.node.SqlNode node, Table table,
			Integer rows, Integer offset) throws Exception {
		var context = new ParametersContext(table);
		context.put("_orderBy", "ID");
		if (rows != null)
			context.put("_row", rows);
		if (offset != null)
			context.put("_offset", offset);
		try (var parameters = node.eval(context); var query = parameters.createStatement(connection)) {
			parameters.setBind(query);
			try (var result = query.executeQuery()) {
				var ids = new ArrayList<Integer>();
				while (result.next())
					ids.add(result.getInt(1));
				return ids;
			}
		}
	}

	/**
	 * Reads table T from a source DB, recreates it elsewhere and returns the target
	 * column types.
	 */
	private static Map<String, String> recreate(String ddl) throws Exception {
		try (Connection source = open(); Connection target = open()) {
			execute(source, ddl);
			createIn(target, read(source));
			Map<String, String> source_types = columnTypes(source);
			Map<String, String> target_types = columnTypes(target);
			assertEquals(source_types, target_types);
			return target_types;
		}
	}

	private static Connection open() throws SQLException {
		return DriverManager.getConnection("jdbc:hsqldb:mem:review-" + UUID.randomUUID(), "SA", "");
	}

	private static Dialect dialect(Connection connection) {
		return DialectResolver.getInstance().getDialect(connection);
	}

	private static Table read(Connection connection) throws Exception {
		return SchemaUtils.getSchema(connection, "PUBLIC", "T").orElseThrow().getTables().get("T");
	}

	private static void createIn(Connection target, Table table) throws Exception {
		SqlFactory<Table> factory = dialect(target).createSqlFactoryRegistry().getSqlFactory(table, SqlType.CREATE);
		var operations = factory.createSql(table);
		for (var operation : operations)
			execute(target, operation.getSqlText());
	}

	private static Map<String, String> columnTypes(Connection connection) throws SQLException {
		Map<String, String> types = new LinkedHashMap<>();
		try (var statement = connection.createStatement();
				var rs = statement.executeQuery(
						"SELECT COLUMN_NAME, DTD_IDENTIFIER FROM INFORMATION_SCHEMA.COLUMNS WHERE TABLE_NAME='T' ORDER BY ORDINAL_POSITION")) {
			while (rs.next())
				types.put(rs.getString(1), rs.getString(2));
		}
		return types;
	}

	private static List<Integer> ids(Connection connection, String sql) throws SQLException {
		var ids = new ArrayList<Integer>();
		try (var statement = connection.createStatement(); var rs = statement.executeQuery(sql)) {
			while (rs.next())
				ids.add(rs.getInt(1));
		}
		return ids;
	}

	private static void execute(Connection connection, String sql) throws SQLException {
		try (var statement = connection.createStatement()) {
			statement.execute(sql);
		}
	}
}
