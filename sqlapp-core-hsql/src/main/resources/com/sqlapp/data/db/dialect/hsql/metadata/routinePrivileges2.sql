WITH families AS (
 SELECT ROUTINE_SCHEMA, ROUTINE_NAME, COUNT(*) AS overload_count
 FROM INFORMATION_SCHEMA.ROUTINES
 GROUP BY ROUTINE_SCHEMA, ROUTINE_NAME
), granted AS (
 SELECT GRANTOR, GRANTEE, ROUTINE_SCHEMA, ROUTINE_NAME, PRIVILEGE_TYPE, IS_GRANTABLE,
        COUNT(DISTINCT SPECIFIC_NAME) AS granted_count
 FROM INFORMATION_SCHEMA.ROUTINE_PRIVILEGES
 GROUP BY GRANTOR, GRANTEE, ROUTINE_SCHEMA, ROUTINE_NAME, PRIVILEGE_TYPE, IS_GRANTABLE
)
SELECT r.*, CASE WHEN g.granted_count = f.overload_count THEN 'YES' ELSE 'NO' END AS FAMILY_COMPLETE
FROM INFORMATION_SCHEMA.ROUTINE_PRIVILEGES r
JOIN families f ON f.ROUTINE_SCHEMA=r.ROUTINE_SCHEMA AND f.ROUTINE_NAME=r.ROUTINE_NAME
JOIN granted g ON g.GRANTOR=r.GRANTOR AND g.GRANTEE=r.GRANTEE
 AND g.ROUTINE_SCHEMA=r.ROUTINE_SCHEMA AND g.ROUTINE_NAME=r.ROUTINE_NAME
 AND g.PRIVILEGE_TYPE=r.PRIVILEGE_TYPE AND g.IS_GRANTABLE=r.IS_GRANTABLE
WHERE r.GRANTEE NOT IN ('_SYSTEM', 'DBA', 'CREATE_SCHEMA', 'CHANGE_AUTHORIZATION', 'SCRIPT_OPS')
 /*if isNotEmpty(catalogName)*/
 AND r.ROUTINE_CATALOG IN /*catalogName*/('%')
 /*end*/
 /*if isNotEmpty(schemaName)*/
 AND r.ROUTINE_SCHEMA IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(objectName)*/
 AND r.ROUTINE_NAME IN /*objectName*/('%')
 /*end*/
ORDER BY r.GRANTOR,r.GRANTEE,r.ROUTINE_SCHEMA,r.ROUTINE_NAME,r.SPECIFIC_NAME
