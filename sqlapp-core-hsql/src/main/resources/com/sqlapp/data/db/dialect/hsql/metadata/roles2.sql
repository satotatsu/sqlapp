SELECT a.AUTHORIZATION_NAME AS ROLE_NAME, 'NO' AS IS_GRANTABLE,
       CAST(NULL AS VARCHAR(128)) AS GRANTEE
FROM INFORMATION_SCHEMA.AUTHORIZATIONS a
WHERE a.AUTHORIZATION_TYPE = 'ROLE'
  /*if isNotEmpty(roleName) */
  AND a.AUTHORIZATION_NAME IN /*roleName*/('%')
  /*end*/
ORDER BY a.AUTHORIZATION_NAME
