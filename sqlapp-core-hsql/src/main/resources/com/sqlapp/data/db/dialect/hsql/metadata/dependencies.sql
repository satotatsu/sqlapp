SELECT * FROM (
 SELECT 'ROUTINE' AS OBJECT_KIND, SPECIFIC_SCHEMA AS OBJECT_SCHEMA, SPECIFIC_NAME AS OBJECT_NAME,
        'RELATION' AS REFERENCED_KIND, TABLE_SCHEMA AS REFERENCED_SCHEMA, TABLE_NAME AS REFERENCED_NAME
 FROM INFORMATION_SCHEMA.ROUTINE_TABLE_USAGE
 UNION
 SELECT 'ROUTINE', SPECIFIC_SCHEMA, SPECIFIC_NAME, 'ROUTINE', ROUTINE_SCHEMA, ROUTINE_NAME
 FROM INFORMATION_SCHEMA.ROUTINE_ROUTINE_USAGE
 UNION
 SELECT 'ROUTINE', SPECIFIC_SCHEMA, SPECIFIC_NAME, 'Sequence', SEQUENCE_SCHEMA, SEQUENCE_NAME
 FROM INFORMATION_SCHEMA.ROUTINE_SEQUENCE_USAGE
 UNION
 SELECT 'RELATION', VIEW_SCHEMA, VIEW_NAME, 'RELATION', TABLE_SCHEMA, TABLE_NAME
 FROM INFORMATION_SCHEMA.VIEW_TABLE_USAGE
 UNION
 SELECT 'RELATION', VIEW_SCHEMA, VIEW_NAME, 'ROUTINE', SPECIFIC_SCHEMA, SPECIFIC_NAME
 FROM INFORMATION_SCHEMA.VIEW_ROUTINE_USAGE
) D
WHERE 1=1
/*if isNotEmpty(schemaName)*/
AND OBJECT_SCHEMA = /*schemaName*/'PUBLIC'
/*end*/
ORDER BY OBJECT_KIND, OBJECT_SCHEMA, OBJECT_NAME, REFERENCED_KIND, REFERENCED_SCHEMA, REFERENCED_NAME
