SELECT
  LOCATION_ID
  , NODE_NAME
  , LOCATION_PATH
  , LOCATION_USAGE
  , LOCATION_LABEL
FROM V_CATALOG.STORAGE_LOCATIONS
WHERE LOCATION_LABEL IS NOT NULL
  AND LOCATION_LABEL <> ''
  /*if isNotEmpty(tableSpaceName)*/
  AND LOCATION_LABEL IN /*tableSpaceName*/('%')
  /*end*/
ORDER BY LOCATION_LABEL, NODE_NAME, LOCATION_PATH
