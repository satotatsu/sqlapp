package com.sqlapp.data.db.dialect.test.oracle;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.sql.Connection;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import com.sqlapp.data.db.dialect.test.GeneratedKeyCounterAssertions;
import com.sqlapp.data.db.dialect.test.ReusableTestcontainers;
import com.sqlapp.data.schemas.Column;
import com.sqlapp.data.schemas.Table;
import com.sqlapp.jdbc.bulk.GeneratedKeyCounters;
import org.testcontainers.oracle.OracleContainer;

/**
 * Raises an Oracle identity past imported keys with a restated identity clause.
 */
class OracleGeneratedKeyCounterTest {
	private static final OracleContainer ORACLE = ReusableTestcontainers
			.configure(new OracleContainer(OracleTestEnvironment.image()));

	@BeforeAll
	static void startContainer() {
		ReusableTestcontainers.start(ORACLE);
	}

	@AfterAll
	static void stopContainer() {
		ReusableTestcontainers.stop(ORACLE);
	}

	@Test
	void raisesIdentity() throws Exception {
		try (Connection connection = ORACLE.createConnection(""); var statement = connection.createStatement()) {
			try {
				statement.execute("DROP TABLE KEY_COUNTER_T PURGE");
			} catch (java.sql.SQLException ignored) {
				// absent on a fresh container
			}
			statement.execute(
					"CREATE TABLE KEY_COUNTER_T(ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, V NUMBER(10))");
			GeneratedKeyCounterAssertions.assertRaisesPastImportedKeys(connection, new Table("KEY_COUNTER_T"),
					new Column("ID").setIdentity(true), false,
					"INSERT INTO KEY_COUNTER_T(ID, V) SELECT 5, 1 FROM DUAL UNION ALL SELECT 42, 2 FROM DUAL",
					"INSERT INTO KEY_COUNTER_T(V) VALUES (3)", "SELECT ID FROM KEY_COUNTER_T WHERE V = 3");
			statement.execute("CREATE TABLE KEY_COUNTER_PLAIN(ID NUMBER(10) PRIMARY KEY)");
			assertEquals(GeneratedKeyCounters.Action.NO_GENERATOR, GeneratedKeyCounters.synchronize(connection,
					new Table("KEY_COUNTER_PLAIN"), new Column("ID").setIdentity(true), 10L, false).action());
			statement.execute("DROP TABLE KEY_COUNTER_PLAIN PURGE");
		}
	}
}
