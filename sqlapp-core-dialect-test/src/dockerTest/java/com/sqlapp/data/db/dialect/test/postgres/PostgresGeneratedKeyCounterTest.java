package com.sqlapp.data.db.dialect.test.postgres;

import static org.junit.jupiter.api.Assertions.assertEquals;

import java.sql.Connection;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import com.sqlapp.data.db.dialect.test.GeneratedKeyCounterAssertions;
import com.sqlapp.data.db.dialect.test.ReusableTestcontainers;
import com.sqlapp.data.schemas.Column;
import com.sqlapp.data.schemas.Table;
import com.sqlapp.jdbc.bulk.GeneratedKeyCounters;

/** Raises PostgreSQL 18 identity and serial generators past imported keys. */
class PostgresGeneratedKeyCounterTest {
	private static final org.testcontainers.postgresql.PostgreSQLContainer POSTGRES = ReusableTestcontainers
			.configure(new org.testcontainers.postgresql.PostgreSQLContainer("postgres:18.4"));

	@BeforeAll
	static void startContainer() {
		ReusableTestcontainers.start(POSTGRES);
	}

	@AfterAll
	static void stopContainer() {
		ReusableTestcontainers.stop(POSTGRES);
	}

	private static Connection connection() throws Exception {
		return POSTGRES.createConnection("");
	}

	@Test
	void raisesIdentityAndSerialGenerators() throws Exception {
		try (var connection = connection(); var statement = connection.createStatement()) {
			statement.execute("DROP SCHEMA IF EXISTS key_counter CASCADE");
			statement.execute("CREATE SCHEMA key_counter");
			statement.execute(
					"CREATE TABLE key_counter.identity_t(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, v INT)");
			statement.execute("CREATE TABLE key_counter.serial_t(id SERIAL PRIMARY KEY, v INT)");
			for (String name : new String[] { "identity_t", "serial_t" })
				GeneratedKeyCounterAssertions.assertRaisesPastImportedKeys(connection,
						new Table(name).setSchemaName("key_counter"), new Column("id").setIdentity(true), false,
						"INSERT INTO key_counter." + name + "(id, v) VALUES (5, 1), (42, 2)",
						"INSERT INTO key_counter." + name + "(v) VALUES (3)",
						"SELECT id FROM key_counter." + name + " WHERE v = 3");
			statement.execute("CREATE TABLE key_counter.plain_t(id INT PRIMARY KEY)");
			assertEquals(GeneratedKeyCounters.Action.NO_GENERATOR,
					GeneratedKeyCounters.synchronize(connection, new Table("plain_t").setSchemaName("key_counter"),
							new Column("id").setIdentity(true), 10L, false).action());
		}
	}
}
