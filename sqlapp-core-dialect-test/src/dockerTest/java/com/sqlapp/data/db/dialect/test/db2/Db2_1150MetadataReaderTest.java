package com.sqlapp.data.db.dialect.test.db2;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNotNull;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Locale;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import com.sqlapp.data.db.datatype.DataType;
import com.sqlapp.data.db.dialect.Dialect;
import com.sqlapp.data.db.dialect.DialectResolver;
import com.sqlapp.data.db.dialect.db2.Db2_1150;
import com.sqlapp.data.db.dialect.test.ReusableTestcontainers;
import com.sqlapp.data.schemas.Schema;
import com.sqlapp.data.schemas.PartitioningType;
import com.sqlapp.data.schemas.Table;

/** Db2 11.5 compatibility coverage for the full metadata reader tree. */
class Db2_1150MetadataReaderTest {
	private static final SqlReadyDb2Container DB2 = new SqlReadyDb2Container(
			"icr.io/db2_community/db2:11.5.8.0");

	@BeforeAll
	static void startContainer() {
		DB2.start();
	}

	@AfterAll
	static void stopContainer() {
		if (!ReusableTestcontainers.isReuseEnabled()) {
			DB2.stop();
		}
	}

	@Test
	void testMetadataReaderOperatesOnDb2_11_5() throws SQLException {
		try (Connection connection = DB2.createConnection("");
				Statement statement = connection.createStatement()) {
			drop(statement, "DROP VIEW METADATA_COMPAT_VIEW");
			drop(statement, "DROP TABLE METADATA_COMPAT_CHILD");
			drop(statement, "DROP TABLE METADATA_COMPAT_PARENT");
			drop(statement, "DROP TABLE METADATA_COMPAT_PARTITIONED");
			drop(statement, "DROP TABLE METADATA_COMPAT_MDC");
			drop(statement, "DROP TABLE METADATA_COMPAT_TYPED");
			drop(statement, "DROP TYPE METADATA_COMPAT_ADDRESS");
			drop(statement, "DROP TYPE METADATA_COMPAT_MONEY");
			drop(statement, "DROP SEQUENCE METADATA_COMPAT_SEQ");
			statement.execute("""
					CREATE DISTINCT TYPE METADATA_COMPAT_MONEY
					 AS DECIMAL(18, 2) WITH COMPARISONS
					""");
			statement.execute("""
					CREATE TYPE METADATA_COMPAT_ADDRESS AS (
					 STREET VARCHAR(100), POSTAL_CODE CHAR(5)) MODE DB2SQL
					""");
			statement.execute("""
					CREATE TABLE METADATA_COMPAT_PARENT (
					 ID BIGINT NOT NULL PRIMARY KEY, NAME VARCHAR(100))
					""");
			statement.execute("""
					CREATE TABLE METADATA_COMPAT_CHILD (
					 ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					 PARENT_ID BIGINT NOT NULL, AMOUNT DECIMAL(18,2),
					 CONSTRAINT CK_METADATA_COMPAT CHECK (AMOUNT >= 0),
					 CONSTRAINT FK_METADATA_COMPAT FOREIGN KEY (PARENT_ID)
					 REFERENCES METADATA_COMPAT_PARENT(ID))
					""");
			statement.execute("CREATE INDEX IDX_METADATA_COMPAT ON METADATA_COMPAT_CHILD(PARENT_ID)");
			statement.execute("CREATE SEQUENCE METADATA_COMPAT_SEQ START WITH 1");
			statement.execute("""
					CREATE TABLE METADATA_COMPAT_PARTITIONED (
					 ID BIGINT NOT NULL, BUCKET INTEGER NOT NULL)
					 PARTITION BY RANGE (BUCKET) (
					  PARTITION P_LOW STARTING FROM (MINVALUE) ENDING AT (99) INCLUSIVE,
					  PARTITION P_HIGH STARTING FROM (100) INCLUSIVE ENDING AT (MAXVALUE))
					""");
			statement.execute("CREATE VIEW METADATA_COMPAT_VIEW AS SELECT ID, PARENT_ID FROM METADATA_COMPAT_CHILD");
			statement.execute("""
					CREATE TABLE METADATA_COMPAT_MDC (
					 REGION CHAR(2) NOT NULL, BUCKET INTEGER NOT NULL,
					 PAYLOAD VARCHAR(100))
					 ORGANIZE BY DIMENSIONS (REGION, BUCKET)
					""");
			statement.execute("""
					CREATE TABLE METADATA_COMPAT_TYPED (
					 ID BIGINT NOT NULL PRIMARY KEY,
					 AMOUNT METADATA_COMPAT_MONEY)
					""");

			Dialect dialect = DialectResolver.getInstance().getDialect(connection);
			assertInstanceOf(Db2_1150.class, dialect);
			String schemaName = DB2.getUsername().toUpperCase(Locale.ROOT);
			var schemaReader = dialect.getCatalogReader().getSchemaReader();
			schemaReader.setSchemaName(schemaName);
			Schema schema = schemaReader.getAllFull(connection).stream()
					.filter(current -> schemaName.equalsIgnoreCase(current.getName()))
					.findFirst().orElseThrow();
			Table child = schema.getTables().get("METADATA_COMPAT_CHILD");
			assertNotNull(child);
			assertNotNull(child.getConstraints().get("CK_METADATA_COMPAT"));
			assertNotNull(child.getConstraints().get("FK_METADATA_COMPAT"));
			assertNotNull(child.getIndexes().get("IDX_METADATA_COMPAT"));
			assertNotNull(schema.getSequences().get("METADATA_COMPAT_SEQ"));
			assertNotNull(schema.getViews().get("METADATA_COMPAT_VIEW"));
			Table partitioned = schema.getTables()
					.get("METADATA_COMPAT_PARTITIONED");
			assertNotNull(partitioned);
			assertEquals(PartitioningType.Range,
					partitioned.getPartitioning().getPartitioningType());
			assertEquals(2, partitioned.getPartitioning().getPartitions().size());
			Table mdc = schema.getTables().get("METADATA_COMPAT_MDC");
			assertNotNull(mdc);
			assertEquals("C", mdc.getColumns().get("REGION")
					.getSpecifics().get("TYPE"));
			assertNotNull(mdc.getColumns().get("REGION")
					.getSpecifics().get("DIMENSION"));
			assertNotNull(mdc.getColumns().get("BUCKET")
					.getSpecifics().get("DIMENSION"));
			var money = schema.getDomains().get("METADATA_COMPAT_MONEY");
			assertNotNull(money);
			assertEquals(DataType.DECIMAL, money.getDataType());
			assertEquals("METADATA_COMPAT_MONEY", schema.getTables()
					.get("METADATA_COMPAT_TYPED").getColumns().get("AMOUNT")
					.getDataTypeName());
			var address = schema.getTypes().get("METADATA_COMPAT_ADDRESS");
			assertNotNull(address);
			assertEquals(2, address.getColumns().size());
			assertEquals(DataType.VARCHAR,
					address.getColumns().get("STREET").getDataType());
		}
	}

	private void drop(final Statement statement, final String sql)
			throws SQLException {
		try {
			statement.execute(sql);
		} catch (SQLException e) {
			if (!"42704".equals(e.getSQLState())) {
				throw e;
			}
		}
	}
}
