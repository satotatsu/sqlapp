package com.sqlapp.data.db.dialect.postgres.sql;

import static org.junit.jupiter.api.Assertions.*;

import org.junit.jupiter.api.Test;

import com.sqlapp.data.db.datatype.DataType;
import com.sqlapp.data.db.dialect.postgres.DialectHolder;
import com.sqlapp.data.db.sql.SqlType;
import com.sqlapp.data.schemas.Column;
import com.sqlapp.data.schemas.IdentityGenerationType;
import com.sqlapp.data.schemas.Table;

class PostgresIdentityRestartSqlTest {
	@Test
	void identityKeepsOptionsAndRestartsAtTheNextValue() {
		var table = new Table("t");
		table.getColumns()
				.add(new Column("id").setDataType(DataType.BIGINT).setIdentity(true)
						.setIdentityGenerationType(IdentityGenerationType.ByDefault).setIdentityStartValue(1)
						.setIdentityStep(5).setIdentityLastValue(41L));
		var sql = DialectHolder.postgreSQL180.createSqlFactoryRegistry().createSql(table, SqlType.CREATE);
		assertTrue(sql.get(0).getSqlText().contains("GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 5)"),
				sql.get(0).getSqlText());
		assertTrue(sql.stream().anyMatch(o -> o.getSqlText().equals("ALTER TABLE t ALTER COLUMN id RESTART WITH 41")),
				sql.toString());
	}

	@Test
	void serialRestartsItsOwnedSequence() {
		var table = new Table("t");
		table.getColumns().add(new Column("id").setDataType(DataType.INT).setIdentity(true).setIdentityLastValue(7L));
		var sql = DialectHolder.postgreSQL180.createSqlFactoryRegistry().createSql(table, SqlType.CREATE);
		assertTrue(sql.get(0).getSqlText().contains("serial"), sql.get(0).getSqlText());
		assertTrue(
				sql.stream().anyMatch(
						o -> o.getSqlText().equals("SELECT setval(pg_get_serial_sequence('t', 'id'), 7, false)")),
				sql.toString());
	}

	@Test
	void noRestartWithoutANewNextValue() {
		var table = new Table("t");
		table.getColumns()
				.add(new Column("id").setDataType(DataType.BIGINT).setIdentity(true)
						.setIdentityGenerationType(IdentityGenerationType.Always).setIdentityStartValue(10)
						.setIdentityLastValue(10L));
		var sql = DialectHolder.postgreSQL180.createSqlFactoryRegistry().createSql(table, SqlType.CREATE);
		assertEquals(1, sql.size(), sql.toString());
		assertTrue(sql.get(0).getSqlText().contains("GENERATED ALWAYS AS IDENTITY (START WITH 10)"),
				sql.get(0).getSqlText());
	}
}
