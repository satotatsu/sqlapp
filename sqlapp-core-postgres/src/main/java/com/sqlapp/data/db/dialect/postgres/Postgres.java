	/**
	 * Returns {@code default} for {@code GENERATED BY DEFAULT AS IDENTITY} columns.
	 * Returns {@code null} for {@code GENERATED ALWAYS AS IDENTITY} and serial
	 * columns, so that generated INSERT statements leave the column out and the
	 * database generates the value. Inserting an explicit value into an ALWAYS
	 * column needs {@code OVERRIDING SYSTEM VALUE} (see
	 * {@code PostgresBulkUpsertExecutor}).
	 */
	@Override
	public String getIdentityInsertDefaultValue(Column column) {
		if (column.getIdentityGenerationType() == IdentityGenerationType.ByDefault) {
			return "default";
		}
		return null;
	}

