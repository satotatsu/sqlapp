SELECT
  D.OWNER
, D.NAME AS DOMAIN_NAME
, D.DATA_DISPLAY
, D.DATA_ORDER
, C.DATA_TYPE
, C.DATA_LENGTH
, C.DATA_PRECISION
, C.DATA_SCALE
, C.CHAR_LENGTH
, C.NULLABLE
, C.DATA_DEFAULT
, C.DEFAULT_ON_NULL
, C.EXACT
, DC.NAME AS CONSTRAINT_NAME
, DC.SEARCH_CONDITION
, DC.DEFERRABLE
, DC.DEFERRED
FROM ALL_DOMAINS D
INNER JOIN ALL_DOMAIN_COLS C
  ON D.OWNER=C.OWNER
 AND D.NAME=C.DOMAIN_NAME
 AND C.COLUMN_ID=1
 AND C.DATA_TYPE_ID=1
LEFT JOIN
(
  SELECT X.*
  FROM
  (
    SELECT
      C.*
    , ROW_NUMBER() OVER
      (
        PARTITION BY C.DOMAIN_OWNER, C.DOMAIN_NAME
        ORDER BY C.NAME
      ) AS RN
    FROM ALL_DOMAIN_CONSTRAINTS C
    WHERE C.SEARCH_CONDITION IS NOT NULL
  ) X
  WHERE X.RN=1
) DC
  ON D.OWNER=DC.DOMAIN_OWNER
 AND D.NAME=DC.DOMAIN_NAME
WHERE D.COLS=1
  /*if isNotEmpty(schemaName)*/
  AND D.OWNER IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(domainName)*/
  AND D.NAME IN /*domainName*/('%')
  /*end*/
ORDER BY D.OWNER, D.NAME
