SELECT
 J.OWNER, J.JOB_NAME, J.JOB_CREATOR, J.JOB_TYPE, J.JOB_ACTION, J.ENABLED, J.COMMENTS,
 J.PROGRAM_OWNER, J.PROGRAM_NAME, J.NUMBER_OF_ARGUMENTS,
 J.SCHEDULE_OWNER, J.SCHEDULE_NAME, J.REPEAT_INTERVAL, J.JOB_CLASS,
 J.AUTO_DROP, J.RESTARTABLE, J.STATE, J.JOB_PRIORITY, J.MAX_RUNS, J.MAX_FAILURES,
 J.DESTINATION, J.NLS_ENV,
 A.ARGUMENT_NAME, A.ARGUMENT_POSITION, A.ARGUMENT_TYPE, A.VALUE AS ARGUMENT_VALUE, A.OUT_ARGUMENT,
 CASE WHEN A.ANYDATA_VALUE IS NULL THEN 'FALSE' ELSE 'TRUE' END AS HAS_ANYDATA_VALUE,
 TO_CHAR(J.START_DATE, 'YYYY-MM-DD"T"HH24:MI:SS.FF6 TZR TZH:TZM', 'NLS_DATE_LANGUAGE=American') AS START_DATE_TEXT,
 TO_CHAR(J.END_DATE, 'YYYY-MM-DD"T"HH24:MI:SS.FF6 TZR TZH:TZM', 'NLS_DATE_LANGUAGE=American') AS END_DATE_TEXT,
 TO_CHAR(J.LAST_START_DATE, 'YYYY-MM-DD"T"HH24:MI:SS.FF6 TZR TZH:TZM', 'NLS_DATE_LANGUAGE=American') AS LAST_START_DATE_TEXT,
 TO_CHAR(J.NEXT_RUN_DATE, 'YYYY-MM-DD"T"HH24:MI:SS.FF6 TZR TZH:TZM', 'NLS_DATE_LANGUAGE=American') AS NEXT_RUN_DATE_TEXT
FROM ALL_SCHEDULER_JOBS J
LEFT OUTER JOIN ALL_SCHEDULER_JOB_ARGS A ON A.OWNER=J.OWNER AND A.JOB_NAME=J.JOB_NAME
WHERE 1=1
 /*if isNotEmpty(schemaName)*/
 AND J.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(eventName)*/
 AND J.JOB_NAME IN /*eventName*/('%')
 /*end*/
ORDER BY J.OWNER, J.JOB_NAME, A.ARGUMENT_POSITION
