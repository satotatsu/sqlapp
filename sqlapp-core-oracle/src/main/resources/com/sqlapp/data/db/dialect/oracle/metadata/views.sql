SELECT
  V.*
, O.*
, C.COMMENTS
, R.ORACLE_CHECK_CONSTRAINT
, R.ORACLE_READ_ONLY_CONSTRAINT
FROM ALL_VIEWS V
INNER JOIN ALL_OBJECTS O
ON (V.OWNER=O.OWNER
    AND
    V.VIEW_NAME=O.OBJECT_NAME
    AND
    O.OBJECT_TYPE='VIEW')
LEFT OUTER JOIN (
  SELECT OWNER, TABLE_NAME
  , MAX(DECODE(CONSTRAINT_TYPE, 'V', CONSTRAINT_NAME)) AS ORACLE_CHECK_CONSTRAINT
  , MAX(DECODE(CONSTRAINT_TYPE, 'O', CONSTRAINT_NAME)) AS ORACLE_READ_ONLY_CONSTRAINT
  FROM ALL_CONSTRAINTS
  WHERE CONSTRAINT_TYPE IN ('V', 'O')
  GROUP BY OWNER, TABLE_NAME
) R ON (V.OWNER=R.OWNER AND V.VIEW_NAME=R.TABLE_NAME)
LEFT OUTER JOIN ALL_TAB_COMMENTS C
ON (V.OWNER=C.OWNER
    AND
    V.VIEW_NAME=C.TABLE_NAME
    AND
    C.TABLE_TYPE='VIEW'
    AND
    C.COMMENTS IS NOT NULL)
WHERE 1=1
  /*if isNotEmpty(schemaName)*/
  AND V.OWNER IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND V.VIEW_NAME IN /*tableName*/('%')
  /*end*/
ORDER BY V.OWNER, V.VIEW_NAME
