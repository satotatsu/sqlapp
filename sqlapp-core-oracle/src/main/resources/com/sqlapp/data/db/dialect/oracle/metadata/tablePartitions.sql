SELECT 
PT.OWNER AS schema_name
, PT.*
, TP.*
, IP.TABLESPACE_NAME AS IOT_TABLESPACE_NAME
FROM ALL_PART_TABLES PT
INNER JOIN ALL_TAB_PARTITIONS TP
  ON (PT.OWNER=TP.TABLE_OWNER
  AND PT.TABLE_NAME=TP.TABLE_NAME)
LEFT OUTER JOIN ALL_INDEXES IX
  ON IX.TABLE_OWNER=PT.OWNER AND IX.TABLE_NAME=PT.TABLE_NAME AND IX.INDEX_TYPE='IOT - TOP'
LEFT OUTER JOIN ALL_IND_PARTITIONS IP
  ON IP.INDEX_OWNER=IX.OWNER AND IP.INDEX_NAME=IX.INDEX_NAME
  AND IP.PARTITION_POSITION=TP.PARTITION_POSITION
WHERE 1=1 
  /*if isNotEmpty(schemaName)*/
  AND PT.OWNER IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND PT.TABLE_NAME IN /*tableName*/('%')
  /*end*/
ORDER BY PT.OWNER, PT.TABLE_NAME, TP.PARTITION_POSITION
