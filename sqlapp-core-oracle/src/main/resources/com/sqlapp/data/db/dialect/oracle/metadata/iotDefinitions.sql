SELECT A.OWNER, A.TABLE_NAME,
 DBMS_METADATA.GET_DDL('TABLE', A.TABLE_NAME, A.OWNER) AS TABLE_DEFINITION
FROM ALL_TABLES A
WHERE (A.IOT_TYPE='IOT' OR EXISTS (
 SELECT 1 FROM ALL_PART_TABLES P
 WHERE P.OWNER=A.OWNER AND P.TABLE_NAME=A.TABLE_NAME
 AND P.SUBPARTITIONING_TYPE <> 'NONE'
))
 /*if isNotEmpty(schemaName)*/
 AND A.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(tableName)*/
 AND A.TABLE_NAME IN /*tableName*/('%')
 /*end*/
ORDER BY A.OWNER, A.TABLE_NAME
