FROM ALL_ANNOTATIONS_USAGE A
WHERE A.OBJECT_TYPE='DOMAIN'
 /*if isNotEmpty(schemaName)*/
 AND A.ANNOTATION_OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(domainName)*/
 AND A.OBJECT_NAME IN /*domainName*/('%')
 /*end*/
