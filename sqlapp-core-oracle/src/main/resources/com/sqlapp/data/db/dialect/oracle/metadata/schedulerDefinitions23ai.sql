SELECT R.OBJECT_KIND, R.OWNER, R.OBJECT_NAME,
 DBMS_METADATA.GET_DDL('PROCOBJ', R.OBJECT_NAME, R.OWNER) AS OBJECT_DEFINITION
FROM (
 SELECT 'JOB' AS OBJECT_KIND, J.OWNER, J.JOB_NAME AS OBJECT_NAME
 FROM ALL_SCHEDULER_JOBS J
 WHERE 1=1
 /*if isNotEmpty(schemaName)*/
 AND J.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(eventName)*/
 AND J.JOB_NAME IN /*eventName*/('%')
 /*end*/
 UNION ALL
 SELECT DISTINCT 'PROGRAM', P.OWNER, P.PROGRAM_NAME
 FROM ALL_SCHEDULER_JOBS J
 JOIN ALL_SCHEDULER_PROGRAMS P ON P.OWNER=J.PROGRAM_OWNER AND P.PROGRAM_NAME=J.PROGRAM_NAME
 WHERE 1=1
 /*if isNotEmpty(schemaName)*/
 AND J.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(eventName)*/
 AND J.JOB_NAME IN /*eventName*/('%')
 /*end*/
 UNION ALL
 SELECT DISTINCT 'SCHEDULE', S.OWNER, S.SCHEDULE_NAME
 FROM ALL_SCHEDULER_JOBS J
 JOIN ALL_SCHEDULER_SCHEDULES S ON S.OWNER=J.SCHEDULE_OWNER AND S.SCHEDULE_NAME=J.SCHEDULE_NAME
 WHERE 1=1
 /*if isNotEmpty(schemaName)*/
 AND J.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(eventName)*/
 AND J.JOB_NAME IN /*eventName*/('%')
 /*end*/
) R
ORDER BY R.OBJECT_KIND, R.OWNER, R.OBJECT_NAME
