SELECT D.OWNER, D.NAME AS DOMAIN_NAME, D.TYPE AS DOMAIN_KIND,
 DBMS_METADATA.GET_DDL('SQL_DOMAIN', D.NAME, D.OWNER) AS DOMAIN_DEFINITION
FROM ALL_DOMAINS D
WHERE (
 D.TYPE IN ('ENUMERATED', 'FLEXIBLE')
 OR EXISTS (SELECT 1 FROM ALL_DOMAIN_CONSTRAINTS C
  WHERE C.DOMAIN_OWNER=D.OWNER AND C.DOMAIN_NAME=D.NAME AND C.SEARCH_CONDITION IS NULL)
 OR EXISTS (SELECT 1 FROM ALL_DOMAIN_COLS C
  WHERE C.OWNER=D.OWNER AND C.DOMAIN_NAME=D.NAME AND C.DATA_TYPE_ID<>1)
 OR EXISTS (SELECT 1 FROM ALL_DOMAIN_COLS C
  WHERE C.OWNER=D.OWNER AND C.DOMAIN_NAME=D.NAME AND C.NULLABLE='N')
 /*if isNotEmpty(definitionOwner) && isNotEmpty(definitionName)*/
 OR (D.OWNER IN /*definitionOwner*/('%') AND D.NAME IN /*definitionName*/('%'))
 /*end*/
)
 /*if isNotEmpty(schemaName)*/
 AND D.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(domainName)*/
 AND D.NAME IN /*domainName*/('%')
 /*end*/
ORDER BY D.OWNER, D.NAME
