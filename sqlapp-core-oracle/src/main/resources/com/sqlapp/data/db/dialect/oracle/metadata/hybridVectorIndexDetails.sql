SELECT
  USER AS OWNER
, O.IXO_INDEX_NAME AS INDEX_NAME
, O.IXO_CLASS
, O.IXO_OBJECT
FROM CTX_USER_INDEX_OBJECTS O
WHERE O.IXO_CLASS IN ('DATASTORE', 'FILTER', 'LEXER', 'VECTORIZER')
  /*if isNotEmpty(schemaName)*/
  AND USER IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(indexName)*/
  AND O.IXO_INDEX_NAME IN /*indexName*/('%')
  /*end*/
ORDER BY O.IXO_INDEX_NAME, O.IXO_CLASS
