SELECT P.OWNER, P.PROGRAM_NAME, P.PROGRAM_TYPE, P.PROGRAM_ACTION,
 P.NUMBER_OF_ARGUMENTS, P.ENABLED, P.COMMENTS,
 A.ARGUMENT_NAME, A.ARGUMENT_POSITION, A.ARGUMENT_TYPE, A.METADATA_ATTRIBUTE,
 A.DEFAULT_VALUE, A.OUT_ARGUMENT,
 CASE WHEN A.DEFAULT_ANYDATA_VALUE IS NULL THEN 'FALSE' ELSE 'TRUE' END AS HAS_DEFAULT_ANYDATA_VALUE,
 CASE WHEN A.DEFAULT_ANYDATA_VALUE IS NOT NULL THEN
   CASE WHEN A.DEFAULT_ANYDATA_VALUE.GetTypeName()='SYS.VARCHAR2'
        THEN A.DEFAULT_ANYDATA_VALUE.AccessVarchar2() END
 END AS DEFAULT_ANYDATA_TEXT
FROM ALL_SCHEDULER_PROGRAMS P
LEFT OUTER JOIN ALL_SCHEDULER_PROGRAM_ARGS A ON A.OWNER=P.OWNER AND A.PROGRAM_NAME=P.PROGRAM_NAME
WHERE 1=1
 /*if isNotEmpty(schemaName)*/
 AND P.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(programName)*/
 AND P.PROGRAM_NAME IN /*programName*/('%')
 /*end*/
ORDER BY P.OWNER, P.PROGRAM_NAME, A.ARGUMENT_POSITION
