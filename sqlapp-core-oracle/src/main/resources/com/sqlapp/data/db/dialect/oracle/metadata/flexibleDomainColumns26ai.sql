SELECT C.OWNER, C.DOMAIN_NAME, C.COLUMN_NAME, C.DISCRIMINANT
FROM ALL_DOMAIN_COLS C
JOIN ALL_DOMAINS D ON D.OWNER=C.OWNER AND D.NAME=C.DOMAIN_NAME
WHERE D.TYPE='FLEXIBLE' AND C.DATA_TYPE_ID=1
 /*if isNotEmpty(schemaName)*/
 AND C.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(domainName)*/
 AND C.DOMAIN_NAME IN /*domainName*/('%')
 /*end*/
ORDER BY C.OWNER, C.DOMAIN_NAME, C.COLUMN_ID
