SELECT
  A.*
, B.COMMENTS
, L.LOB_TABLESPACE_NAME
, I.TABLESPACE_NAME AS IOT_TABLESPACE_NAME
, I.PCT_THRESHOLD AS IOT_PCT_THRESHOLD
, I.COMPRESSION AS IOT_COMPRESSION
, I.PREFIX_LENGTH AS IOT_PREFIX_LENGTH
, CASE WHEN EXISTS (SELECT 1 FROM ALL_TABLES O WHERE O.OWNER=A.OWNER AND O.IOT_NAME=A.TABLE_NAME
  AND O.IOT_TYPE IN ('IOT_OVERFLOW','IOT_MAPPING')) THEN 'YES' ELSE 'NO' END AS IOT_COMPLEX
FROM ALL_TABLES A
LEFT OUTER JOIN ALL_TAB_COMMENTS B
ON (A.OWNER=B.OWNER
    AND
    A.TABLE_NAME=B.TABLE_NAME
    AND
    B.TABLE_TYPE='TABLE'
    AND
    B.COMMENTS IS NOT NULL)
LEFT OUTER JOIN (
 SELECT OWNER, TABLE_NAME,
  CASE WHEN COUNT(*)=COUNT(TABLESPACE_NAME) AND COUNT(DISTINCT TABLESPACE_NAME)=1
   THEN MIN(TABLESPACE_NAME) END AS LOB_TABLESPACE_NAME
 FROM ALL_LOBS
 WHERE 1=1
 /*if isNotEmpty(schemaName)*/
 AND OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(tableName)*/
 AND TABLE_NAME IN /*tableName*/('%')
 /*end*/
 GROUP BY OWNER, TABLE_NAME
) L ON L.OWNER=A.OWNER AND L.TABLE_NAME=A.TABLE_NAME
LEFT OUTER JOIN ALL_INDEXES I ON I.TABLE_OWNER=A.OWNER AND I.TABLE_NAME=A.TABLE_NAME AND I.INDEX_TYPE='IOT - TOP'
WHERE 1=1 
  AND (A.IOT_TYPE IS NULL OR A.IOT_TYPE='IOT')
  /*if isNotEmpty(schemaName)*/
  AND A.OWNER IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND A.TABLE_NAME IN /*tableName*/('%')
  /*end*/
ORDER BY A.OWNER, A.TABLE_NAME
