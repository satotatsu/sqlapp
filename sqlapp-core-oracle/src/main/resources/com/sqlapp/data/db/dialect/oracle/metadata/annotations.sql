SELECT
  A.OBJECT_NAME
, A.OBJECT_TYPE
, A.COLUMN_NAME
, A.ANNOTATION_OWNER
, A.ANNOTATION_NAME
, A.ANNOTATION_VALUE
FROM ALL_ANNOTATIONS_USAGE A
WHERE A.DOMAIN_NAME IS NULL
  /*if isNotEmpty(schemaName)*/
  AND A.ANNOTATION_OWNER IN /*schemaName*/('%')
  /*end*/
  AND A.OBJECT_TYPE IN ('TABLE', 'INDEX')
  /*if isNotEmpty(tableName)*/
  AND (
       (A.OBJECT_TYPE='TABLE'
        AND A.OBJECT_NAME IN /*tableName*/('%'))
       OR A.OBJECT_TYPE='INDEX'
      )
  /*end*/
ORDER BY
  A.ANNOTATION_OWNER
, A.OBJECT_TYPE
, A.OBJECT_NAME
, A.COLUMN_NAME
, A.ANNOTATION_NAME
