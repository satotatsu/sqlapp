SELECT S.OWNER, S.SCHEDULE_NAME, S.REPEAT_INTERVAL, S.COMMENTS,
 TO_CHAR(S.START_DATE, 'YYYY-MM-DD"T"HH24:MI:SS.FF6 TZR TZH:TZM', 'NLS_DATE_LANGUAGE=American') AS START_DATE_TEXT,
 TO_CHAR(S.END_DATE, 'YYYY-MM-DD"T"HH24:MI:SS.FF6 TZR TZH:TZM', 'NLS_DATE_LANGUAGE=American') AS END_DATE_TEXT
FROM ALL_SCHEDULER_SCHEDULES S
WHERE 1=1
 /*if isNotEmpty(schemaName)*/
 AND S.OWNER IN /*schemaName*/('%')
 /*end*/
 /*if isNotEmpty(scheduleName)*/
 AND S.SCHEDULE_NAME IN /*scheduleName*/('%')
 /*end*/
ORDER BY S.OWNER, S.SCHEDULE_NAME
