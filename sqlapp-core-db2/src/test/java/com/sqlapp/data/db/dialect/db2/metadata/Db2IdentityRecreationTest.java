package com.sqlapp.data.db.dialect.db2.metadata;

import static org.junit.jupiter.api.Assertions.*;
import java.math.BigDecimal;
import java.sql.*;
import java.util.*;
import java.util.concurrent.atomic.AtomicInteger;
import org.junit.jupiter.api.Test;
import com.sqlapp.data.db.dialect.db2.DialectHolder;
import com.sqlapp.data.db.sql.*;
import com.sqlapp.data.parameter.ParametersContext;
import com.sqlapp.data.schemas.*;
import com.sqlapp.jdbc.ExResultSet;
import com.sqlapp.jdbc.sql.*;
import com.sqlapp.jdbc.sql.node.SqlNode;

class Db2IdentityRecreationTest {
	private Map<String, String> fields() {
		var fields = new HashMap<String, String>(Map.of("column_name", "ID", "table_name", "T", "schema_name", "APP",
				"TYPENAME", "BIGINT", "TYPESCHEMA", "SYSIBM", "NULLS", "N", "IDENTITY", "Y", "GENERATED", "D"));
		fields.putAll(Map.of("START", "10", "INCREMENT", "5", "MINVALUE", "0", "MAXVALUE", "1000", "CACHE", "40",
				"CYCLE", "Y", "ORDER", "Y"));
		return fields;
	}

	private ExResultSet row(Map<String, String> fields) {
		return new ExResultSet(null) {
			@Override
			public String getString(String key) {
				return fields.get(key);
			}

			@Override
			public Object getObject(String key) {
				return fields.get(key);
			}

			@Override
			public BigDecimal getBigDecimal(String key) {
				return fields.get(key) == null ? null : new BigDecimal(fields.get(key));
			}

			@Override
			public long getLong(String key) {
				return Long.parseLong(fields.getOrDefault(key, "0"));
			}

			@Override
			public int getInt(String key) {
				return Integer.parseInt(fields.getOrDefault(key, "0"));
			}

			@Override
			public boolean wasNull() {
				return false;
			}
		};
	}

	private Column read(Map<String, String> fields) throws SQLException {
		return new Db2ColumnReader(DialectHolder.Db2_1110Dialect).createColumn(row(fields));
	}

	private String create(Column column) throws Exception {
		Table table = new Table("T").setSchemaName("APP");
		table.getColumns().add(column);
		Table restored = SchemaUtils.readXml(new java.io.StringReader(table.asXml()));
		SqlFactory<Table> factory = DialectHolder.Db2_1110Dialect.createSqlFactoryRegistry().getSqlFactory(restored,
				SqlType.CREATE);
		return factory.createSql(restored).getFirst().getSqlText().replaceAll("\\s+", " ");
	}

	@Test
	void generationModeAndAllOptionsSurviveXmlAndCreate() throws Exception {
		Column column = read(fields());
		String ddl = create(column);
		assertTrue(ddl.contains(
				"GENERATED BY DEFAULT AS IDENTITY (START WITH 10 INCREMENT BY 5 MINVALUE 0 MAXVALUE 1000 CYCLE CACHE 40 ORDER)"),
				ddl);
		assertEquals(Long.valueOf(10), column.getIdentityStartValue());
		assertEquals(Integer.valueOf(40), column.getIdentityCacheSize());
	}

	@Test
	void descendingAlwaysNoCacheAndNoCycleRetainNativeMeaning() throws Exception {
		var fields = fields();
		fields.putAll(Map.of("GENERATED", "A", "START", "-1", "INCREMENT", "-2", "MINVALUE", "-100", "MAXVALUE", "-1",
				"CACHE", "0", "CYCLE", "N", "ORDER", "N"));
		String ddl = create(read(fields));
		assertTrue(ddl.contains("GENERATED ALWAYS AS IDENTITY"));
		assertTrue(ddl.contains("START WITH -1 INCREMENT BY -2 MINVALUE -100 MAXVALUE -1 NO CYCLE NO CACHE NO ORDER"),
				ddl);
	}

	@Test
	void decimal31ValuesRemainExactAfterXml() throws Exception {
		var fields = fields();
		fields.putAll(Map.of("TYPENAME", "DECIMAL", "LENGTH", "31", "SCALE", "0", "START", "100000000000000000000",
				"MAXVALUE", "9999999999999999999999999999999"));
		Column column = read(fields);
		assertNull(column.getIdentityStartValue());
		assertNull(column.getIdentityMaxValue());
		String ddl = create(column);
		assertTrue(ddl.contains("START WITH 100000000000000000000"), ddl);
		assertTrue(ddl.contains("MAXVALUE 9999999999999999999999999999999"), ddl);
		column.setIdentityStartValue(20);
		assertTrue(create(column).contains("START WITH 20 "));
	}

	@Test
	void invalidModeBoundsIncrementCacheAndDefaultAreRejected() throws Exception {
		var fields = fields();
		fields.put("GENERATED", "?");
		assertThrows(SQLException.class, () -> read(fields));
		for (var option : Map.of("INCREMENT", "0", "START", "1001", "CACHE", "1", "MINVALUE", "2000").entrySet()) {
			var values = fields();
			values.put(option.getKey(), option.getValue());
			assertThrows(IllegalArgumentException.class, () -> create(read(values)));
		}
		Column column = read(fields());
		column.setDefaultValue("1");
		assertThrows(IllegalArgumentException.class, () -> create(column));
		var small = fields();
		small.put("TYPENAME", "SMALLINT");
		small.put("MAXVALUE", "40000");
		assertThrows(IllegalArgumentException.class, () -> create(read(small)));
		var fractional = fields();
		fractional.putAll(Map.of("TYPENAME", "DECIMAL", "LENGTH", "10", "SCALE", "1"));
		assertThrows(IllegalArgumentException.class, () -> create(read(fractional)));
	}

	@Test
	void identityMetadataAcrossTwentyTablesStillUsesOneQuery() {
		AtomicInteger queries = new AtomicInteger();
		var reader = new Db2ColumnReader(DialectHolder.Db2_1110Dialect) {
			@Override
			protected JdbcQueryHandler execute(Connection c, SqlNode sql, ParametersContext p,
					ResultSetNextHandler handler) {
				queries.incrementAndGet();
				for (int i = 0; i < 20; i++)
					try {
						var fields = fields();
						fields.put("table_name", "T" + i);
						handler.handleResultSetNext(row(fields));
					} catch (SQLException e) {
						throw new IllegalStateException(e);
					}
				return null;
			}
		};
		var columns = reader.doGetAll(null, new ParametersContext(), new ProductVersionInfo());
		assertEquals(1, queries.get());
		assertEquals(20, columns.size());
		assertTrue(columns.stream().allMatch(c -> c.getIdentityGenerationType() == IdentityGenerationType.ByDefault));
	}
}
