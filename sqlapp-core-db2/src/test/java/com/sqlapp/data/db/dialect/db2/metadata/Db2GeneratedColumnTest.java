package com.sqlapp.data.db.dialect.db2.metadata;

import static org.junit.jupiter.api.Assertions.*;
import java.sql.*;
import java.util.*;
import java.util.concurrent.atomic.AtomicInteger;
import org.junit.jupiter.api.Test;
import com.sqlapp.data.db.datatype.DataType;
import com.sqlapp.data.db.dialect.db2.DialectHolder;
import com.sqlapp.data.db.sql.*;
import com.sqlapp.data.parameter.ParametersContext;
import com.sqlapp.data.schemas.*;
import com.sqlapp.jdbc.sql.*;
import com.sqlapp.jdbc.sql.node.SqlNode;

class Db2GeneratedColumnTest {
	private Map<String, String> fields() {
		return new HashMap<>(Map.of("column_name", "TOTAL", "table_name", "T", "schema_name", "APP", "TYPENAME",
				"INTEGER", "TYPESCHEMA", "SYSIBM", "NULLS", "Y", "GENERATED", "A", "TEXT",
				"AS (COALESCE(\"price, net\", 0) * (2 + 3))", "HIDDEN", "I"));
	}

	private Column read(Map<String, String> fields) throws SQLException {
		return new Db2_1050ColumnReader(DialectHolder.Db2_1110Dialect).createColumn(Db2MetadataParityTest.row(fields));
	}

	private String create(Column column) throws Exception {
		Table table = new Table("T").setSchemaName("APP");
		table.getColumns().add(column);
		Table restored = SchemaUtils.readXml(new java.io.StringReader(table.asXml()));
		SqlFactory<Table> factory = DialectHolder.Db2_1110Dialect.createSqlFactoryRegistry().getSqlFactory(restored,
				SqlType.CREATE);
		return factory.createSql(restored).getFirst().getSqlText().replaceAll("\\s+", " ");
	}

	@Test
	void expressionAndImplicitlyHiddenAttributeSurviveXmlAndRecreation() throws Exception {
		Column column = read(fields());
		assertEquals("COALESCE(\"price, net\", 0) * (2 + 3)", column.getFormula());
		String ddl = create(column);
		assertTrue(ddl.contains("GENERATED ALWAYS AS (COALESCE(\"price, net\", 0) * (2 + 3))"), ddl);
		assertTrue(ddl.contains("IMPLICITLY HIDDEN"), ddl);
		assertFalse(ddl.contains("DEFAULT"), ddl);
	}

	@Test
	void currentDefaultReplacesHistoricalImplicitValueOnlyInModernQuery() throws Exception {
		var modern = new Db2ColumnReader(DialectHolder.Db2_1110Dialect);
		String sql = modern.getSqlNode(new ProductVersionInfo()).toString();
		assertTrue(sql.contains("c.DEFAULT AS default_value"));
		assertFalse(sql.contains("coalesce(c.IMPLICITVALUE"));
		assertTrue(new Db2ColumnReader(DialectHolder.Db2_1050Dialect).getSqlNode(new ProductVersionInfo()).toString()
				.contains("coalesce(c.IMPLICITVALUE"));
		var fields = fields();
		fields.remove("TEXT");
		fields.remove("GENERATED");
		fields.remove("HIDDEN");
		fields.put("DEFAULT_VALUE", "99");
		fields.put("IMPLICITVALUE", "1");
		assertTrue(create(read(fields)).contains("DEFAULT 99"));
	}

	@Test
	void rowChangeTimestampPreservesGenerationModeAndNullability() throws Exception {
		var fields = fields();
		fields.remove("TEXT");
		fields.putAll(Map.of("TYPENAME", "TIMESTAMP", "SCALE", "6", "NULLS", "N", "ROWCHANGETIMESTAMP", "Y"));
		assertTrue(create(read(fields)).contains("GENERATED ALWAYS FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP"));
		fields.put("GENERATED", "D");
		assertTrue(
				create(read(fields)).contains("GENERATED BY DEFAULT FOR EACH ROW ON UPDATE AS ROW CHANGE TIMESTAMP"));
		fields.put("NULLS", "Y");
		assertThrows(IllegalArgumentException.class, () -> create(read(fields)));
	}

	@Test
	void malformedExpressionsAndConflictingAttributesFailAndFullDdlRemainsAvailable() throws Exception {
		var fields = fields();
		fields.put("TEXT", "AS ()");
		assertThrows(SQLException.class, () -> read(fields));
		Column column = read(fields());
		column.setDefaultValue("1");
		assertThrows(IllegalArgumentException.class, () -> create(column));
		column.setDefaultValue(null);
		column.getSpecifics().put("GENERATED", "D");
		assertThrows(IllegalArgumentException.class, () -> create(column));
		column.getSpecifics().put("GENERATED", "A");
		column.setFormula(null);
		assertThrows(IllegalArgumentException.class, () -> create(column));
		column.setFormula("1 + 2");
		column.getSpecifics().put("HIDDEN", "S");
		assertThrows(IllegalArgumentException.class, () -> create(column));
		Table table = new Table("T").setSchemaName("APP").setDefinition("CREATE TABLE APP.T (ID INTEGER)");
		table.getColumns().add(column);
		SqlFactory<Table> factory = DialectHolder.Db2_1110Dialect.createSqlFactoryRegistry().getSqlFactory(table,
				SqlType.CREATE);
		assertEquals("CREATE TABLE APP.T (ID INTEGER)", factory.createSql(table).getFirst().getSqlText());
	}

	@Test
	void generatedColumnsAcrossTwentyTablesStillUseOneQuery() {
		AtomicInteger queries = new AtomicInteger();
		var reader = new Db2_1050ColumnReader(DialectHolder.Db2_1110Dialect) {
			@Override
			protected JdbcQueryHandler execute(Connection c, SqlNode sql, ParametersContext p,
					ResultSetNextHandler handler) {
				queries.incrementAndGet();
				for (int i = 0; i < 20; i++)
					try {
						var fields = fields();
						fields.put("table_name", "T" + i);
						handler.handleResultSetNext(Db2MetadataParityTest.row(fields));
					} catch (SQLException e) {
						throw new IllegalStateException(e);
					}
				return null;
			}
		};
		var columns = reader.doGetAll(null, new ParametersContext(), new ProductVersionInfo());
		assertEquals(1, queries.get());
		assertEquals(20, columns.size());
		assertTrue(columns.stream().allMatch(c -> c.getFormula() != null));
	}
}
