SELECT v.VARSCHEMA, v.VARNAME, v.TYPESCHEMA, v.TYPENAME, v.TYPEMODULENAME, v.LENGTH, v.SCALE,
       v.CODEPAGE, v.TYPESTRINGUNITS, v.STRINGUNITSLENGTH, v.SCOPE, v.READONLY,
       v.DEFAULT AS DEFAULT_EXPRESSION, v.QUALIFIER, v.FUNC_PATH, v.COLLATIONSCHEMA, v.COLLATIONNAME, v.REMARKS, v.CREATE_TIME
FROM SYSCAT.VARIABLES v
WHERE v.VARMODULEID IS NULL AND v.OWNER <> 'SYSIBM' AND v.READONLY <> 'S'
/*if isNotEmpty(schemaName)*/
  AND rtrim(VARSCHEMA) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(constantName)*/
  AND rtrim(VARNAME) IN /*constantName*/('%')
/*end*/
ORDER BY VARSCHEMA, VARNAME
WITH UR
