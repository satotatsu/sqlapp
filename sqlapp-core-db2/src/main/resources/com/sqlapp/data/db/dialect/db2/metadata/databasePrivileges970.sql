SELECT a.GRANTOR, a.GRANTEE, a.GRANTEETYPE,
       a.BINDADDAUTH, a.CONNECTAUTH, a.CREATETABAUTH, a.DBADMAUTH,
       a.NOFENCEAUTH, a.IMPLSCHEMAAUTH, a.LOADAUTH,
       a.EXTERNALROUTINEAUTH, a.QUIESCECONNECTAUTH, a.SECURITYADMAUTH,
       a.ACCESSCTRLAUTH, a.DATAACCESSAUTH, a.SQLADMAUTH, a.WLMADMAUTH, a.EXPLAINAUTH
FROM SYSCAT.DBAUTH a
WHERE a.GRANTOR <> 'SYSIBM'
/*if isNotEmpty(userName)*/
  AND rtrim(a.GRANTEE) IN /*userName*/('%')
/*end*/
ORDER BY a.GRANTEE, a.GRANTEETYPE, a.GRANTOR
