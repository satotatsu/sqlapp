SELECT m.MODULESCHEMA, m.MODULENAME, m.MODULETYPE, m.DIALECT,
       m.OWNER, m.BASE_MODULESCHEMA, m.BASE_MODULENAME, m.CREATE_TIME, m.REMARKS,
       COALESCE(o.MEMBER_COUNT, 0) AS MEMBER_COUNT
FROM SYSCAT.MODULES m
LEFT JOIN (
  SELECT OBJECTSCHEMA, OBJECTMODULENAME, COUNT(*) AS MEMBER_COUNT
  FROM SYSCAT.MODULEOBJECTS
  GROUP BY OBJECTSCHEMA, OBJECTMODULENAME
) o ON o.OBJECTSCHEMA=m.MODULESCHEMA AND o.OBJECTMODULENAME=m.MODULENAME
WHERE m.OWNERTYPE <> 'S'
  AND m.MODULETYPE IN ('M', 'P')
  /*if isNotEmpty(schemaName) */
  AND m.MODULESCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(packageName) */
  AND m.MODULENAME IN /*packageName*/('%')
  /*end*/
ORDER BY m.MODULESCHEMA, m.MODULENAME
WITH UR
