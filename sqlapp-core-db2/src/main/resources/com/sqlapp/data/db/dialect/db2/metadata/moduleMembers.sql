SELECT o.OBJECTSCHEMA, o.OBJECTMODULENAME, o.OBJECTNAME, o.OBJECTTYPE,
       o.SPECIFICNAME, o.PUBLISHED, o.USERDEFINED,
       c.SQLSTATE AS CONDITION_SQLSTATE, c.REMARKS AS CONDITION_REMARKS,
       v.TYPESCHEMA, v.TYPENAME, v.TYPEMODULENAME, v.LENGTH, v.SCALE,
       v.CODEPAGE, v.TYPESTRINGUNITS, v.STRINGUNITSLENGTH, v.SCOPE, v.READONLY,
       v.DEFAULT AS DEFAULT_EXPRESSION, v.QUALIFIER, v.FUNC_PATH,
       v.COLLATIONSCHEMA, v.COLLATIONNAME, v.REMARKS AS VARIABLE_REMARKS,
	       r.TEXT AS ROUTINE_TEXT, r.LANGUAGE AS ROUTINE_LANGUAGE, r.REMARKS AS ROUTINE_REMARKS,
       r.MODULEROUTINEIMPLEMENTED, r.QUALIFIER AS ROUTINE_QUALIFIER, r.FUNC_PATH AS ROUTINE_FUNC_PATH,
       r.ORIGIN AS ROUTINE_ORIGIN, r.RETURN_TYPESCHEMA AS ROUTINE_RETURN_SCHEMA,
       r.RETURN_TYPEMODULE AS ROUTINE_RETURN_MODULE, r.RETURN_TYPENAME AS ROUTINE_RETURN_NAME,
       r.PARM_COUNT AS ROUTINE_PARAMETER_COUNT,
       CASE WHEN o.USERDEFINED='Y' AND o.OBJECTTYPE IN ('FUNCTION','PROCEDURE') THEN
         CASE WHEN COALESCE(signature.PARAMETERS,0)=r.PARM_COUNT AND COALESCE(signature.UNSUPPORTED,0)=0
           AND (r.ROUTINETYPE='P' OR COALESCE(signature.RESULTS,0)>0) THEN 'Y' ELSE 'N' END
       END AS ROUTINE_DECLARATION_INDEPENDENT,
       generated_p.TYPESCHEMA AS ROUTINE_PARAMETER_SCHEMA, generated_p.TYPEMODULENAME AS ROUTINE_PARAMETER_MODULE,
       generated_p.TYPENAME AS ROUTINE_PARAMETER_NAME,
       CASE WHEN cursor_target.DEPENDENCIES IS NULL THEN 'W' WHEN cursor_target.DEPENDENCIES=1 AND cursor_target.ROW_DEPENDENCIES=1 THEN 'S' ELSE 'U' END AS TYPE_CURSOR_KIND,
       cursor_target.ROW_SCHEMA AS TYPE_CURSOR_ROW_SCHEMA, cursor_target.ROW_MODULE AS TYPE_CURSOR_ROW_MODULE, cursor_target.ROW_NAME AS TYPE_CURSOR_ROW_NAME,
       d.METATYPE AS TYPE_METATYPE, d.SOURCESCHEMA, d.SOURCENAME, d.SOURCEMODULENAME,
       d.TYPERULES AS TYPE_TYPERULES, d.NULLS AS TYPE_NULLS,
       d.LENGTH AS TYPE_LENGTH, d.SCALE AS TYPE_SCALE, d.CODEPAGE AS TYPE_CODEPAGE,
       d.TYPESTRINGUNITS AS TYPE_TYPESTRINGUNITS, d.STRINGUNITSLENGTH AS TYPE_STRINGUNITSLENGTH,
       d.ARRAY_LENGTH AS TYPE_ARRAY_LENGTH, d.ARRAYINDEXTYPESCHEMA AS TYPE_ARRAYINDEXTYPESCHEMA,
       d.ARRAYINDEXTYPENAME AS TYPE_ARRAYINDEXTYPENAME, d.ARRAYINDEXTYPELENGTH AS TYPE_ARRAYINDEXTYPELENGTH,
       d.ARRAYINDEXTYPE_STRINGUNITS AS TYPE_ARRAYINDEXTYPE_STRINGUNITS,
       d.ARRAYINDEXTYPE_STRINGUNITSLENGTH AS TYPE_ARRAYINDEXTYPE_STRINGUNITSLENGTH,
       d.FUNC_PATH AS TYPE_FUNC_PATH, d.CONSTRAINT_TEXT AS TYPE_CONSTRAINT_TEXT,
       d.REMARKS AS TYPE_REMARKS, d.COLLATIONSCHEMA AS TYPE_COLLATIONSCHEMA, d.COLLATIONNAME AS TYPE_COLLATIONNAME,
       COALESCE(c.CREATE_TIME,v.CREATE_TIME,r.CREATE_TIME,d.CREATE_TIME) AS MEMBER_CREATE_TIME
FROM SYSCAT.MODULEOBJECTS o
JOIN SYSCAT.MODULES m ON m.MODULESCHEMA=o.OBJECTSCHEMA AND m.MODULENAME=o.OBJECTMODULENAME
LEFT JOIN SYSCAT.CONDITIONS c ON o.OBJECTTYPE='CONDITION' AND c.CONDSCHEMA=o.OBJECTSCHEMA
 AND c.CONDMODULENAME=o.OBJECTMODULENAME AND c.CONDNAME=o.OBJECTNAME
LEFT JOIN SYSCAT.VARIABLES v ON o.OBJECTTYPE='VARIABLE' AND v.VARSCHEMA=o.OBJECTSCHEMA
 AND v.VARMODULENAME=o.OBJECTMODULENAME AND v.VARNAME=o.OBJECTNAME
LEFT JOIN SYSCAT.ROUTINES r ON o.OBJECTTYPE IN ('FUNCTION','PROCEDURE') AND r.ROUTINESCHEMA=o.OBJECTSCHEMA
 AND r.ROUTINEMODULENAME=o.OBJECTMODULENAME AND r.SPECIFICNAME=o.SPECIFICNAME
LEFT JOIN SYSCAT.DATATYPES d ON o.OBJECTTYPE='TYPE' AND d.TYPESCHEMA=o.OBJECTSCHEMA
 AND d.TYPEMODULENAME=o.OBJECTMODULENAME AND d.TYPENAME=o.OBJECTNAME
LEFT JOIN (
 SELECT p.ROUTINESCHEMA,p.SPECIFICNAME,
        SUM(CASE WHEN p.ROWTYPE IN ('P','B','O') THEN 1 ELSE 0 END) AS PARAMETERS,
        SUM(CASE WHEN p.ROWTYPE IN ('C','R') THEN 1 ELSE 0 END) AS RESULTS,
        SUM(CASE WHEN p.TYPESCHEMA IS NULL OR p.TYPESCHEMA<>'SYSIBM' OR p.TYPEMODULENAME IS NOT NULL
          OR p.DEFAULT IS NOT NULL OR p.ROWTYPE NOT IN ('P','B','O','C','R') OR COALESCE(p.LOCATOR,'N')<>'N'
          OR p.TARGET_TYPESCHEMA IS NOT NULL OR p.SCOPE_TABSCHEMA IS NOT NULL OR p.TRANSFORMGRPNAME IS NOT NULL
          OR p.CAST_FUNCSCHEMA IS NOT NULL OR (p.COLLATIONSCHEMA IS NOT NULL AND p.COLLATIONSCHEMA<>'SYSIBM')
          THEN 1 ELSE 0 END) AS UNSUPPORTED
 FROM SYSCAT.ROUTINEPARMS p
 WHERE p.ROUTINEMODULEID IS NOT NULL
 GROUP BY p.ROUTINESCHEMA,p.SPECIFICNAME
) signature ON signature.ROUTINESCHEMA=r.ROUTINESCHEMA AND signature.SPECIFICNAME=r.SPECIFICNAME
LEFT JOIN (
 SELECT dep.TYPESCHEMA,dep.TYPEMODULENAME,dep.TYPENAME,COUNT(*) AS DEPENDENCIES,
        SUM(CASE WHEN dep.BTYPE='R' AND target.METATYPE='F' THEN 1 ELSE 0 END) AS ROW_DEPENDENCIES,
        MAX(CASE WHEN dep.BTYPE='R' AND target.METATYPE='F' THEN target.TYPESCHEMA END) AS ROW_SCHEMA,
        MAX(CASE WHEN dep.BTYPE='R' AND target.METATYPE='F' THEN target.TYPEMODULENAME END) AS ROW_MODULE,
        MAX(CASE WHEN dep.BTYPE='R' AND target.METATYPE='F' THEN target.TYPENAME END) AS ROW_NAME
 FROM SYSCAT.DATATYPEDEP dep
 LEFT JOIN SYSCAT.DATATYPES target ON dep.BTYPE='R' AND target.TYPESCHEMA=dep.BSCHEMA
  AND COALESCE(target.TYPEMODULENAME,'')=COALESCE(dep.BMODULENAME,'') AND target.TYPENAME=dep.BNAME
 GROUP BY dep.TYPESCHEMA,dep.TYPEMODULENAME,dep.TYPENAME
) cursor_target ON cursor_target.TYPESCHEMA=d.TYPESCHEMA AND cursor_target.TYPENAME=d.TYPENAME
 AND COALESCE(cursor_target.TYPEMODULENAME,'')=COALESCE(d.TYPEMODULENAME,'')
LEFT JOIN SYSCAT.ROUTINEPARMS generated_p ON o.USERDEFINED='N' AND o.OBJECTTYPE='FUNCTION'
 AND generated_p.ROUTINESCHEMA=r.ROUTINESCHEMA AND generated_p.SPECIFICNAME=r.SPECIFICNAME
 AND generated_p.ROWTYPE='P' AND generated_p.ORDINAL=1
WHERE m.OWNERTYPE <> 'S' AND m.MODULETYPE IN ('M', 'P')
/*if isNotEmpty(schemaName)*/
 AND m.MODULESCHEMA IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(packageName)*/
 AND m.MODULENAME IN /*packageName*/('%')
/*end*/
ORDER BY o.OBJECTSCHEMA,o.OBJECTMODULENAME,MEMBER_CREATE_TIME,o.OBJECTTYPE,o.OBJECTNAME,o.SPECIFICNAME
WITH UR
