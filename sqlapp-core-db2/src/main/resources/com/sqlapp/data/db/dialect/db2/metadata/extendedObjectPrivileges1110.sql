SELECT a.*
FROM (
  SELECT 'SEQUENCE' AS OBJECT_TYPE, SEQSCHEMA AS schema_name, SEQNAME AS object_name,
         GRANTOR, GRANTEE, GRANTEETYPE, 'ALTER' AS PRIVILEGE, ALTERAUTH AS AUTH_STATE
  FROM SYSCAT.SEQUENCEAUTH
  UNION ALL
  SELECT 'SEQUENCE', SEQSCHEMA, SEQNAME, GRANTOR, GRANTEE, GRANTEETYPE, 'USAGE', USAGEAUTH
  FROM SYSCAT.SEQUENCEAUTH
  UNION ALL
  SELECT 'INDEX', INDSCHEMA, INDNAME, GRANTOR, GRANTEE, GRANTEETYPE, 'CONTROL', CONTROLAUTH
  FROM SYSCAT.INDEXAUTH
  UNION ALL
  SELECT 'SERVER', CAST(NULL AS VARCHAR(128)), SERVERNAME, GRANTOR, GRANTEE, GRANTEETYPE,
         'PASSTHRU', 'Y'
  FROM SYSCAT.PASSTHRUAUTH
  UNION ALL
  SELECT 'TABLESPACE', CAST(NULL AS VARCHAR(128)), TBSPACE, GRANTOR, GRANTEE, GRANTEETYPE, 'USE', USEAUTH
  FROM SYSCAT.TBSPACEAUTH
  UNION ALL
  SELECT 'PACKAGE', PKGSCHEMA, PKGNAME, GRANTOR, GRANTEE, GRANTEETYPE, 'CONTROL', CONTROLAUTH
  FROM SYSCAT.PACKAGEAUTH
  UNION ALL
  SELECT 'PACKAGE', PKGSCHEMA, PKGNAME, GRANTOR, GRANTEE, GRANTEETYPE, 'BIND', BINDAUTH
  FROM SYSCAT.PACKAGEAUTH
  UNION ALL
  SELECT 'PACKAGE', PKGSCHEMA, PKGNAME, GRANTOR, GRANTEE, GRANTEETYPE, 'EXECUTE', EXECUTEAUTH
  FROM SYSCAT.PACKAGEAUTH
  UNION ALL
  SELECT 'MODULE', MODULESCHEMA, MODULENAME, GRANTOR, GRANTEE, GRANTEETYPE, 'EXECUTE', EXECUTEAUTH
  FROM SYSCAT.MODULEAUTH
  UNION ALL
  SELECT 'VARIABLE', a.VARSCHEMA, a.VARNAME, a.GRANTOR, a.GRANTEE, a.GRANTEETYPE, 'READ', a.READAUTH
  FROM SYSCAT.VARIABLEAUTH a JOIN SYSCAT.VARIABLES v ON v.VARID=a.VARID AND v.VARMODULEID IS NULL
  UNION ALL
  SELECT 'VARIABLE', a.VARSCHEMA, a.VARNAME, a.GRANTOR, a.GRANTEE, a.GRANTEETYPE, 'WRITE', a.WRITEAUTH
  FROM SYSCAT.VARIABLEAUTH a JOIN SYSCAT.VARIABLES v ON v.VARID=a.VARID AND v.VARMODULEID IS NULL
  UNION ALL
  SELECT 'WORKLOAD', CAST(NULL AS VARCHAR(128)), WORKLOADNAME, GRANTOR, GRANTEE, GRANTEETYPE, 'USAGE', USAGEAUTH
  FROM SYSCAT.WORKLOADAUTH
  UNION ALL
  SELECT 'XSROBJECT', x.OBJECTSCHEMA, x.OBJECTNAME, a.GRANTOR, a.GRANTEE, a.GRANTEETYPE, 'USAGE', a.USAGEAUTH
  FROM SYSCAT.XSROBJECTAUTH a JOIN SYSCAT.XSROBJECTS x ON x.OBJECTID=a.OBJECTID
) a
WHERE a.GRANTOR <> 'SYSIBM' AND a.AUTH_STATE <> 'N'
/*if isNotEmpty(schemaName)*/
  AND rtrim(a.schema_name) IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(objectName)*/
  AND rtrim(a.object_name) IN /*objectName*/('%')
/*end*/
ORDER BY a.OBJECT_TYPE, a.schema_name, a.object_name, a.GRANTEE, a.GRANTOR, a.PRIVILEGE
WITH UR
