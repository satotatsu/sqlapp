SELECT a.TYPESCHEMA AS schema_name, a.TYPEMODULENAME AS module_name, a.TYPENAME AS type_name,
       a.FIELDNAME AS column_name, a.FIELDTYPENAME AS data_type, a.FIELDTYPESCHEMA AS data_type_schema,
       a.FIELDTYPEMODULENAME AS data_type_module,
       a.LENGTH, a.SCALE, a.CODEPAGE, a.TYPESTRINGUNITS, a.STRINGUNITSLENGTH,
       a.COLLATIONSCHEMA, a.COLLATIONNAME, a.ORDINAL,
       CAST(NULL AS CHAR(1)) AS LOGGED, CAST(NULL AS CHAR(1)) AS COMPACT
FROM SYSCAT.ROWFIELDS a
JOIN SYSCAT.MODULES m ON m.MODULESCHEMA=a.TYPESCHEMA AND m.MODULENAME=a.TYPEMODULENAME
WHERE m.OWNERTYPE <> 'S' AND m.MODULETYPE IN ('M', 'P')
/*if isNotEmpty(schemaName)*/
 AND a.TYPESCHEMA IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(packageName)*/
 AND a.TYPEMODULENAME IN /*packageName*/('%')
/*end*/
ORDER BY a.TYPESCHEMA,a.TYPEMODULENAME,a.TYPENAME,a.ORDINAL
WITH UR
