SELECT m.FUNCTION_MAPPING, m.FUNCSCHEMA, m.FUNCNAME, m.SPECIFICNAME,
       m.SERVERNAME, m.SERVERTYPE, m.SERVERVERSION, m.WRAPNAME, m.REMARKS, m.CREATE_TIME,
       o.OPTION AS OPTION_NAME, o.SETTING
FROM SYSCAT.FUNCMAPPINGS m
LEFT JOIN SYSCAT.FUNCMAPOPTIONS o ON o.FUNCTION_MAPPING=m.FUNCTION_MAPPING
WHERE m.OWNER <> 'SYSIBM'
ORDER BY m.CREATE_TIME, m.FUNCTION_MAPPING, o.OPTION
WITH UR
