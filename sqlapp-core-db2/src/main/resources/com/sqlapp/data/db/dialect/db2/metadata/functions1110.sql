SELECT
    r.ROUTINESCHEMA AS schema_name
  , r.ROUTINENAME AS routine_name
  , r.SPECIFICNAME AS specific_name
  , r.ROUTINEID AS id
  , CASE
    WHEN r.ORIGIN = 'E' THEN 'EXTERNAL'
    ELSE 'SQL'
    END AS ROUTINE_BODY
  , r.LANGUAGE
  , r.TEXT AS ROUTINE_DEFINITION
  , p.TYPENAME AS RETURN_TYPE_NAME
  , p.LENGTH AS RETURN_LENGTH
  , p.SCALE AS RETURN_SCALE
  , p.TYPESCHEMA AS RETURN_TYPESCHEMA
  , p.TYPEMODULENAME AS RETURN_TYPEMODULENAME
  , p.CODEPAGE AS RETURN_CODEPAGE
  , p.TYPESTRINGUNITS AS RETURN_TYPESTRINGUNITS
  , p.STRINGUNITSLENGTH AS RETURN_STRINGUNITSLENGTH
  , p.LOCATOR AS RETURN_LOCATOR
  , r.*
FROM SYSCAT.ROUTINES r
LEFT JOIN SYSCAT.ROUTINEPARMS p
  ON p.ROUTINESCHEMA=r.ROUTINESCHEMA AND p.SPECIFICNAME=r.SPECIFICNAME
 AND p.ROWTYPE IN ('C','R') AND p.ORDINAL=0
 AND (p.ROWTYPE='C' OR NOT EXISTS (
   SELECT 1 FROM SYSCAT.ROUTINEPARMS declared_result
   WHERE declared_result.ROUTINESCHEMA=p.ROUTINESCHEMA AND declared_result.SPECIFICNAME=p.SPECIFICNAME
     AND declared_result.ROWTYPE='C' AND declared_result.ORDINAL=0))
WHERE r.ROUTINEMODULEID IS NULL
  AND ROUTINETYPE='F'
  /*if isNotEmpty(schemaName) */
  AND rtrim(r.ROUTINESCHEMA) IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(functionName) */
  AND rtrim(r.ROUTINENAME) IN /*functionName*/('%')
  /*end*/
  AND (rtrim(r.LANGUAGE) <>'' OR r.ORIGIN IN ('M', 'U'))
ORDER BY r.ROUTINESCHEMA, r.ROUTINENAME, r.SPECIFICNAME
WITH UR
