SELECT
  d.DOMAIN_CATALOG
, d.DOMAIN_SCHEMA
, d.DOMAIN_NAME
, CAST('YES' AS VARCHAR) AS IS_NULLABLE
, d.DOMAIN_DEFAULT AS COLUMN_DEFAULT
, COALESCE(d.DECLARED_DATA_TYPE, d.DATA_TYPE) AS TYPE_NAME
, COALESCE(
    d.CHARACTER_MAXIMUM_LENGTH
  , d.NUMERIC_PRECISION
  , d.DATETIME_PRECISION
  ) AS PRECISION
, d.NUMERIC_SCALE AS SCALE
, (
    SELECT LISTAGG(
        '(' || cc.CHECK_CLAUSE || ')'
      , ' AND '
    ) WITHIN GROUP (ORDER BY dc.CONSTRAINT_NAME)
    FROM INFORMATION_SCHEMA.DOMAIN_CONSTRAINTS dc
    JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS cc
      ON  dc.CONSTRAINT_CATALOG = cc.CONSTRAINT_CATALOG
      AND dc.CONSTRAINT_SCHEMA = cc.CONSTRAINT_SCHEMA
      AND dc.CONSTRAINT_NAME = cc.CONSTRAINT_NAME
    WHERE dc.DOMAIN_CATALOG = d.DOMAIN_CATALOG
      AND dc.DOMAIN_SCHEMA = d.DOMAIN_SCHEMA
      AND dc.DOMAIN_NAME = d.DOMAIN_NAME
  ) AS CHECK_CONSTRAINT
, CAST(NULL AS VARCHAR) AS "SQL"
, d.DOMAIN_ON_UPDATE
, d.REMARKS
FROM INFORMATION_SCHEMA.DOMAINS d
WHERE TRUE
  /*if isNotEmpty(catalogName)*/
  AND d.DOMAIN_CATALOG IN /*catalogName*/('%')
  /*end*/
  /*if isNotEmpty(schemaName)*/
  AND d.DOMAIN_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(domainName)*/
  AND d.DOMAIN_NAME IN /*domainName*/('%')
  /*end*/
ORDER BY d.DOMAIN_CATALOG, d.DOMAIN_SCHEMA, d.DOMAIN_NAME
