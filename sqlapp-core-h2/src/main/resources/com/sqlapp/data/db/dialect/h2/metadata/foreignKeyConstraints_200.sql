SELECT
  pk_tc.TABLE_CATALOG AS PKTABLE_CATALOG
, pk_tc.TABLE_SCHEMA AS PKTABLE_SCHEMA
, pk_tc.TABLE_NAME AS PKTABLE_NAME
, pk_kcu.COLUMN_NAME AS PKCOLUMN_NAME
, fk_tc.TABLE_CATALOG AS FKTABLE_CATALOG
, fk_tc.TABLE_SCHEMA AS FKTABLE_SCHEMA
, fk_tc.TABLE_NAME AS FKTABLE_NAME
, fk_kcu.COLUMN_NAME AS FKCOLUMN_NAME
, fk_tc.CONSTRAINT_NAME AS FK_NAME
, pk_tc.CONSTRAINT_NAME AS PK_NAME
, fk_kcu.ORDINAL_POSITION
, CASE rc.UPDATE_RULE
    WHEN 'CASCADE' THEN 0
    WHEN 'RESTRICT' THEN 1
    WHEN 'SET NULL' THEN 2
    WHEN 'SET DEFAULT' THEN 4
    ELSE 3
  END AS UPDATE_RULE
, CASE rc.DELETE_RULE
    WHEN 'CASCADE' THEN 0
    WHEN 'RESTRICT' THEN 1
    WHEN 'SET NULL' THEN 2
    WHEN 'SET DEFAULT' THEN 4
    ELSE 3
  END AS DELETE_RULE
, CASE
    WHEN fk_tc.IS_DEFERRABLE <> 'YES' THEN 7
    WHEN fk_tc.INITIALLY_DEFERRED = 'YES' THEN 5
    ELSE 6
  END AS DEFERRABILITY
FROM INFORMATION_SCHEMA.REFERENTIAL_CONSTRAINTS rc
JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS fk_tc
  ON  rc.CONSTRAINT_CATALOG = fk_tc.CONSTRAINT_CATALOG
  AND rc.CONSTRAINT_SCHEMA = fk_tc.CONSTRAINT_SCHEMA
  AND rc.CONSTRAINT_NAME = fk_tc.CONSTRAINT_NAME
JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE fk_kcu
  ON  fk_tc.CONSTRAINT_CATALOG = fk_kcu.CONSTRAINT_CATALOG
  AND fk_tc.CONSTRAINT_SCHEMA = fk_kcu.CONSTRAINT_SCHEMA
  AND fk_tc.CONSTRAINT_NAME = fk_kcu.CONSTRAINT_NAME
JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS pk_tc
  ON  rc.UNIQUE_CONSTRAINT_CATALOG = pk_tc.CONSTRAINT_CATALOG
  AND rc.UNIQUE_CONSTRAINT_SCHEMA = pk_tc.CONSTRAINT_SCHEMA
  AND rc.UNIQUE_CONSTRAINT_NAME = pk_tc.CONSTRAINT_NAME
JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE pk_kcu
  ON  pk_tc.CONSTRAINT_CATALOG = pk_kcu.CONSTRAINT_CATALOG
  AND pk_tc.CONSTRAINT_SCHEMA = pk_kcu.CONSTRAINT_SCHEMA
  AND pk_tc.CONSTRAINT_NAME = pk_kcu.CONSTRAINT_NAME
  AND fk_kcu.POSITION_IN_UNIQUE_CONSTRAINT =
      pk_kcu.ORDINAL_POSITION
WHERE TRUE
  /*if isNotEmpty(catalogName)*/
  AND pk_tc.TABLE_CATALOG IN /*catalogName*/('%')
  /*end*/
  /*if isNotEmpty(schemaName)*/
  AND pk_tc.TABLE_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND pk_tc.TABLE_NAME IN /*tableName*/('%')
  /*end*/
  /*if isNotEmpty(columnName)*/
  AND pk_kcu.COLUMN_NAME IN /*columnName*/('%')
  /*end*/
ORDER BY pk_tc.TABLE_CATALOG, pk_tc.TABLE_SCHEMA, pk_tc.TABLE_NAME,
  fk_tc.CONSTRAINT_NAME, fk_kcu.ORDINAL_POSITION
