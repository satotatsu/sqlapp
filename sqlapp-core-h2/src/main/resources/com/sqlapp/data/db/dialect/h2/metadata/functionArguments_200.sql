SELECT
  r.ROUTINE_CATALOG AS ALIAS_CATALOG
, r.ROUTINE_SCHEMA AS ALIAS_SCHEMA
, r.ROUTINE_NAME AS ALIAS_NAME
, r.SPECIFIC_NAME
, p.PARAMETER_NAME AS COLUMN_NAME
, p.ORDINAL_POSITION AS POS
, p.PARAMETER_MODE
, p.IS_RESULT
, 'TRUE' AS NULLABLE
, COALESCE(
    p.CHARACTER_MAXIMUM_LENGTH
  , p.NUMERIC_PRECISION
  , p.DATETIME_PRECISION
  ) AS PRECISION
, p.NUMERIC_SCALE AS SCALE
, COALESCE(p.DECLARED_DATA_TYPE, p.DATA_TYPE) AS TYPE_NAME
FROM INFORMATION_SCHEMA.PARAMETERS p
JOIN INFORMATION_SCHEMA.ROUTINES r
  ON  p.SPECIFIC_CATALOG = r.SPECIFIC_CATALOG
  AND p.SPECIFIC_SCHEMA = r.SPECIFIC_SCHEMA
  AND p.SPECIFIC_NAME = r.SPECIFIC_NAME
WHERE r.ROUTINE_TYPE = 'FUNCTION'
  /*if isNotEmpty(catalogName)*/
  AND r.ROUTINE_CATALOG IN /*catalogName*/('%')
  /*end*/
  /*if isNotEmpty(schemaName)*/
  AND r.ROUTINE_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(routineName) */
  AND r.ROUTINE_NAME IN /*routineName*/('%')
  /*end*/
ORDER BY r.ROUTINE_CATALOG, r.ROUTINE_SCHEMA, r.ROUTINE_NAME,
  r.SPECIFIC_NAME, p.ORDINAL_POSITION
