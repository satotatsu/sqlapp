SELECT
  tc.CONSTRAINT_CATALOG
, tc.CONSTRAINT_SCHEMA
, tc.CONSTRAINT_NAME
, tc.CONSTRAINT_TYPE
, tc.TABLE_CATALOG
, tc.TABLE_SCHEMA
, tc.TABLE_NAME
, tc.REMARKS
, kcu.COLUMN_NAME
, kcu.ORDINAL_POSITION
, FALSE AS IS_GENERATED
, 'ASC' AS ASC_OR_DESC
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu
  ON  tc.CONSTRAINT_CATALOG = kcu.CONSTRAINT_CATALOG
  AND tc.CONSTRAINT_SCHEMA = kcu.CONSTRAINT_SCHEMA
  AND tc.CONSTRAINT_NAME = kcu.CONSTRAINT_NAME
WHERE tc.CONSTRAINT_TYPE IN ('UNIQUE', 'PRIMARY KEY')
  /*if isNotEmpty(catalogName)*/
  AND tc.CONSTRAINT_CATALOG IN /*catalogName*/('%')
  /*end*/
  /*if isNotEmpty(schemaName)*/
  AND tc.CONSTRAINT_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(constraintName)*/
  AND tc.CONSTRAINT_NAME IN /*constraintName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND tc.TABLE_NAME IN /*tableName*/('%')
  /*end*/
ORDER BY tc.CONSTRAINT_CATALOG, tc.CONSTRAINT_SCHEMA, tc.TABLE_NAME,
  tc.CONSTRAINT_TYPE, tc.CONSTRAINT_NAME, kcu.ORDINAL_POSITION
