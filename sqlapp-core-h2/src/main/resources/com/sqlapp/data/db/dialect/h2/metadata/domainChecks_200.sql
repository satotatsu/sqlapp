SELECT dc.DOMAIN_CATALOG, dc.DOMAIN_SCHEMA, dc.DOMAIN_NAME, dc.CONSTRAINT_NAME, cc.CHECK_CLAUSE
FROM INFORMATION_SCHEMA.DOMAIN_CONSTRAINTS dc
JOIN INFORMATION_SCHEMA.CHECK_CONSTRAINTS cc
ON dc.CONSTRAINT_CATALOG=cc.CONSTRAINT_CATALOG AND dc.CONSTRAINT_SCHEMA=cc.CONSTRAINT_SCHEMA AND dc.CONSTRAINT_NAME=cc.CONSTRAINT_NAME
WHERE TRUE
/*if isNotEmpty(catalogName)*/
AND dc.DOMAIN_CATALOG IN /*catalogName*/('%')
/*end*/
/*if isNotEmpty(schemaName)*/
AND dc.DOMAIN_SCHEMA IN /*schemaName*/('%')
/*end*/
/*if isNotEmpty(domainName)*/
AND dc.DOMAIN_NAME IN /*domainName*/('%')
/*end*/
ORDER BY dc.DOMAIN_CATALOG, dc.DOMAIN_SCHEMA, dc.DOMAIN_NAME, dc.CONSTRAINT_NAME
