SELECT
  c.TABLE_CATALOG
, c.TABLE_SCHEMA
, c.TABLE_NAME
, c.COLUMN_NAME
, c.ORDINAL_POSITION
, CASE WHEN c.IS_NULLABLE = 'YES' THEN 1 ELSE 0 END AS NULLABLE
, c.COLUMN_DEFAULT
, COALESCE(
    c.DOMAIN_NAME
  , c.DECLARED_DATA_TYPE
  , c.DATA_TYPE
  ) AS TYPE_NAME
, c.CHARACTER_MAXIMUM_LENGTH
, c.CHARACTER_OCTET_LENGTH
, c.NUMERIC_SCALE
, CAST(NULL AS VARCHAR) AS SEQUENCE_NAME
, c.COLLATION_NAME
, CAST(NULL AS VARCHAR) AS CHECK_CONSTRAINT
, c.REMARKS
, c.IS_IDENTITY
, c.IDENTITY_START
, c.IDENTITY_INCREMENT
, c.IDENTITY_MAXIMUM
, c.IDENTITY_MINIMUM
, c.IDENTITY_CYCLE
, c.IS_GENERATED
, c.GENERATION_EXPRESSION
, c.COLUMN_ON_UPDATE
FROM INFORMATION_SCHEMA.COLUMNS c
WHERE TRUE
  /*if isNotEmpty(catalogName)*/
  AND c.TABLE_CATALOG IN /*catalogName*/('%')
  /*end*/
  /*if isNotEmpty(schemaName)*/
  AND c.TABLE_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(tableName)*/
  AND c.TABLE_NAME IN /*tableName*/('%')
  /*end*/
  /*if isNotEmpty(columnName)*/
  AND c.COLUMN_NAME IN /*columnName*/('%')
  /*end*/
ORDER BY c.TABLE_CATALOG, c.TABLE_SCHEMA, c.TABLE_NAME, c.ORDINAL_POSITION
