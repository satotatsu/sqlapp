package com.sqlapp.data.db.dialect.h2.sql;

import static org.junit.jupiter.api.Assertions.*;

import java.sql.DriverManager;

import org.junit.jupiter.api.Test;

import com.sqlapp.data.db.datatype.AbstractLengthType;
import com.sqlapp.data.db.datatype.DataType;
import com.sqlapp.data.db.dialect.Dialect;
import com.sqlapp.data.db.dialect.DialectResolver;
import com.sqlapp.data.db.sql.SqlType;
import com.sqlapp.data.schemas.Column;
import com.sqlapp.data.schemas.IdentityGenerationType;
import com.sqlapp.data.schemas.Table;
import com.sqlapp.data.schemas.Trigger;
import com.sqlapp.data.schemas.UniqueConstraint;

class H2DialectDefaultsTest {
	private static final Dialect H2_14 = DialectResolver.getInstance().getDialect("H2", 1, 4, 200);
	private static final Dialect H2_21 = DialectResolver.getInstance().getDialect("H2", 2, 1, 214);
	private static final Dialect H2_23 = DialectResolver.getInstance().getDialect("H2", 2, 3, 232);

	@Test
	void unspecifiedIdentityGenerationIsByDefault() throws Exception {
		var table = new Table("T");
		table.getColumns().add(new Column("ID").setDataType(DataType.INT).setIdentity(true));
		String sql = H2_23.createSqlFactoryRegistry().createSql(table, SqlType.CREATE).get(0).getSqlText();
		assertTrue(sql.contains("GENERATED BY DEFAULT AS IDENTITY"), sql);
		try (var connection = DriverManager.getConnection("jdbc:h2:mem:");
				var statement = connection.createStatement()) {
			statement.execute(sql);
			statement.execute("INSERT INTO T(ID) VALUES(10)");
		}
		table.getColumns().get("ID").setIdentityGenerationType(IdentityGenerationType.Always);
		assertTrue(H2_23.createSqlFactoryRegistry().createSql(table, SqlType.CREATE).get(0).getSqlText()
				.contains("GENERATED ALWAYS AS IDENTITY"));
	}

	@Test
	void identityWithOnUpdateIsRejected() {
		var table = new Table("T");
		table.getColumns().add(new Column("ID").setDataType(DataType.INT).setIdentity(true).setOnUpdate("1"));
		assertThrows(IllegalArgumentException.class,
				() -> H2_23.createSqlFactoryRegistry().createSql(table, SqlType.CREATE));
	}

	@Test
	void defaultUniqueNullTreatmentIsAcceptedBeforeH2_22() {
		var table = new Table("T");
		table.getColumns().add(new Column("A").setDataType(DataType.INT));
		var unique = new UniqueConstraint("U", false, table.getColumns().get("A"));
		unique.getSpecifics().put("h2.nullsDistinct", "YES");
		table.getConstraints().add(unique);
		String sql = H2_21.createSqlFactoryRegistry().createSql(table, SqlType.CREATE).get(0).getSqlText();
		assertFalse(sql.contains("NULLS"), sql);
		assertTrue(H2_23.createSqlFactoryRegistry().createSql(table, SqlType.CREATE).get(0).getSqlText()
				.contains("UNIQUE NULLS DISTINCT"));
	}

	@Test
	void stringLengthLimitsFollowTheVersion() {
		for (var type : new DataType[] { DataType.CHAR, DataType.NCHAR, DataType.NVARCHAR, DataType.VARCHAR }) {
			assertEquals(type, H2_14.getDbDataTypes().getDbType(type, 5000L).getDataType(), type.name());
			assertEquals(type, H2_23.getDbDataTypes().getDbType(type, 5000L).getDataType(), type.name());
			assertEquals(maxLength(H2_14, DataType.VARCHAR), maxLength(H2_14, type), type.name());
			assertEquals(1_000_000_000L, maxLength(H2_23, type), type.name());
		}
		for (var type : new DataType[] { DataType.BINARY, DataType.VARBINARY })
			assertEquals(1_000_000_000L, maxLength(H2_23, type), type.name());
	}

	private static long maxLength(Dialect dialect, DataType type) {
		return ((AbstractLengthType<?>) dialect.getDbDataTypes().getDbType(type)).getMaxLength();
	}

	@Test
	void triggerWithoutOrientationUsesTheNativeDefault() {
		var trigger = new Trigger("TR");
		trigger.setTableName("T");
		trigger.setActionTiming("AFTER");
		trigger.getEventManipulation().add("INSERT");
		trigger.setClassName("example.Trigger");
		String sql = H2_23.createSqlFactoryRegistry().createSql(trigger, SqlType.CREATE).get(0).getSqlText();
		assertFalse(sql.contains("FOR EACH"), sql);
		trigger.setActionOrientation("ROW");
		assertTrue(H2_23.createSqlFactoryRegistry().createSql(trigger, SqlType.CREATE).get(0).getSqlText()
				.contains("FOR EACH ROW"));
	}

	@Test
	void undecoratedCommentDoesNotRequireASchema() {
		var table = new Table("T").setRemarks("note");
		var registry = H2_23.createSqlFactoryRegistry();
		registry.getOptions().setDecorateSchemaName(false);
		assertEquals("COMMENT ON TABLE T IS 'note'",
				registry.createSql(table, SqlType.SET_COMMENT).get(0).getSqlText());
		var column = new Column("C").setRemarks("c");
		table.getColumns().add(column);
		assertEquals("COMMENT ON COLUMN T.C IS 'c'",
				registry.createSql(column, SqlType.SET_COMMENT).get(0).getSqlText());
	}
}
