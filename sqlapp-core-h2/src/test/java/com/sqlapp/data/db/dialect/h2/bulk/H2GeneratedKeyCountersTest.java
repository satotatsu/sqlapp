package com.sqlapp.data.db.dialect.h2.bulk;

import static org.junit.jupiter.api.Assertions.*;

import java.math.BigInteger;
import java.sql.Connection;
import java.sql.DriverManager;

import org.junit.jupiter.api.Test;

import com.sqlapp.data.schemas.Column;
import com.sqlapp.data.schemas.Table;
import com.sqlapp.jdbc.bulk.GeneratedKeyCounters;
import com.sqlapp.jdbc.bulk.GeneratedKeyCounters.Action;

class H2GeneratedKeyCountersTest {
	@Test
	void raisesTheCounterPastImportedKeys() throws Exception {
		try (var connection = DriverManager.getConnection("jdbc:h2:mem:")) {
			execute(connection, "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, V INT)");
			execute(connection, "INSERT INTO T(ID, V) VALUES (10, 1), (50, 2)");
			var result = GeneratedKeyCounters.synchronize(connection, table(), id(null), null, false);
			assertEquals(Action.RESTARTED, result.action(), result.toString());
			assertEquals(BigInteger.valueOf(51), result.next());
			execute(connection, "INSERT INTO T(V) VALUES (3)");
			assertEquals(51, single(connection, "SELECT ID FROM T WHERE V = 3"));
			// A second run finds the counter already safe and never moves it back.
			assertEquals(Action.ALREADY_SAFE,
					GeneratedKeyCounters.synchronize(connection, table(), id(null), 20L, false).action());
		}
	}

	@Test
	void usesTheSourceNextValueAndTheIncrement() throws Exception {
		try (var connection = DriverManager.getConnection("jdbc:h2:mem:")) {
			execute(connection,
					"CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY (INCREMENT BY 5) PRIMARY KEY, V INT)");
			execute(connection, "INSERT INTO T(ID, V) VALUES (21, 1)");
			var result = GeneratedKeyCounters.synchronize(connection, table(), id(5L), 100L, false);
			assertEquals(BigInteger.valueOf(100), result.next());
			execute(connection, "INSERT INTO T(V) VALUES (2)");
			assertEquals(100, single(connection, "SELECT ID FROM T WHERE V = 2"));
			assertEquals(BigInteger.valueOf(105),
					GeneratedKeyCounters.synchronize(connection, table(), id(5L), null, false).before());
		}
	}

	@Test
	void columnsWithoutAGeneratorAreReported() throws Exception {
		try (var connection = DriverManager.getConnection("jdbc:h2:mem:")) {
			execute(connection, "CREATE TABLE T(ID INT PRIMARY KEY, V INT)");
			execute(connection, "INSERT INTO T VALUES (1, 1)");
			assertEquals(Action.NO_GENERATOR,
					GeneratedKeyCounters.synchronize(connection, table(), id(null), null, false).action());
		}
	}

	@Test
	void emptyTablesWithoutASourceValueAreLeftAlone() throws Exception {
		try (var connection = DriverManager.getConnection("jdbc:h2:mem:")) {
			execute(connection, "CREATE TABLE T(ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, V INT)");
			assertEquals(Action.ALREADY_SAFE,
					GeneratedKeyCounters.synchronize(connection, table(), id(null), null, false).action());
		}
	}

	private static Table table() {
		return new Table("T").setSchemaName("PUBLIC");
	}

	private static Column id(Long step) {
		var column = new Column("ID").setIdentity(true);
		if (step != null)
			column.setIdentityStep(step);
		return column;
	}

	private static void execute(Connection connection, String sql) throws Exception {
		try (var statement = connection.createStatement()) {
			statement.execute(sql);
		}
	}

	private static long single(Connection connection, String sql) throws Exception {
		try (var statement = connection.createStatement(); var rows = statement.executeQuery(sql)) {
			rows.next();
			return rows.getLong(1);
		}
	}
}
