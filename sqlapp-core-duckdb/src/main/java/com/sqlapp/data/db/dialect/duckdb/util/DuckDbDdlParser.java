package com.sqlapp.data.db.dialect.duckdb.util;

import java.util.ArrayList;
import java.util.Collections;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Parses the canonical DDL that DuckDB stores in {@code duckdb_tables().sql}
 * and {@code duckdb_indexes().sql}.
 * <p>
 * DuckDB does not expose generated-column flags (before 2.0) or index key lists
 * in a structured catalog column, but the stored DDL is regenerated by DuckDB
 * in a stable form. The parser respects single-quoted strings, double-quoted
 * identifiers and nested parentheses.
 * </p>
 */
public final class DuckDbDdlParser {

	private static final String GENERATED_ALWAYS_AS = "GENERATED ALWAYS AS";

	private DuckDbDdlParser() {
	}

	/**
	 * Splits text by commas that are outside quotes and parentheses.
	 *
	 * @param text text to split
	 * @return trimmed elements
	 */
	public static List<String> splitTopLevel(final String text) {
		final List<String> result = new ArrayList<>();
		if (text == null) {
			return result;
		}
		int depth = 0;
		int start = 0;
		for (int i = 0; i < text.length(); i++) {
			final char c = text.charAt(i);
			if (c == '\'' || c == '"') {
				i = skipQuoted(text, i);
			} else if (c == '(') {
				depth++;
			} else if (c == ')') {
				depth--;
			} else if (c == ',' && depth == 0) {
				result.add(text.substring(start, i).trim());
				start = i + 1;
			}
		}
		final String last = text.substring(start).trim();
		if (!last.isEmpty() || !result.isEmpty()) {
			result.add(last);
		}
		return result;
	}

	/**
	 * Column attributes that DuckDB keeps only in the table DDL.
	 *
	 * @param name                 unquoted column name
	 * @param generationExpression expression of a generated column, or null
	 * @param collation            collation name, or null
	 */
	public record ColumnDdl(String name, String generationExpression, String collation) {
	}

	/**
	 * Returns the column attributes of a {@code CREATE TABLE} statement stored by
	 * DuckDB.
	 *
	 * @param createTableSql DDL from {@code duckdb_tables().sql}
	 * @return unquoted column name to column attributes, in column order
	 */
	public static Map<String, ColumnDdl> columns(final String createTableSql) {
		if (createTableSql == null) {
			return Collections.emptyMap();
		}
		final int open = indexOfTopLevel(createTableSql, '(', 0);
		if (open < 0) {
			return Collections.emptyMap();
		}
		final int close = matchingParenthesis(createTableSql, open);
		if (close < 0) {
			throw new IllegalArgumentException("Unbalanced DuckDB table DDL: " + createTableSql);
		}
		final Map<String, ColumnDdl> result = new LinkedHashMap<>();
		for (final String element : splitTopLevel(createTableSql.substring(open + 1, close))) {
			final int[] name = leadingIdentifier(element);
			if (name == null) {
				continue;
			}
			final String columnName = unquoteIdentifier(element.substring(0, name[1]));
			result.put(columnName,
					new ColumnDdl(columnName, generationExpression(element, name[1]), collation(element, name[1])));
		}
		return result;
	}

	/**
	 * Returns the generated columns of a {@code CREATE TABLE} statement stored by
	 * DuckDB.
	 *
	 * @param createTableSql DDL from {@code duckdb_tables().sql}
	 * @return unquoted column name to generation expression
	 */
	public static Map<String, String> generatedColumns(final String createTableSql) {
		final Map<String, String> result = new LinkedHashMap<>();
		for (final ColumnDdl column : columns(createTableSql).values()) {
			if (column.generationExpression() != null) {
				result.put(column.name(), column.generationExpression());
			}
		}
		return result;
	}

	private static String generationExpression(final String element, final int from) {
		final int generated = indexOfTopLevelKeyword(element, GENERATED_ALWAYS_AS, from);
		if (generated < 0) {
			return null;
		}
		final int exprOpen = indexOfTopLevel(element, '(', generated + GENERATED_ALWAYS_AS.length());
		final int exprClose = exprOpen < 0 ? -1 : matchingParenthesis(element, exprOpen);
		if (exprClose < 0) {
			throw new IllegalArgumentException("Unexpected DuckDB generated column: " + element);
		}
		return element.substring(exprOpen + 1, exprClose).trim();
	}

	private static String collation(final String element, final int from) {
		final int collate = indexOfTopLevelKeyword(element, "COLLATE", from);
		if (collate < 0) {
			return null;
		}
		int start = collate + "COLLATE".length();
		while (start < element.length() && Character.isWhitespace(element.charAt(start))) {
			start++;
		}
		if (start < element.length() && element.charAt(start) == '"') {
			final int end = skipQuoted(element, start);
			return unquoteIdentifier(element.substring(start, Math.min(end + 1, element.length())));
		}
		int end = start;
		while (end < element.length() && (isWordChar(element.charAt(end)) || element.charAt(end) == '.')) {
			end++;
		}
		return end > start ? element.substring(start, end) : null;
	}

	/**
	 * Returns the key elements of a {@code CREATE INDEX} statement stored by
	 * DuckDB.
	 *
	 * @param createIndexSql DDL from {@code duckdb_indexes().sql}
	 * @return key elements (column identifiers or expressions) as written in the
	 *         DDL
	 */
	public static List<String> indexKeys(final String createIndexSql) {
		if (createIndexSql == null) {
			return Collections.emptyList();
		}
		final int on = indexOfTopLevelKeyword(createIndexSql, "ON", 0);
		if (on < 0) {
			throw new IllegalArgumentException("Unexpected DuckDB index DDL: " + createIndexSql);
		}
		final int open = indexOfTopLevel(createIndexSql, '(', on + 2);
		final int close = open < 0 ? -1 : matchingParenthesis(createIndexSql, open);
		if (close < 0) {
			throw new IllegalArgumentException("Unexpected DuckDB index DDL: " + createIndexSql);
		}
		return splitTopLevel(createIndexSql.substring(open + 1, close));
	}

	/**
	 * Returns the unquoted identifier when the element is exactly one plain or
	 * double-quoted identifier.
	 *
	 * @param element key element
	 * @return identifier, or null when the element is an expression
	 */
	public static String identifierOrNull(final String element) {
		if (element == null) {
			return null;
		}
		final String text = element.trim();
		final int[] name = leadingIdentifier(text);
		if (name == null || name[1] != text.length()) {
			return null;
		}
		return unquoteIdentifier(text);
	}

	/**
	 * Parses the values of a DuckDB {@code ENUM('a', 'b')} type name.
	 *
	 * @param typeName type name from {@code duckdb_columns().data_type}
	 * @return values, or null when the type is not an inline ENUM
	 */
	public static List<String> enumValues(final String typeName) {
		if (typeName == null) {
			return null;
		}
		final String text = typeName.trim();
		if (!text.regionMatches(true, 0, "ENUM", 0, 4)) {
			return null;
		}
		final int open = text.indexOf('(');
		if (open < 0 || !text.substring(4, open).isBlank()) {
			return null;
		}
		final int close = matchingParenthesis(text, open);
		if (close != text.length() - 1) {
			return null;
		}
		final List<String> values = new ArrayList<>();
		for (final String element : splitTopLevel(text.substring(open + 1, close))) {
			if (element.length() < 2 || element.charAt(0) != '\'' || element.charAt(element.length() - 1) != '\'') {
				throw new IllegalArgumentException("Unexpected DuckDB ENUM value: " + element);
			}
			values.add(element.substring(1, element.length() - 1).replace("''", "'"));
		}
		return values;
	}

	private static String unquoteIdentifier(final String identifier) {
		final String text = identifier.trim();
		if (text.length() >= 2 && text.charAt(0) == '"' && text.charAt(text.length() - 1) == '"') {
			return text.substring(1, text.length() - 1).replace("\"\"", "\"");
		}
		return text;
	}

	/**
	 * @return {start, end} of a leading identifier, or null when the element starts
	 *         with a table constraint keyword or no identifier
	 */
	private static int[] leadingIdentifier(final String element) {
		if (element.isEmpty()) {
			return null;
		}
		if (element.charAt(0) == '"') {
			final int end = skipQuoted(element, 0);
			if (end >= element.length()) {
				return null;
			}
			return new int[] { 0, end + 1 };
		}
		int i = 0;
		while (i < element.length()) {
			final char c = element.charAt(i);
			if (Character.isLetterOrDigit(c) || c == '_' || c == '$') {
				i++;
			} else {
				break;
			}
		}
		if (i == 0 || Character.isDigit(element.charAt(0))) {
			return null;
		}
		final String word = element.substring(0, i).toUpperCase(Locale.ROOT);
		switch (word) {
		case "CONSTRAINT":
		case "PRIMARY":
		case "UNIQUE":
		case "CHECK":
		case "FOREIGN":
			return null;
		default:
			return new int[] { 0, i };
		}
	}

	private static int skipQuoted(final String text, final int start) {
		final char quote = text.charAt(start);
		int i = start + 1;
		while (i < text.length()) {
			if (text.charAt(i) == quote) {
				if (i + 1 < text.length() && text.charAt(i + 1) == quote) {
					i += 2;
					continue;
				}
				return i;
			}
			i++;
		}
		return text.length();
	}

	private static int indexOfTopLevel(final String text, final char target, final int from) {
		int depth = 0;
		for (int i = from; i < text.length(); i++) {
			final char c = text.charAt(i);
			if (c == '\'' || c == '"') {
				i = skipQuoted(text, i);
			} else if (c == target && depth == 0) {
				return i;
			} else if (c == '(') {
				depth++;
			} else if (c == ')') {
				depth--;
			}
		}
		return -1;
	}

	private static int indexOfTopLevelKeyword(final String text, final String keyword, final int from) {
		final String[] words = keyword.split(" ");
		int depth = 0;
		for (int i = from; i < text.length(); i++) {
			final char c = text.charAt(i);
			if (c == '\'' || c == '"') {
				i = skipQuoted(text, i);
			} else if (c == '(') {
				depth++;
			} else if (c == ')') {
				depth--;
			} else if (depth == 0 && isWordStart(text, i) && matchesWords(text, i, words)) {
				return i;
			}
		}
		return -1;
	}

	private static boolean isWordStart(final String text, final int i) {
		return i == 0 || !isWordChar(text.charAt(i - 1));
	}

	private static boolean isWordChar(final char c) {
		return Character.isLetterOrDigit(c) || c == '_' || c == '$';
	}

	private static boolean matchesWords(final String text, final int start, final String[] words) {
		int i = start;
		for (int w = 0; w < words.length; w++) {
			if (w > 0) {
				final int before = i;
				while (i < text.length() && Character.isWhitespace(text.charAt(i))) {
					i++;
				}
				if (i == before) {
					return false;
				}
			}
			final String word = words[w];
			if (!text.regionMatches(true, i, word, 0, word.length())) {
				return false;
			}
			i += word.length();
		}
		return i >= text.length() || !isWordChar(text.charAt(i));
	}

	private static int matchingParenthesis(final String text, final int open) {
		int depth = 0;
		for (int i = open; i < text.length(); i++) {
			final char c = text.charAt(i);
			if (c == '\'' || c == '"') {
				i = skipQuoted(text, i);
			} else if (c == '(') {
				depth++;
			} else if (c == ')') {
				depth--;
				if (depth == 0) {
					return i;
				}
			}
		}
		return -1;
	}
}
