SELECT
  t.TRIGGER_NAME
  , t.SCHEMA_NAME
  , t.OWNER
  , t.PROCEDURE_NAME
  , t.PROCEDURE_ARGS
  , t.ENABLED AS TRIGGER_ENABLED
  , s.SCHEDULE_NAME
  , s.ENABLED AS SCHEDULE_ENABLED
  , s.DATE_TIME_TYPE
  , s.DATE_TIME_STRING
FROM V_CATALOG.STORED_PROC_TRIGGERS t
INNER JOIN V_CATALOG.USER_SCHEDULES s
  ON s.SCHEMA_NAME=t.SCHEMA_NAME
  AND s.ATTACHED_TRIGGER=t.TRIGGER_NAME
WHERE 1=1
  /*if isNotEmpty(schemaName)*/
  AND t.SCHEMA_NAME IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(eventName)*/
  AND t.TRIGGER_NAME IN /*eventName*/('%')
  /*end*/
ORDER BY t.SCHEMA_NAME, t.TRIGGER_NAME
