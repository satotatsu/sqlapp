SELECT p.*
  , t.TABLE_SCHEMA AS TABLE_SCHEMA_NAME
  , t.TABLE_NAME
  , pc.PROJECTION_COLUMN_NAME
  , pc.COLUMN_POSITION
  , pc.SORT_POSITION
  , pc.DATA_TYPE
  , pc.ENCODING_TYPE
FROM V_CATALOG.PROJECTIONS p
LEFT JOIN V_CATALOG.TABLES t ON t.TABLE_ID=p.ANCHOR_TABLE_ID
LEFT JOIN V_CATALOG.PROJECTION_COLUMNS pc ON pc.PROJECTION_ID=p.PROJECTION_ID
WHERE 1=1
  /*if isNotEmpty(schemaName)*/
  AND p.PROJECTION_SCHEMA IN /*schemaName*/('%')
  /*end*/
  /*if isNotEmpty(projectionName)*/
  AND p.PROJECTION_NAME IN /*projectionName*/('%')
  /*end*/
ORDER BY p.PROJECTION_SCHEMA, p.PROJECTION_NAME, pc.COLUMN_POSITION
